// 编排提示 —— 把 plan.js 的契约**自动告诉 AI**，而不是指望工单作者去背（协-005）。
//
// 为什么需要它（首次跑 orchestrator 当场踩到）：
//   工单里写的是「输出 JSON 计划」，AI 于是输出了 `{"tickets": [...]}`。
//   拆解本身**完全正确**——两张子单、角色合法、验收标准客观、依赖关系对——
//   但 plan.js 只认 `tasks` 或 `任务`，于是整份计划被判不可用。
//
//   一个字段名的差异，报废一次 88 秒的真实调用。而且报错信息是
//   「未找到合法的 JSON 计划」，看不出是差在哪个键上。
//
// 根因不是 AI 不听话，是**契约只存在于代码里，没人告诉它**。
// 工单作者也不该被要求去读 plan.js 才能写一张 orchestrator 单。
//
// 处置：执行 orchestrator 工单时，由平台把契约拼进提示词。契约变了这里跟着变，
// 不需要去改每一张历史工单。
'use strict';

// 从 plan.js 的实际校验规则倒推出来的硬要求。改 plan.js 时**必须同步改这里**——
// 契约测试里有一条断言盯着两边不许漂移。
function 契约块(配置) {
  const 角色 = Object.keys((配置 && 配置.roles) || {});
  const 上限 = Number(((配置 || {}).orchestration || {}).maxTasks ?? 20);
  return [
    '',
    '---',
    '',
    '# 输出契约（平台自动附加，必须严格遵守）',
    '',
    '把计划输出成一段 JSON，用 ```json 代码块包裹。**顶层键必须叫 `tasks`**（不是 tickets、',
    '不是 items、不是 subtasks）——平台只认这一个名字，叫别的会被整份判为不可用。',
    '',
    '```json',
    '{',
    '  "summary": "一句话说明这个拆解的思路",',
    '  "tasks": [',
    '    {',
    '      "key": "唯一短标识，字母开头，只含字母数字下划线短横，最长 32 字符",',
    '      "title": "标题，不超过 100 字",',
    `      "role": "只能是：${角色.join(' / ') || 'backend / frontend / integrator / reviewer'}",`,
    '      "description": "范围说明（可选）",',
    '      "acceptance": ["客观可验证的验收标准，至少一条，不能为空"],',
    '      "doNot": ["明确不做什么（可选）"],',
    '      "dependsOn": ["依赖的其它 key（可选）"],',
    '      "writeScope": ["允许写入的文件或 glob（可选）"],',
    '      "needDeps": ["装依赖的目录（可选）；true 表示仓根"]',
    '    }',
    '  ]',
    '}',
    '```',
    '',
    // 协-038：这一段是 HW-7 实测换来的。工单里要求子单声明 needDeps，而契约块当时
    // 没提这个字段、plan.js 也不认——模型没地方放，就把它塞进了 acceptance 当勾选项。
    // 写下来了，但装依赖那步读的是 frontmatter，不是清单里的一行字：
    // 那批 5 张子单里有 4 张要跑命令，会一张不落地卡在「验不了」，每张烧掉一轮判官。
    '**`needDeps` 什么时候必须写**：子单的验收标准里只要有「跑构建 / 跑测试 / 跑 typecheck」',
    '这类命令，就必须声明它——隔离工作区是一次干净 checkout，**没有人在里面装过依赖**，',
    '不声明的话那些命令一条都跑不起来，判官只能给「验不了」，这张单白跑一轮。',
    '',
    '写的是**相对工作区根**的目录（`["tooling","services/api"]`），或 `true` 表示仓根。',
    '⚠ 如果验收命令是**扫全仓**的（monorepo 的 `typecheck` / `unit` 常常如此），',
    '要把所有会被扫到的包**列全**，不能只列这张单改到的那个——少一个，命令就跑不完。',
    '',
    '硬性规则（违反任何一条，整份计划会被内核打回）：',
    `- 子任务数量 1～${上限} 张；`,
    '- `key`：字母开头，只含字母数字下划线短横，**最长 32 字符**（超一个字符整份计划就被打回）；',
    '- `key` 不得重复，`dependsOn` 只能引用同一份计划里已出现的 key，不能依赖自己；',
    '- 依赖关系不能成环；',
    '- 每张单**必须**有非空的 `acceptance`——没有客观验收标准的单，做完了也没法判是否做对；',
    '- `reviewer` 是只读角色：不得声明 `writeScope`，也不得要求 coding/backend/frontend 能力。',
    '  要实现评审功能请用 `backend`，要写集成测试或报告请用 `integrator`；',
    '- 不要自己动手改任何文件，你只出计划。',
  ].join('\n');
}

// 只给 orchestrator 角色附加。别的角色附上去是噪音，还会诱导它们去输出计划。
function 拼提示(配置, 角色, 正文) {
  if (String(角色 || '') !== 'orchestrator') return { 提示: 正文, 附加: false };
  return { 提示: String(正文 || '') + 契约块(配置), 附加: true };
}

module.exports = { 契约块, 拼提示 };
