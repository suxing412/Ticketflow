// 工单模板 —— 让「写得出好验收标准」成为默认，而不是靠人自觉（协-005）。
//
// 为什么需要它：验收标准写不好 → 判官判不过 → 回炉重跑 → 再判不过。
// 每一轮都是真实付费。与其等巡检报「反复回炉」，不如在建单那一刻就把结构给对。
//
// ⚠ 一处必须说准的事实：R-1 被判不过三次，我一度以为是「它的验收标准自相矛盾」。
// 核对原文后不成立——它那两条（「有非空文字输出」「未产生任何文件改动」）
// 各自客观可验，本模块的体检也放行。真正的矛盾在**我调质检时传的
// `变更文件: ['index.js']`** 与第二条冲突：那是测试数据的错，不是工单的错。
//
// 记在这里是因为这类误判很危险：把「用错了工具」归咎成「单子写得烂」，
// 会让人去改一张本来没问题的单，而真正的错误原封不动。
//
// 模板能防住的是最常见的那类——**标准写得含糊，判官只能靠猜**。
// 它防不住「标准客观但要求本身错了」，更防不住调用方喂错参数。
