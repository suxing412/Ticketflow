// 生成一张单的正文骨架
function 取(角色) {
  const k = String(角色 || '').trim();
  const g = 骨架[k];
  if (!g) {
    return {
      有: false,
      正文: ['## 范围', '', '## 不要做', '- ', '', '## 验收标准', '- [ ] ', '', '## 写入范围', '- '].join('\n'),
      说明: `没有 ${k || '(空)'} 的模板，给了通用骨架`,
    };
  }
  return { 有: true, 正文: g.正文.join('\n'), 说明: g.说明 };
}

// 验收标准体检。**不拦不改**，只挑毛病——
// 自动改写别人的验收标准是越界：标准是人对「做对了」的定义，机器无权重写。
function 体检(正文, fm = {}) {
  const 文 = String(正文 || '');
  const 病 = [];
  const 验收段 = (文.match(/##\s*验收标准\s*\r?\n([\s\S]*?)(?=\r?\n##|$)/) || [])[1] || '';
  const 条 = 验收段.split(/\r?\n/).map((l) => l.replace(/^\s*[-*]\s*\[[ xX]\]\s*/, '').trim()).filter(Boolean);

  if (!验收段.trim()) 病.push({ 级: '急', 说: '没有「## 验收标准」一节——判官无从判起，这张单跑完也不知道算不算做对' });
  else if (!条.length) 病.push({ 级: '急', 说: '验收标准一条都没写' });

  // 顺序有讲究：主观词要排在「过短」之前判。
  // 「实现正确」只有 4 个字，两条规则都命中——但告诉人「这是主观词」比
  // 「这条太短」有用得多：前者指出病根，后者只描述症状（写长点也还是没法验）。
  for (const c of 条) {
    if (/^<.*>$/.test(c) || /^（.*）$/.test(c)) {
      病.push({ 级: '急', 说: `验收标准还是模板占位符没填：「${c.slice(0, 30)}」` });
    } else if (/正确|合理|良好|优化|完善|健壮|清晰|规范/.test(c) && !/`|=|返回|退出码|文件|行为/.test(c)) {
      // 这类词判官没法验——它们描述的是感受不是事实
      病.push({ 级: '常', 说: `验收标准含主观词且无客观依据，判官只能靠猜：「${c.slice(0, 30)}」` });
    } else if (c.length < 6) {
      病.push({ 级: '常', 说: `验收标准过短，判官可能理解不了：「${c}」` });
    }
  }
  // 只提示代码单。文档/评审单即使写了某条检查命令，也不该被推定必须有项目总闸。
  const 是代码单 = String((fm || {}).产出物类型 || '').trim() === '代码';
  const 提到子闸 = /(?:lint(?::code)?|format:check|typecheck|\bunit\b|\bcontract\b|\bbuild\b|格式检查|代码检查|类型检查|单元测试|契约测试)/i.test(验收段);
  const 有总闸 = /质量总闸|(?:npm|pnpm|yarn|bun)(?:\s+--prefix\s+\S+)?\s+(?:run\s+)?quality(?:\s|`|$)/i.test(验收段);
  if (是代码单 && 提到子闸 && !有总闸) {
    病.push({
      级: '常',
      说: '代码单的验收标准列了质量子命令，却没有项目质量总闸；容易漏掉格式检查、代码检查、类型检查或测试中的另一半',
    });
  }
  return { 条数: 条.length, 病, ok: !病.some((x) => x.级 === '急') };
}

module.exports = { 取, 体检, 骨架 };
