// 质检 —— 在途干完之后，由**另一个 Provider** 判一次（协-004）。
//
// 为什么必须有：在途干完直接判完成，等于没有人验收——AI 说自己做完了就算做完。
// 这在真花钱的产线上不成立：它可能只改了一半、可能改错了地方、可能什么都没干
// 但输出了一段像模像样的报告。
//
// 纯计算：组装质检提示词、归一判官结论、决定下一步。不起进程、不碰文件。
// 真正拉起判官的是执行器，落盘的是工单库。
'use strict';

const 评审意见 = require('./review-opinion');
const 加固 = require('./执行加固');

// 要不要送检。默认要——**跳过质检必须是显式决定**。
// 反过来（默认不检、要检才配）会让「没配 = 没人验收」，而那正是最危险的默认。
function 需质检(配置, 工单) {
  const 段 = (配置.质检 || {});
  if (段.启用 === false) return { 要: false, 因: '配置 质检.启用 = false，全局关闭' };
  const fm = 工单.fm || {};
  if (fm.QA === '关' || fm.质检 === '关') return { 要: false, 因: `工单 ${工单.id} 显式声明 QA:关` };
  const 免 = Array.isArray(段.免检角色) ? 段.免检角色 : [];
  const 角色 = fm.role || fm.职能 || '';
  if (免.includes(角色)) return { 要: false, 因: `角色 ${角色} 在免检名单内` };
  // reviewer 自己的产出不再送检——否则判官判判官，无穷递归。
  if (角色 === 'reviewer') return { 要: false, 因: 'reviewer 的产出不再送检（判官判判官会无限递归）' };
  return { 要: true, 因: null };
}

// 质检提示词：把工单的验收标准和实际改动摆给判官看。
// **不把执行方的输出原样喂进去**——那会让判官读到「我已完成」这类自述而被带偏。
// 判官该看的是客观材料：要求是什么、实际改了什么。
function 质检提示词(工单, 变更文件, 选项 = {}) {
  const fm = 工单.fm || {};
  return [
    '你是质检员。判断下面这张工单是否达到了它自己声明的验收标准。',
    '',
    // 判官得知道去哪儿看代码。不说的话它只能猜，而猜错的方向是致命的：
    // 在一个它以为空的目录里找不到文件，就会断定「什么都没做」——
    // 实测踩过（QA-VERIFY：实现已合进主线且功能正确，仍被判不过）。
    选项.审阅区
      ? '**代码就在你的当前工作目录里**，是这张单交付时那个提交的快照。直接读文件核对，不要凭工单描述想象。'
      : '⚠ 本次**没有给你代码视图**，当前目录是空的。请只依据工单正文判断，'
        + '不要把「目录里找不到文件」当成「没有实现」——那只说明取材失败。',
    '',
    `## 工单 ${工单.id}：${fm.title || ''}`,
    '',
    工单.body || '',
    '',
    '## 实际改动的文件',
    // 「拿不到清单」和「确实一个文件都没改」是两回事，而这两句话对判官的含义
    // 完全相反：后者是判不过的铁证，前者只说明取材失败。
    // 原先两种情况都印成「（无文件改动）」，判官只能按铁证处理——
    // 首次真跑就是这么把一次已经合进 master 的实现判成不过的。
    (变更文件 && 变更文件.length)
      ? 变更文件.map((f) => `- ${f}`).join('\n')
      : '（**没有取到改动清单**——这不等于没改文件，可能是取材时工作区已被回收。'
        + '请以工单正文与你能看到的代码为准判断，不要仅凭这一行断定「什么都没做」。）',
    '',
    // 交付回执（协-029）：执行方自己说的「我跑了哪些命令、退出码多少」。
    //
    // 这段**不是**上面那条「不把执行方的输出原样喂进去」的例外，而是它的补充：
    // 那条防的是「我已完成」这类**自述结论**把判官带偏；这里给的是**可核对的事实**
    // （命令、退出码、测试通过数）。判官照样该自己去核，但至少现在有东西可核——
    // HW-4 第三轮判不过的理由就是「没有回执，无法验证三条命令的退出码」，
    // 而那些输出 agent 明明打过，是平台丢的（协-029 之前不落盘）。
    ...(选项.回执 ? [
      '## 执行方交付回执（他自己的说法，**需要你核对**，不是结论）',
      String(选项.回执).slice(0, 8000),
      '',
    ] : []),
    '## 你要输出的格式',
    '第一行必须是 `结论：通过`、`结论：不过` 或 `结论：验不了` 之一。',
    '',
    // 「活不对」和「我验不了」是两件事，处置南辕北辙：前者该返工，后者该修环境。
    // 混成一个「不过」的后果实测过——HW-4 因为工作区没装依赖被判不过两轮，
    // 每一轮都把单打回让 agent 重做，而代码根本没问题。
    '**什么时候用「验不了」**：你要核对的东西**这次拿不到**——比如验收标准要求跑命令，'
    + '而命令因为环境缺依赖、缺配置、没有网络而根本跑不起来；或者取材失败（看不到代码、拿不到改动清单）。'
    + '这不是被评审方的错，别把它判成「不过」：**不过 = 活不对，验不了 = 我没法判**，'
    + '两者的下一步完全不同（前者返工，后者修环境）。',
    '判得了就别用它——「验不了」不是拿不准时的中间档，拿不准该给「不过」并写清疑点。',
    '',
    '然后按需给出：',
    '## 阻断问题',
    '（不过的原因，逐条。通过则写「无」）',
    '## 验收证据',
    '（你据以判断的依据，逐条）',
    '',
    '只做判断，不要修改任何文件。',
  ].join('\n');
}

// 归一判官结果，并决定工单下一步。
//
// 判官失败 ≠ 被评审方不合格（加固②）：判官自己崩了、零输出、输出里找不到结论，
// 都是**判官的**问题，工单维持原状待重判，不能因此打回。
function 判定(判官退出码, 判官输出) {
  // 「验不了」先认（协-029）：它是**第三种结论**，不是「不过」的一个子类。
  //
  // 判不过 → 工单回待投让人返工；验不了 → 工单**留在质检**，该修的是环境。
  // 把后者当前者的后果实测过：HW-4 因为隔离工作区没装依赖被判不过两轮，
  // 每轮都把单打回重做，而代码根本没问题——返工修不好一个缺依赖的工作区。
  //
  // 位置在归类之前：加固.判官结果归类 只认「通过/不过/判官失败」三态，
  // 把验不了递进去会被当成「解析不出结论」→ 判官失败 → 维持原状待重判，
  // 那样表面上也不打回，但**原因就丢了**，人看到的是「判官抽风了」。
  if (/结论[:：]\s*验不了/.test(String(判官输出 || '')) && 判官退出码 === 0) {
    return {
      结论: '验不了',
      下一步: null,                       // 不流转：这张单没毛病，是环境不让判
      说明: '判官说它**验不了**（要核对的东西这次拿不到：缺依赖/缺配置/取材失败）。'
        + '工单留在质检态不打回——返工修不好一个跑不动命令的工作区。'
        + '先照判词把环境补上（多半是工单要声明 需要依赖），再点一次判。',
      意见: 评审意见.parse(判官输出, false),
    };
  }
  const 归类 = 加固.判官结果归类({
    退出码: 判官退出码,
    输出: 判官输出,
    解析出结论: /结论[:：]\s*(通过|不过)/.test(String(判官输出 || ''))
      ? /结论[:：]\s*通过/.test(String(判官输出 || ''))
      : null,
  });
  if (归类.类别 === '判官失败') {
    return { 结论: '判官失败', 下一步: null, 说明: 归类.说明, 意见: null };
  }
  const 意见 = 评审意见.parse(判官输出, 归类.类别 === '通过');
  return {
    结论: 归类.类别,
    下一步: 归类.类别 === '通过' ? '完成' : '待投',
    说明: 归类.类别 === '通过' ? '质检通过' : '质检不过，回待投重做（不是失败终态，同一张单可以再跑）',
    意见,
  };
}

// 判词作废 —— 判官在审阅区里动了它正在判的东西（协-034）。
//
// 协-034 把判官从「只读」放宽成「只在自己那个一次性审阅区内可写」，理由是
// tsc 要写 dist、vitest 要写 .vite-temp，只读沙箱下命令型验收**永远**跑不完。
// 但放宽的同时必须补上另一半：**「它没改它正在判的东西」这句话得查，不能靠 flag 让它自觉。**
//
// 查出来动了源码，判词一律作废，按判官失败处理——**不是判不过**：
// 被评审方没有任何过错，这次质检本身失效了，该做的是重判，不是返工。
// 归到「判官失败」这一档也顺带复用了既有的「不流转、维持原状」处置。
//
// 只吃 tracked 改动与非忽略新增（工作区服务的 /changes 就是这个语义）：
// dist/、node_modules/ 本来就在 .gitignore 里，构建产物不会误报成篡改。
function 作废(判, 篡改文件) {
  const 文件 = (篡改文件 || []).filter(Boolean);
  if (!文件.length) return 判;
  const 列 = 文件.slice(0, 10).map((f) => `- ${f}`).join('\n');
  return {
    结论: '判官失败',
    下一步: null,                         // 维持原状待重判：作废的是这次质检，不是这张单
    篡改: 文件,
    说明: `**判词作废**：判官在审阅区里改了 ${文件.length} 个受管文件——`
      + '而它的活是判，不是改。一个能改代码的判官给出的「通过」不构成验收：'
      + '它可能是把不过的地方顺手修好之后才判的过。\n' + 列
      + (文件.length > 10 ? `\n…（共 ${文件.length} 个）` : '')
      + '\n工单维持原状待重判。审阅区判完即 --force 收掉，这些改动没有落到任何地方。',
    // 意见留着：人要看它到底判了什么、改了什么，才好判断是恶意还是手滑。
    意见: 判 && 判.意见 ? 判.意见 : null,
    原结论: (判 && 判.结论) || null,
  };
}

module.exports = { 需质检, 质检提示词, 判定, 作废 };
