// 提示装配 —— 把「AI 干活前应该知道的一切」拼成一份提示词（协-005）。
//
// 此前执行器只喂工单正文。于是两件早就存在的东西一直没被用上：
//
//   ① 角色协议模板（角色协议模板/*.md）——出厂就在库里，六份，从没有人 require 过。
//      backend 那份写着「新增或修改逻辑必须带可运行测试」「不修改前端实现目录」，
//      这些约束不喂给 AI，它就只能靠猜。
//
//   ② 上一轮的质检意见——判不过会回待投重跑，但重跑时 AI **看不到上次为什么没过**。
//      同一个坑它会照踩不误，而每踩一次都是一次真实付费。
//      R-1 被判不过三次就是这么来的。
//
// 纯计算 + 只读文件。装配顺序有讲究，见下。
'use strict';

const fs = require('fs');
const path = require('path');

// 读角色协议。缺文件不报错——协议是增强不是前提，没有它工单照样能跑。
// 但**要如实告知没读到**：静默少喂一段约束，事后没人能从回执里看出来。
function 角色协议(平台根, 角色) {
  const 名 = String(角色 || '').trim();
  if (!名) return { 有: false, 文: '', 因: '工单没写角色' };
  const p = path.join(平台根, '角色协议模板', `${名}.md`);
  try {
    const 文 = fs.readFileSync(p, 'utf8').trim();
    return 文 ? { 有: true, 文, 来源: p } : { 有: false, 文: '', 因: `${名}.md 是空的` };
  } catch {
    return { 有: false, 文: '', 因: `没有 角色协议模板/${名}.md` };
  }
}

// 通用协议：所有角色都该遵守的那部分。
function 通用协议(平台根) {
  try {
    const 文 = fs.readFileSync(path.join(平台根, '角色协议模板', 'common.md'), 'utf8').trim();
    return 文 ? { 有: true, 文 } : { 有: false, 文: '' };
  } catch { return { 有: false, 文: '' }; }
}

// 上一轮的质检意见 → 重做要求。
//
// 措辞上刻意**不复述判官的全部原话**，只给阻断问题与证据：判官的行文里常有
// 「我先看一眼文件」这类过程叙述，喂回去会让下一轮的 AI 跟着复述过程而不是解决问题。
function 回炉要求(fm) {
  const 意 = (fm && fm.质检意见) || null;
  if (!意 || fm.质检结论 !== '不过') return { 有: false, 文: '' };
  const 行 = ['', '---', '', '# ⚠ 这张单上一轮**被判不过**，你是在重做', ''];
  if ((意.问题 || []).length) {
    行.push('## 上次的阻断问题（必须逐条解决）');
    for (const x of 意.问题) 行.push(`- ${x}`);
    行.push('');
  }
  if ((意.证据 || []).length) {
    行.push('## 判官当时看到的');
    for (const x of 意.证据) 行.push(`- ${x}`);
    行.push('');
  }
  行.push(`判官：${fm.质检判官 || '未知'}　时间：${fm.质检时间 || ''}`);
  行.push('');
  行.push('**先解决上面这些，再做别的。** 如果你认为某条阻断问题本身不成立'
    + '（比如验收标准自相矛盾），把理由写进产出，不要默默忽略它——'
    + '同一张单反复被判不过时，问题往往出在标准本身，那需要人来改单。');
  return { 有: true, 文: 行.join('\n') };
}

// 装配。顺序是有讲究的：
//   工单正文 → 角色协议 → 回炉要求
// 正文在最前：它是这次要干的事，最该被完整读到。
// 协议在中间：长期约束，读不读得仔细影响没那么大。
// 回炉要求在**最后**：LLM 对末尾内容的注意力更高，而「上次为什么没过」正是
// 这一轮最该优先解决的东西。
function 装配(平台根, 工单) {
  const fm = (工单 && 工单.fm) || {};
  const 角色 = fm.role || fm.职能 || '';
  const 段 = [String(工单.body || '')];
  const 记 = { 正文: true };

  const 通 = 通用协议(平台根);
  if (通.有) { 段.push('', '---', '', '# 通用协议', '', 通.文); 记.通用协议 = true; }

  const 协 = 角色协议(平台根, 角色);
  if (协.有) { 段.push('', '---', '', `# ${角色} 角色协议`, '', 协.文); 记.角色协议 = 角色; }
  else 记.角色协议缺 = 协.因;

  const 回 = 回炉要求(fm);
  if (回.有) { 段.push(回.文); 记.回炉要求 = true; }

  return { 提示: 段.join('\n'), 装配记录: 记 };
}

module.exports = { 装配, 角色协议, 通用协议, 回炉要求 };
