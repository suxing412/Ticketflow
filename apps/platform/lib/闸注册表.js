// 闸注册表 + 等我() —— 「现在欠人几笔」的唯一谓词（协-019）。
//
// 形制取自 studio 2026-08-20 的 gatereg（施工令-061 第二节），连同它换轴的理由一起抄：
// 他们的决策台原先问的是「哪些**工单**处于某几个状态」——判据轴是工单状态。
// 于是「不在工单目录里」的那些欠债（专项关账）**结构上就看不见**，当日欠 3 笔、页面显示 1 笔。
// 治法不是把队列写宽一点，是**把定义域从「状态」换成「闸」**：一条闸一个权威源，各查各的。
//
// platform 这边同病：工单状态只有六个（草稿/待投/在途/质检/完成/已归档），
// 而「订阅耗尽等你拍板要不要落 API 计费」这笔债根本不是工单状态——它住在执行器的
// 耗尽记录里。只看状态就永远看不见它。
//
// 抄过来的三条硬纪律：
//   ① **只读权威状态，严禁拿呼叫信箱当数据源**。通知是广播不是账本；拿广播当账本，
//      等于把漏报和重复写进地基（信箱本身还有静默窗去重，更不能当账用）。
//   ② 每笔带 gateKey = 闸号:实体id，**按 key 幂等**。同一实体同一闸扫出几次都只算一笔。
//   ③ **闸分两型**。响应型：有队列在等你落笔（草稿待投出、卡死待分诊…），这类才进 等我()。
//      发起型：没有队列，是你想做才做的动作（建单、归档、轮换令牌）。它们同样要登记在册
//      （注册表要完备，人得知道有这些口子），但**不可能有 pending**——判据显式为 null。
//      硬塞进 等我() 只会造出永远为空或永远为满的假账。
