function 注册表(账本根) {
  try {
    const j = JSON.parse(fs.readFileSync(path.join(账本根, '闸注册表.json'), 'utf8'));
    const arr = Array.isArray(j) ? j : j.闸;
    if (Array.isArray(arr) && arr.length) return arr;
  } catch { /* 文件不在或坏了：走缺省，不静默变空 */ }
  return 缺省注册表;
}

const 停自 = (fm) => (fm && (fm.派单时间 || fm.更新时间 || fm.创建时间)) || null;

/* ===== pending 判据 =====
 * 每条 = (ctx) => [{ id, title, 停摆自 }]。只碰自己那一个权威源，取不到就返回空数组**并抛**——
 * 抛出去由 等我() 收进 失败[]，让调用方看得见「这条闸哑了」。静默返回空 = 假装没有欠债。 */
const 判据表 = {
  草稿: (c) => c.工单表.filter((t) => t.state === '草稿')
    .map((t) => ({ id: t.id, title: (t.fm && t.fm.title) || t.id, 停摆自: 停自(t.fm) })),

  // **待投 ≠ 欠你一笔**。三种情况不算债，照 studio「backlog ≠ 欠债」那条收窄：
  //   · 自动派发开着 → 这批活有人接管了，不该摆到人脸上（此闸恒空，宁可恒空也不虚报）
  //   · 依赖没就绪 → 它在等上游，不在等你
  //   · 池全冻结 → 它在等额度/预算窗口，你点了也派不出去
  待投候派: (c) => {
    if (c.自动派发开) return [];
    const 全冻 = c.可用池数 === 0;
    if (全冻) return [];
    return c.工单表.filter((t) => t.state === '待投')
      .filter((t) => c.依赖就绪(t))
      .map((t) => ({ id: t.id, title: (t.fm && t.fm.title) || t.id, 停摆自: 停自(t.fm) }));
  },

  在途超时: (c) => c.工单表.filter((t) => t.state === '在途' && !(t.fm && t.fm.中断))
    .filter((t) => {
      const 起 = Date.parse(停自(t.fm) || '');
      return Number.isFinite(起) && c.现在 - 起 > c.卡死阈值;
    })
    .map((t) => ({ id: t.id, title: (t.fm && t.fm.title) || t.id, 停摆自: 停自(t.fm) })),

  // 服务重启把在跑的活丢下 —— 协-019 之前它没有任何标记，只能等巡检按超时猜。
  // 现在执行器停机时会显式盖章，于是「被我们自己中断的」和「跑太久卡住的」分得开：
  // 前者重投是安全的（它根本没跑完），后者要先弄清它到底在干什么。
  // 质检也算（协-027）：判官跑到一半被停机掐掉，工单停在「质检」而不是「在途」——
  // 只看在途的话，被中断的质检查无对证，而它同样在等人点一下重判。
  服务重启中断: (c) => c.工单表.filter((t) => (t.state === '在途' || t.state === '质检') && t.fm && t.fm.中断)
    .map((t) => ({
      id: t.id,
      title: `${(t.fm && t.fm.title) || t.id}｜被中断的是${(t.fm && t.fm.中断类别) || '执行'}`,
      停摆自: (t.fm && t.fm.中断于) || 停自(t.fm),
    })),

  // 未进主线：活干完了、检查点也落了，但**没进主线**（快进发布不成立，多半是主工作区
  // 有未提交改动，或兄弟单先把基线推进了一格）。协-016 已经让它不再静默断链——
  // 检查点照落、工单照流转、看板上挂「未进主线」徽标。
  //
  // 但徽标是**被动的**：它标在那儿，不会告诉你该干什么。而这笔债只有人能了结
  // （建一张 integrator 单去合，或者手工合）。所以它必须进「等你落笔」——
  // 2026-08-23 HW-4 实测：工单在质检、看板上标着未进主线，而欠账清单里一个字都没有。
  //
  // 已完成/已归档的不算：归档的不再管，完成的若还挂着戳，那说明发布确实没成，仍要算。
  待集成: (c) => c.工单表.filter((t) => t.fm && t.fm.待集成 && t.state !== '已归档')
    .map((t) => ({
      id: t.id,
      title: `${(t.fm && t.fm.title) || t.id}｜${(t.fm.待集成.说) || '未进主线'}（分支 ${t.fm.待集成.分支 || '?'}）`,
      停摆自: t.fm.待集成.时刻 || 停自(t.fm),
    })),

  订阅耗尽: (c) => Object.entries(c.耗尽 || {}).map(([池, v]) => ({
    id: 池, title: `${池} 订阅额度已耗尽——再跑会落到 API 按 token 计费`, 停摆自: (v && v.时刻) || null,
  })),

  依赖死结: (c) => {
    const 有 = new Set(c.工单表.map((t) => t.id));
    const 状态of = Object.fromEntries(c.工单表.map((t) => [t.id, t.state]));
    const 出 = [];
    for (const t of c.工单表) {
      if (t.state === '完成' || t.state === '已归档') continue;
      const d = (t.fm && t.fm.依赖) || [];
      const 表 = Array.isArray(d) ? d : [d];
      const 坏 = 表.map(String).filter((x) => !有.has(x) || 状态of[x] === '已归档');
      if (坏.length) {
        出.push({ id: t.id, title: `${(t.fm && t.fm.title) || t.id}｜上游永远不会完成：${坏.join('、')}`, 停摆自: 停自(t.fm) });
      }
    }
    return 出;
  },
};

/**
 * 等我(ctx) —— 欠人的每一笔。
 * ctx: { 工单表, 现在, 卡死阈值, 依赖就绪(t), 自动派发开, 可用池数, 耗尽, 账本根 }
 * @returns {{债, 计数, 失败, 注册, 逾期阈值小时}}
 *   债 按停摆时长降序——最久的排最前，这是催办的天然序，不是按单号。
 */
function 等我(ctx = {}) {
  const c = {
    工单表: [], 现在: Date.now(), 卡死阈值: 30 * 60 * 1000,
    依赖就绪: () => true, 自动派发开: false, 可用池数: 1, 耗尽: {}, ...ctx,
  };
  const 表 = 注册表(c.账本根 || '.');
  const 债 = []; const 失败 = []; const 见过 = new Set();
  for (const g of 表) {
    if (!g.判据) continue;                       // 发起型：无队列，不是「欠着」
    const fn = 判据表[g.判据];
    if (!fn) { 失败.push({ 闸号: g.闸号, 因: '未知判据 ' + g.判据 }); continue; }
    let rows = [];
    try { rows = fn(c) || []; } catch (e) { 失败.push({ 闸号: g.闸号, 因: String(e.message).slice(0, 160) }); continue; }
    for (const r of rows) {
      const gateKey = g.闸号 + ':' + r.id;
      if (见过.has(gateKey)) continue;
      见过.add(gateKey);
      const ts = Date.parse(r.停摆自 || '');
      债.push({
        gateKey, 闸号: g.闸号, 闸名: g.名称, 落点: g.落点, 按钮: g.按钮,
        id: r.id, title: r.title || r.id, 停摆自: r.停摆自 || null,
        停摆小时: Number.isFinite(ts) ? Math.max(0, Math.round((c.现在 - ts) / 36e5 * 10) / 10) : null,
      });
    }
  }
  // 时长未知的排最后：不知道多久 ≠ 刚发生，但也不该冒充最久。
  债.sort((a, b) => (b.停摆小时 == null ? -1 : b.停摆小时) - (a.停摆小时 == null ? -1 : a.停摆小时));
  return { 债, 计数: 债.length, 失败, 注册: 表 };
}

/** 逾期升格：停摆超 T 小时的债。T 缺省 24。 */
function 逾期(ctx, T) {
  const t = Number(T == null ? 24 : T);
  return 等我(ctx).债.filter((x) => x.停摆小时 != null && x.停摆小时 >= t);
}

// 耗尽台账的读写。执行器写、server 读——跨进程的那半笔债靠它才看得见。
function 读耗尽(账本根) { try { return JSON.parse(fs.readFileSync(耗尽台账(账本根), 'utf8')) || {}; } catch { return {}; } }
function 写耗尽(账本根, 表) {
  try {
    fs.mkdirSync(path.dirname(耗尽台账(账本根)), { recursive: true });
    fs.writeFileSync(耗尽台账(账本根), JSON.stringify(表, null, 2) + '\n', 'utf8');
    return { ok: true };
  } catch (e) { return { ok: false, error: e.message }; }
}

