// 阶段轴 —— 一张单**竖着看**是什么样（协-028）。
//
// 看板是横着看的：一眼扫过所有单，每张只占一行。而人点开一张单时问的是竖的问题——
// 它走到哪一步了、哪一步卡住了、每一步留下了什么证据。
//
// 此前这些事实散在四处，而且**没有一处把它们串成一条线**：
//   · 工单 frontmatter（派单时间 / 检查点 / 发布提交 / 质检结论 / 待集成 / 执行失败 / 空转…）
//   · provider-runs 账本（跑过几次、每次多久）
//   · 那一次 HTTP 回执（关掉浏览器就没了）
//   · agent 自己说的话（协-028 之前根本没留下）
//
// 本模块只做一件事：把 frontmatter 上那些散点，按**发生顺序**排成阶段，每阶段回答三个问题——
//   现在是什么状态（未到 / 在做 / 成了 / 出事了 / 跳过了）、有什么证据、**接下来该谁动**。
//
// 纯函数：给 { id, state, fm }，出一个数组。不读盘、不问网络，好测。
'use strict';

const 时 = (v) => (v ? String(v) : null);

/**
 * 阶段轴(工单) → [{ 键, 名, 态, 说, 证据{}, 该谁 }]
 * 态：未到 | 在做 | 成 | 阻 | 跳过
 * 「阻」= 出事了或停在这儿等人，界面上标红；「跳过」= 这张单本来就不走这一步。
 */
function 阶段轴(t) {
  const fm = (t && t.fm) || {};
  const st = (t && t.state) || '';
  const 有项目 = !!String(fm.项目 || '').trim();
  const 只读单 = ['评审意见', '结论', '判定', '意见'].includes(String(fm.产出物类型 || '').trim());
  const 到过 = (阶段) => ['草稿', '待投', '在途', '质检', '完成', '已归档'].indexOf(st) >= ['草稿', '待投', '在途', '质检', '完成', '已归档'].indexOf(阶段);

  const 出 = [];

  出.push({
    键: '建单', 名: '建单', 态: '成',
    说: `${fm.role || fm.职能 || '(未写角色)'} · ${fm.产出物类型 || '(未写产出物类型)'}`
      + (有项目 ? ` · 项目 ${fm.项目}` : ' · 无项目（只跑不提交）'),
    证据: { 创建时间: 时(fm.创建时间), 优先级: fm.优先级 || null, 依赖: fm.依赖 || null, 写入范围: fm.write_scope || null },
    该谁: null,
  });

  出.push({
    键: '投出', 名: '投出待派',
    态: st === '草稿' ? '在做' : '成',
    说: st === '草稿' ? '还在草稿里，等你投出' : '已进待投队列',
    证据: {},
    该谁: st === '草稿' ? '你（看板 · 草稿列 → 投出）' : null,
  });

  const 派了 = !!fm.派单时间;
  出.push({
    键: '派活', 名: '派活',
    态: 派了 ? '成' : (st === '待投' ? '在做' : '未到'),
    说: 派了 ? `${fm.执行池 || '?'} · 权限${fm.权限模式 || '?'}` : (st === '待投' ? '等你点派活（或开自动派发）' : '还没轮到'),
    证据: { 派单时间: 时(fm.派单时间), 执行池: fm.执行池 || null, 权限模式: fm.权限模式 || null, 回合上限: fm.回合上限 || null, 需要依赖: fm.需要依赖 || null, 降级留痕: fm.降级留痕 || null },
    该谁: (!派了 && st === '待投') ? '你（看板 · 待投列 → 派活）' : null,
  });

  // 执行：这一格最有内容——失败/空转/中断三种坏结局各自不同，混成一个「没成」就没法处置。
  const 执行态 = fm.执行失败 ? '阻' : fm.中断 ? '阻' : fm.空转 ? '阻' : fm.检查点被拒 ? '阻'
    : (fm.检查点 || fm.报告落于) ? '成' : (st === '在途' ? '在做' : 派了 ? '成' : '未到');
  出.push({
    键: '执行', 名: '执行',
    态: 执行态,
    说: fm.检查点被拒 ? `检查点被拒：${String(fm.检查点被拒.因 || '').split(/\r?\n/)[0]}`
      : fm.执行失败 ? `失败：${fm.执行失败.原因 || '(没写原因)'}`
      : fm.中断 ? fm.中断
        : fm.空转 ? `空转：${(fm.空转 && fm.空转.说) || '跑成功但没改任何文件'}`
          : fm.报告落于 ? `只读单：报告已落进工单正文（${fm.报告字数 || '?'} 字）`
            : fm.检查点 ? `改了 ${(fm.变更文件 || []).length} 个文件` : (st === '在途' ? 'agent 正在干' : '还没轮到'),
    证据: {
      检查点: fm.检查点 || null, 变更文件: fm.变更文件 || null,
      执行失败: fm.执行失败 || null, 检查点被拒: fm.检查点被拒 || null, 空转: fm.空转 || null, 中断: fm.中断 || null, 中断类别: fm.中断类别 || null,
      报告落于: 时(fm.报告落于),
    },
    该谁: fm.检查点被拒 ? '你（改动没丢，还在工作区里；收窄改动或改 write_scope 后重投）'
      : fm.执行失败 ? '你（看一眼失败证据再决定重投还是改单）'
      : fm.空转 ? '你（判断是活本来就做完了，还是 agent 没动手）'
        : fm.中断 ? '你（被中断的活没跑完，重投是安全的）' : null,
  });

  // 提交链：不带项目的单**根本没有这一步**，标「跳过」而不是「未到」——
  // 「未到」会让人一直等一个永远不会发生的事。
  if (!有项目) {
    出.push({ 键: '发布', 名: '进主线', 态: '跳过', 说: '这张单没有项目，只跑不提交', 证据: {}, 该谁: null });
  } else {
    const 进了 = !!fm.发布提交;
    出.push({
      键: '发布', 名: '进主线',
      态: 进了 ? '成' : fm.待集成 ? '阻' : (fm.检查点 ? '在做' : '未到'),
      说: 进了 ? `已快进合入（${String(fm.发布提交).slice(0, 8)}）`
        : fm.待集成 ? `**未进主线**：${fm.待集成.说 || ''}（分支 ${fm.待集成.分支 || '?'}）`
          : fm.检查点 ? '有检查点，等发布' : '还没轮到',
      证据: { 发布提交: fm.发布提交 || null, 待集成: fm.待集成 || null },
      该谁: fm.待集成 ? '你（建一张 integrator 单去合，或手工合分支）' : null,
    });
  }

  const 判了 = !!fm.质检结论;
  出.push({
    键: '质检', 名: '质检',
    态: fm.免检原因 ? '跳过' : 判了 ? (fm.质检结论 === '通过' ? '成' : '阻') : (st === '质检' ? '在做' : '未到'),
    说: fm.免检原因 ? `免检：${fm.免检原因}`
      : 判了 ? `${fm.质检判官 || '?'} 判「${fm.质检结论}」` : (st === '质检' ? '等判官（POST /qa/<单号>）' : '还没轮到'),
    证据: { 质检结论: fm.质检结论 || null, 质检判官: fm.质检判官 || null, 质检时间: 时(fm.质检时间), 质检意见: fm.质检意见 || null, 免检原因: fm.免检原因 || null },
    该谁: (判了 && fm.质检结论 !== '通过') ? '你（照判词返工后重投）' : (st === '质检' ? '你（点判一次）' : null),
  });

  出.push({
    键: '完成', 名: '完成',
    态: st === '完成' ? '成' : st === '已归档' ? '跳过' : '未到',
    说: st === '完成' ? `完成于 ${时(fm.完成时间) || '?'}` : st === '已归档' ? '已归档' : '还没到',
    证据: { 完成时间: 时(fm.完成时间) },
    该谁: null,
  });

  return 出.map((x) => ({ ...x, 只读单 })).map((x) => ({ ...x, 到过: 到过(x.键 === '完成' ? '完成' : '草稿') }));
}

module.exports = { 阶段轴 };
