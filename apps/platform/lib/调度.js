// 调度 —— 自动派发的判断内核（协-004）。
//
// 纯计算：给它一批工单和当前在跑的情况，它告诉你**这一轮该派哪几张**。
// 不碰文件、不起进程、不做 IO——所以可单测，而调度逻辑正是最该被单测的东西：
// 它错了不会报错，只会安静地派错单或者一张都不派。
//
// 为什么要有自动派发：手动一张张点，平台只是个遥控器；有了 tick 循环，
// 它才是产线。但产线跑起来就会自己花钱，所以节流闸比派发本身更重要。
'use strict';

// 池并发上限：配置 执行.并发.<池名>，缺省用 执行.并发.默认，再缺省 1。
// **默认 1 是有意的**：并发是加速手段，不是默认姿态。一次一单最容易分诊，
// 出事时也只烧一份钱。要并发是显式决定。
function 并发上限(配置, 池) {
  const 并 = (配置.执行 && 配置.执行.并发) || {};
  const 值 = 并[池] !== undefined ? 并[池] : 并.默认;
  const n = Number(值);
  return Number.isFinite(n) && n > 0 ? Math.floor(n) : 1;
}

// 一轮该派什么。
//   待投表   [{ id, fm }]           候选工单
//   在跑     { <池名>: 数量 }        当前各池在途数
//   选池     (工单) => 池名|null     由调用方注入（真正的选人逻辑在 派单.选派）
//   依赖就绪 (工单) => bool          同上
//
// 返回 { 派: [{ id, 池 }], 跳过: [{ id, 原因 }] }。
// **跳过必须逐条给原因**：一轮什么都没派时，人第一个问题一定是「为什么」，
// 答不上来就只能去翻日志猜。
function 排一轮(配置, { 待投表, 在跑, 选池, 依赖就绪 }) {
  const 派 = []; const 跳过 = [];
  const 占用 = { ...(在跑 || {}) };

  // 优先级 → 创建时间。同优先级先来先服务，避免新单插队把老单饿死。
  const 序 = { P0: 0, P1: 1, P2: 2, P3: 3 };
  const 排好 = [...(待投表 || [])].sort((a, b) => {
    const pa = 序[(a.fm && a.fm.优先级) || 'P1'] ?? 1;
    const pb = 序[(b.fm && b.fm.优先级) || 'P1'] ?? 1;
    if (pa !== pb) return pa - pb;
    const ta = String((a.fm && a.fm.创建时间) || '');
    const tb = String((b.fm && b.fm.创建时间) || '');
    return ta.localeCompare(tb) || String(a.id).localeCompare(String(b.id));
  });

  for (const 单 of 排好) {
    if (!依赖就绪(单)) { 跳过.push({ id: 单.id, 原因: '依赖未就绪' }); continue; }
    const 池 = 选池(单);
    if (!池) { 跳过.push({ id: 单.id, 原因: '无可用 Provider（可能全被预算闸冻结）' }); continue; }
    const 上限 = 并发上限(配置, 池);
    const 已 = 占用[池] || 0;
    if (已 >= 上限) { 跳过.push({ id: 单.id, 原因: `池 ${池} 已达并发上限 ${上限}` }); continue; }
    占用[池] = 已 + 1;
    派.push({ id: 单.id, 池 });
  }
  return { 派, 跳过 };
}

// 在途统计：按执行池分组。给 排一轮 当输入。
//
// 第二个返回值 疑似卡死 是给「为什么派不出去」用的（见 归因）：
// 一张卡死的在途单会**永久占着一个并发额度**，产线吞吐就这么被砍掉一半，
// 而调度只会说「已达并发上限」——那句话字面没错，却把真正的原因盖住了。
// 实测：ORCH-1 卡在途 925 分钟，claude 池上限 2，于是每一轮都只能派一张。
function 统计在跑(在途表, 现在, 卡死阈值毫秒) {
  const 出 = {};
  const 疑似卡死 = [];
  const 阈值 = Number(卡死阈值毫秒) || 0;
  for (const t of 在途表 || []) {
    const 池 = (t.fm && t.fm.执行池) || '未知';
    出[池] = (出[池] || 0) + 1;
    if (!阈值 || !现在) continue;
    const 起 = Date.parse((t.fm && t.fm.派单时间) || '');
    // 没有派单时间的也算可疑：巡检把它单独报「在途无派单时间」，
    // 但对「谁占着额度」这个问题而言，它同样是一张说不清死活的单。
    if (!Number.isFinite(起) || 现在 - 起 > 阈值) {
      疑似卡死.push({ id: t.id, 池, 分钟: Number.isFinite(起) ? Math.round((现在 - 起) / 60000) : null });
    }
  }
  return { 在跑: 出, 疑似卡死 };
}

// 把「已达并发上限」这句话补全成人能行动的一句。
//
// **不自动回收额度**是有意的：调度看得见的只有「很久没动静」，推断不出那个 CLI
// 进程死没死。若它还活着而这里把额度让出去，同一个池会跑出比上限更多的并发——
// 那正是并发闸要防的事。所以只归因、不动作，把决定权留给人（看板上有「退回待投」）。
function 归因(跳过, 疑似卡死) {
  if (!(疑似卡死 || []).length) return 跳过 || [];
  const 按池 = {};
  for (const s of 疑似卡死) (按池[s.池] = 按池[s.池] || []).push(s);
  return (跳过 || []).map((s) => {
    const m = /^池 (.+?) 已达并发上限/.exec(s.原因 || '');
    const 嫌疑 = m && 按池[m[1]];
    if (!嫌疑) return s;
    return {
      ...s,
      原因: s.原因 + `——其中 ${嫌疑.map((x) => x.id + (x.分钟 == null ? '（无派单时间）' : `（已 ${x.分钟} 分钟）`)).join('、')}`
        + ' 疑似已挂却仍占着额度。确认那次执行真停了，就在看板上「退回待投」把额度放出来。',
      疑似卡死: 嫌疑.map((x) => x.id),
    };
  });
}

module.exports = { 并发上限, 排一轮, 统计在跑, 归因 };
