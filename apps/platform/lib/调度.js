// 调度 —— 自动派发的判断内核（协-004）。
//
// 纯计算：给它一批工单和当前在跑的情况，它告诉你**这一轮该派哪几张**。
// 不碰文件、不起进程、不做 IO——所以可单测，而调度逻辑正是最该被单测的东西：
// 它错了不会报错，只会安静地派错单或者一张都不派。
//
// 为什么要有自动派发：手动一张张点，平台只是个遥控器；有了 tick 循环，
// 它才是产线。但产线跑起来就会自己花钱，所以节流闸比派发本身更重要。
'use strict';

// 池并发上限：配置 执行.并发.<池名>，缺省用 执行.并发.默认，再缺省 1。
// **默认 1 是有意的**：并发是加速手段，不是默认姿态。一次一单最容易分诊，
// 出事时也只烧一份钱。要并发是显式决定。
function 并发上限(配置, 池) {
  const 并 = (配置.执行 && 配置.执行.并发) || {};
  const 值 = 并[池] !== undefined ? 并[池] : 并.默认;
  const n = Number(值);
  return Number.isFinite(n) && n > 0 ? Math.floor(n) : 1;
}

// 一轮该派什么。
//   待投表   [{ id, fm }]           候选工单
//   在跑     { <池名>: 数量 }        当前各池在途数
//   选池     (工单) => 池名|null     由调用方注入（真正的选人逻辑在 派单.选派）
//   依赖就绪 (工单) => bool          同上
//
// 返回 { 派: [{ id, 池 }], 跳过: [{ id, 原因 }] }。
// **跳过必须逐条给原因**：一轮什么都没派时，人第一个问题一定是「为什么」，
// 答不上来就只能去翻日志猜。
function 排一轮(配置, { 待投表, 在跑, 选池, 依赖就绪 }) {
  const 派 = []; const 跳过 = [];
  const 占用 = { ...(在跑 || {}) };

  // 优先级 → 创建时间。同优先级先来先服务，避免新单插队把老单饿死。
  const 序 = { P0: 0, P1: 1, P2: 2, P3: 3 };
  const 排好 = [...(待投表 || [])].sort((a, b) => {
    const pa = 序[(a.fm && a.fm.优先级) || 'P1'] ?? 1;
    const pb = 序[(b.fm && b.fm.优先级) || 'P1'] ?? 1;
    if (pa !== pb) return pa - pb;
    const ta = String((a.fm && a.fm.创建时间) || '');
    const tb = String((b.fm && b.fm.创建时间) || '');
    return ta.localeCompare(tb) || String(a.id).localeCompare(String(b.id));
  });

  for (const 单 of 排好) {
    if (!依赖就绪(单)) { 跳过.push({ id: 单.id, 原因: '依赖未就绪' }); continue; }
    const 池 = 选池(单);
    if (!池) { 跳过.push({ id: 单.id, 原因: '无可用 Provider（可能全被预算闸冻结）' }); continue; }
    const 上限 = 并发上限(配置, 池);
    const 已 = 占用[池] || 0;
    if (已 >= 上限) { 跳过.push({ id: 单.id, 原因: `池 ${池} 已达并发上限 ${上限}` }); continue; }
    占用[池] = 已 + 1;
    派.push({ id: 单.id, 池 });
  }
  return { 派, 跳过 };
}

// 在途统计：按执行池分组。给 排一轮 当输入。
function 统计在跑(在途表) {
  const 出 = {};
  for (const t of 在途表 || []) {
    const 池 = (t.fm && t.fm.执行池) || '未知';
    出[池] = (出[池] || 0) + 1;
  }
  return 出;
}

module.exports = { 并发上限, 排一轮, 统计在跑 };
