// 计费 —— 分清「用订阅额度」和「按 token 付费」（协-008）。
//
// 这是一次口径纠正，不是加功能。此前整个产品把每次真跑都标成「花钱」：
// 按钮叫「真跑（花钱）」，池上限叫「预算」，三闸的说法是「没有刹车不许上路」。
//
// 但那与实际的付费方式对不上。用户的设计是：
//   ① 优先用**订阅额度**（Claude Pro / Codex Plus 这类）——月费已经付了，
//      跑一次的边际成本是零。把它标成「花钱」会让人不敢走主路径。
//   ② 订阅额度用完了，**问一句**要不要落到 API 按 token 计费——
//      那才是真的产生新开销的那一刻，也才是闸门该站的位置。
//
// 于是本模块只回答三个问题：
//   · 这个池现在是哪种计费模式
//   · 这一次跑到底产不产生新开销
//   · 订阅是不是已经耗尽了（耗尽之后再跑会不会静默变成计费）
'use strict';

const 订阅 = '订阅';
const 本地 = '本地';
const 计费 = 'api';
const 未声明 = '未声明';

// 计费模式来自配置，**不猜**。
//
// 为什么不去探测：CLI 用的是订阅还是 API key，取决于登录态与环境变量，
// 这台机器上探得到的东西未必是那次 spawn 实际会用的东西。猜错的方向很要命——
// 猜成订阅而实际走了 API，人会在完全不知情的情况下被按 token 计费。
// 所以缺声明时一律当**未声明**，并在需要判断开销时按「可能计费」从严处理。
function 模式(配置, 池) {
  const 表 = (配置 && 配置.计费) || {};
  const 项 = 表[池];
  const m = String((项 && 项.模式) || '').trim().toLowerCase();
  if (m === '订阅' || m === 'subscription' || m === 'sub') return 订阅;
  if (m === 'api' || m === '计费' || m === 'metered') return 计费;
  // 本地：command-cli 这类跑本机命令的池，**根本不存在厂商计费**。
  // 少了这一档的后果是它落进「未声明」，而未声明按会花钱算——
  // 于是一个永远不花钱的桩池把整个界面拖成红的，红色就此失去意义。
  if (m === '本地' || m === 'local' || m === '免费' || m === 'free') return 本地;
  return 未声明;
}

const 订阅名 = (配置, 池) => String((((配置 && 配置.计费) || {})[池] || {}).订阅名 || '').trim();

// 耗尽之后怎么办：问 / 停 / 用api。默认「问」——这正是用户要的那句话。
function 耗尽后(配置, 池) {
  const v = String(((((配置 && 配置.计费) || {})[池]) || {}).耗尽后 || '问').trim();
  return ['问', '停', '用api'].includes(v) ? v : '问';
}

// 这一次跑会不会产生**新的**开销。
//
// 订阅模式下答案是「不会」——月费已经付了。这句话是本模块存在的理由：
// 界面上那个「花钱」标签，只该出现在真的会多花钱的地方。
// 未声明时按可能计费处理：宁可多问一句，不可让人在不知情时被计费。
function 会新增开销(配置, 池, { 订阅已耗尽 } = {}) {
  const m = 模式(配置, 池);
  if (m === 本地) return false;            // 跑本机命令，没有厂商在计费
  if (m === 计费) return true;
  if (m === 订阅) return !!订阅已耗尽;      // 耗尽后若落到 API，就真的开始花钱了
  return true;
}

// 订阅耗尽的信号。
//
// ⚠ **这些模式是尽力而为的，不是权威清单**。各家 CLI 的限流措辞会变，
// 而我没有在真实耗尽的现场验证过它们。所以：
//   · 模式可在 config 的 计费.<池>.耗尽信号 里覆盖，不必改源码；
//   · 判定为耗尽只会让平台**更保守**（停派 + 问人），不会让它多花钱；
//   · 漏判的后果是继续按订阅跑——若此时环境里有 API key，CLI 可能自己落到计费。
//     这条风险单列在 落计费风险() 里，不靠这里的字符串匹配兜底。
const 默认耗尽信号 = [
  /usage limit/i,
  /rate limit/i,
  /quota (?:exceeded|exhausted)/i,
  /out of (?:credits|quota)/i,
  /额度.*(用完|耗尽|不足)/,
  /配额.*(用完|耗尽|不足)/,
  /(请|稍后).*(重试|再试)/,
];

function 耗尽信号(配置, 池) {
  const 自定 = ((((配置 && 配置.计费) || {})[池]) || {}).耗尽信号;
  if (!Array.isArray(自定) || !自定.length) return 默认耗尽信号;
  return 自定.map((s) => {
    try { return new RegExp(String(s), 'i'); } catch { return null; }
  }).filter(Boolean);
}

// 从一次运行的产出里判断订阅是不是耗尽了。
// 只看错误通道与尾部：正文里出现「rate limit」多半是 agent 在讨论这个词，
// 而不是它自己撞上了限流——拿整篇正文去匹配会误判成一片。
function 判耗尽(配置, 池, { 输出, 错出, 退出码 } = {}) {
  if (退出码 === 0) return null;                       // 跑成了就不是耗尽
  const 信号 = 耗尽信号(配置, 池);

  // stderr 是**权威通道**：限流是 CLI 自己报的错，它会走这里。全篇都查。
  const 错 = String(错出 || '');
  for (const re of 信号) {
    const m = re.exec(错);
    if (m) return { 耗尽: true, 池, 命中: m[0].slice(0, 120), 出处: 'stderr' };
  }

  // stdout 里的文字**不足以单独定案**。
  //
  // 踩了两次才想明白：第一版取尾部 2000 字，被 agent 正文里反复讨论
  // 「给接口加上 rate limit 保护」骗到；改成只看最后三行，照样骗到——
  // 那句话就是最后一行。问题不在取多少，在于 stdout 装的是 agent 的话，
  // 而 agent 谈论限流跟它自己撞上限流是两回事。
  //
  // 误判的代价是实打实的：平台以为额度没了、停派、弹框问人，而额度好好的。
  // 所以 stdout 侧加一个合取条件——这一行还得**长得像报错**。
  // 真的限流提示总是伴随错误标记（claude 的 stream-json 会吐 type:"error"），
  // 而 agent 讨论限流时不会。
  const 像报错 = /error|Error|ERROR|错误|失败|"type"\s*:\s*"error"/;
  const 尾行 = String(输出 || '').split(/\r?\n/).filter((l) => l.trim()).slice(-3);
  for (const 行 of 尾行) {
    if (!像报错.test(行)) continue;
    for (const re of 信号) {
      const m = re.exec(行);
      if (m) return { 耗尽: true, 池, 命中: m[0].slice(0, 120), 出处: '输出末尾' };
    }
  }
  return null;
}

// 落计费风险：订阅池，但环境里带着 API key。
//
// 这是**最要紧的一条**，而且它跟字符串匹配无关：CLI 在订阅额度耗尽后，
// 若发现环境变量里有 API key，可能自己切到按 token 计费——平台这边看不见，
// 人也不会收到任何提示，直到账单出来。
// 所以在真跑之前就把这个风险讲明白，而不是等耗尽了再说。
const KEY环境变量 = {
  claude: ['ANTHROPIC_API_KEY', 'ANTHROPIC_AUTH_TOKEN'],
  codex: ['OPENAI_API_KEY'],
};

function 落计费风险(配置, 池, env = process.env) {
  if (模式(配置, 池) !== 订阅) return null;
  const 名单 = KEY环境变量[池] || [];
  const 命中 = 名单.filter((k) => String(env[k] || '').trim());
  if (!命中.length) return null;
  return {
    池, 变量: 命中,
    说: `${池} 声明为订阅计费，但环境里设了 ${命中.join('、')}。`
      + '订阅额度耗尽后，CLI 可能自己切到按 token 计费，而平台看不见这次切换——'
      + '账单出来之前不会有任何提示。不想要这个兜底就清掉该环境变量。',
  };
}

// 一句话说清这个池现在是什么状态，给界面直接用。
function 说明(配置, 池, { 订阅已耗尽 } = {}) {
  const m = 模式(配置, 池);
  if (m === 订阅) {
    const 名 = 订阅名(配置, 池);
    return 订阅已耗尽
      ? { 标签: '额度已耗尽', 花钱: true, 说: `${名 || '订阅'}额度用完了。再跑会落到 API 按 token 计费。` }
      : { 标签: '订阅额度', 花钱: false, 说: `走${名 || '订阅'}额度，月费已付，这一次不产生新开销。` };
  }
  if (m === 本地) return { 标签: '本地执行', 花钱: false, 说: '跑本机命令，不经任何厂商计费。' };
  if (m === 计费) return { 标签: '按量计费', 花钱: true, 说: '按 token 计费，这一次会产生真实开销。' };
  return {
    标签: '计费方式未声明', 花钱: true,
    说: `没有在 config 的 计费.${池} 里声明模式。**不猜**——猜成订阅而实际走 API，`
      + '人会在不知情的情况下被计费。声明之前一律按会计费对待。',
  };
}

module.exports = {
  订阅, 计费, 本地, 未声明,
  模式, 订阅名, 耗尽后, 会新增开销, 判耗尽, 落计费风险, 说明, 默认耗尽信号, KEY环境变量,
};
