// 流程视图 —— 回答「现在卡在哪、接下来能干什么」（协-006）。
//
// 看板是一张平铺列表：按状态排个序，够看，但答不了上面那两个问题。
// 一张单为什么不动？可能是上游没完成、可能是上游根本不存在、也可能它就绪了
// 只是还没人点。这三种在列表里长得一模一样——都只是「待投」。
//
// studio 的流程页是按**管线**分泳道的（管线/战役/专项/里程碑）。那是它的领域概念，
// platform 一个都没有，照抄过来是死代码。但它回答的问题对本产品同样成立，
// 所以照着**问题**抄，不照着形状抄：本产品的骨架是状态机 + 依赖 DAG，
// 于是分道的依据是**依赖深度**——第 0 层不等任何人，第 N 层等着第 N-1 层。
//
// 纯计算，不碰 IO：喂它工单快照，返回可直接渲染的结构。与 lib/巡检.js 同一个路子，
// 好测，也让「算错了」和「取数取错了」两类问题分得开。
'use strict';

const 状态序 = ['草稿', '待投', '在途', '质检', '完成'];

function 依赖表(t) {
  const d = (t && t.fm && (t.fm.依赖 || t.fm.dependsOn)) || [];
  return (Array.isArray(d) ? d : [d]).map(String).filter(Boolean);
}

// 依赖深度。**先占位再回填**，天然断环——父子/依赖字段是人写的，环不是不可能，
// 而一条环边不该把整页算死（这一手是从 studio 的流程页学的，它踩过）。
function 深度表(全部) {
  const 表 = new Map(全部.map((t) => [String(t.id), t]));
  const 深 = {};
  const 走 = (id, 层) => {
    if (深[id] != null) return 深[id];
    深[id] = 0;                                  // 先占位：再遇到自己就返回 0，环在这里断掉
    const t = 表.get(String(id));
    if (!t || 层 > 30) return 0;
    const 上 = 依赖表(t).filter((d) => 表.has(d));
    深[id] = 上.length ? Math.max(0, ...上.map((d) => 走(d, 层 + 1) + 1)) : 0;
    return 深[id];
  };
  for (const t of 全部) 走(String(t.id), 0);
  return 深;
}

// 一张单为什么不动。**分得开才有用**：三种原因的处置完全不同——
// 等上游只需等；上游缺失要去建单或改依赖；就绪了只是没人点，那就点。
function 卡因(t, 表) {
  if (t.state !== '待投') return null;
  const 上 = 依赖表(t);
  if (!上.length) return { 类型: '就绪', 说: '不等任何人，可以派' };
  const 缺 = 上.filter((d) => !表.has(d));
  if (缺.length) {
    return { 类型: '依赖缺失', 单: 缺, 说: `依赖的 ${缺.join('、')} 在库里找不到——永远不会就绪，去建单或改依赖` };
  }
  const 未完 = 上.filter((d) => 表.get(d).state !== '完成');
  if (未完.length) {
    // 成环时这里会一直报「等上游」——那句话字面没错，但它永远等不到。
    // **不在这儿查环**是有意的：lib/巡检.js 的「依赖成环」专管这件事，
    // 而且它报得更准（点名两张单互相依赖）。同一件事两处各查一遍，
    // 迟早会出现「一处修了另一处没修」，那比只有一处更难查。
    return { 类型: '等上游', 单: 未完, 说: `等 ${未完.map((d) => `${d}(${表.get(d).state})`).join('、')}` };
  }
  return { 类型: '就绪', 说: '上游都完成了，可以派' };
}

// 状态机本身：每态几张、能走到哪。
// 把它画出来是为了让「这张单接下来会去哪」变成看得见的东西——
// 表驱动的状态机写在代码里，用的人看不到。
function 状态段(全部, 转移表) {
  return 状态序.map((s) => ({
    状态: s,
    张数: 全部.filter((t) => t.state === s).length,
    去向: (转移表 && 转移表[s]) || [],
  }));
}

function 铺(全部, 选项 = {}) {
  const 单 = (全部 || []).map((t) => ({ ...t, id: String(t.id) }));
  const 表 = new Map(单.map((t) => [t.id, t]));
  const 深 = 深度表(单);

  // 分道：只铺未完成的。完成的单堆在那里只会把「现在该看什么」淹掉，
  // 想看历史去看板筛「完成」。
  //
  // ⚠ 项目筛只在这里生效——**深度与卡因都是拿全库算的**（上面几行）。
  // 反过来做（先按项目筛掉再算）会让跨项目的上游从表里消失，于是一张
  // 依赖着别项目单子的工单被判成「依赖缺失——永远不会就绪」，
  // 而它其实好好的。跨项目依赖不常见，但错那一次的代价是让人去删一条正常的依赖。
  const 项目筛 = String(选项.只看项目 || '');
  const 合项目 = (t) => {
    if (!项目筛) return true;
    const p = (t.fm && t.fm.项目) || '';
    return 项目筛 === '(无项目)' ? !p : p === 项目筛;
  };
  const 在办 = 单.filter((t) => t.state !== '完成' && 合项目(t));
  const 道 = new Map();
  for (const t of 在办) {
    const d = 深[t.id] || 0;
    if (!道.has(d)) 道.set(d, []);
    道.get(d).push({
      id: t.id,
      状态: t.state,
      标题: (t.fm && t.fm.title) || '',
      角色: (t.fm && (t.fm.role || t.fm.角色)) || '',
      池: (t.fm && t.fm.执行池) || '',
      父单: (t.fm && t.fm.父单) || null,
      依赖: 依赖表(t),
      卡因: 卡因(t, 表),
    });
  }

  const 层 = [...道.keys()].sort((a, b) => a - b).map((d) => ({
    深度: d,
    // 第 0 层的说法要准：它是「不等任何人」，不是「最先做」——
    // 一张第 0 层的单也可能是草稿，还没轮到它。
    说明: d === 0 ? '不依赖任何单' : `等着第 ${d - 1} 层`,
    工单: 道.get(d).sort((a, b) => a.id.localeCompare(b.id)),
  }));

  const 全部卡因 = 在办.map((t) => 卡因(t, 表)).filter(Boolean);
  return {
    状态机: 状态段(单, 选项.转移表),
    层,
    小结: {
      在办: 在办.length,
      就绪: 全部卡因.filter((x) => x.类型 === '就绪').length,
      等上游: 全部卡因.filter((x) => x.类型 === '等上游').length,
      依赖缺失: 全部卡因.filter((x) => x.类型 === '依赖缺失').length,
      最深: 层.length ? 层[层.length - 1].深度 : 0,
    },
  };
}

module.exports = { 铺, 深度表, 卡因, 依赖表, 状态序 };
