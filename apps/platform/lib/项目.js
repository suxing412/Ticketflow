// 项目 —— 把「项目」从工单上的一个字符串，做成一等公民（协-007）。
//
// 现状的毛病：注册表早就有（config/项目.local.json），worktree 隔离也在做，
// 但**界面上项目不存在**。看板把所有项目的单混着列；消耗和战绩不分项目，
// 答不了「这个项目花了多少」；注册只能手改 JSON；工单上的 项目 字段是自由文本，
// 写错了要等到真跑那一刻才报「项目未注册」——中间每一步都显示正常。
//
// 模型照 studio（用户点名参考）：**工单库只有一个**，工单靠 项目 字段认领，
// 「工作区」是那个项目的 git 仓——产出、worktree、提交都落在仓里。
// 为什么不给每个项目各开一个工单库根：那会把库切碎，跨项目依赖没处放，
// 巡检与调度也失去全局视野，而且 studio 这台跑了更久的机器没这么做。
//
// ⚠ 本模块**只用 fs**，不引 child_process。它住 server 进程，
// 而 server 的桩模式是物理保证（契约测试盯着传递闭包）。
// 于是体检只能看到「路径在不在、像不像个 git 仓」——真正的 git 状态
// （有没有未提交改动、当前在哪个分支）得问 :4371 工作区服务，那是它的能力面。
// 这个界限是有意的，不是没做完：能看见的和不能看见的，得说清楚。
'use strict';
const fs = require('fs');
const path = require('path');
const 配置位置 = require('./配置位置.js');

const 配置文件 = (平台根) => path.join(配置位置.可写配置目录(平台根), '项目.local.json');

// 项目名白名单。它会进 URL 查询串、会当对象键、会出现在错误信息里，
// 收窄一点省得后面每处都要防一遍。
const 合法名 = /^[A-Za-z0-9一-龥][A-Za-z0-9一-龥._-]{0,63}$/;

function 注册表(配置) {
  return ((配置 || {}).项目 && (配置 || {}).项目.注册) || {};
}
function 默认项目(配置) {
  return ((配置 || {}).项目 && (配置 || {}).项目.默认) || '';
}

// 单个项目的体检。**只看 fs 能看到的**，看不到的不猜。
function 体检(名, 项) {
  const 路径 = String((项 && (项.路径 ||项.path)) || '').trim();
  const 出 = { 名, 路径, 存在: false, 是git仓: false, 就绪: false };
  if (!路径) { 出.说 = '注册项没有写「路径」'; return 出; }
  出.存在 = fs.existsSync(路径);
  if (!出.存在) {
    // 路径写了但不在，是最容易发生的注册错误（换机、盘符变、目录挪走）。
    // 这句要点名说清，而不是笼统一句「项目不可用」。
    出.说 = '注册的路径不存在——换过机器或目录挪走了？改 config/项目.local.json';
    return 出;
  }
  // .git 可能是目录（普通仓）也可能是文件（worktree 里的 .git 是一行指针）
  出.是git仓 = fs.existsSync(path.join(路径, '.git'));
  if (!出.是git仓) {
    出.说 = '路径存在但不是 git 仓——提交链需要 git，隔离 worktree 建不起来';
    return 出;
  }
  出.就绪 = true;
  // 说清这份体检的边界：能看见什么、看不见什么。不说的话，人会以为「就绪」
  // 等于「git 干净可以直接发布」，而那件事本进程根本查不了。
  出.说 = '路径在、是 git 仓。本进程只看得到这些——分支与未提交改动要问工作区服务(:4371)';
  return 出;
}

function 列(配置) {
  const 注册 = 注册表(配置);
  const 默认 = 默认项目(配置);
  const 出 = Object.entries(注册).map(([名, 项]) => ({ ...体检(名, 项), 默认: 名 === 默认 }));
  出.sort((a, b) => (b.默认 - a.默认) || a.名.localeCompare(b.名));
  return 出;
}

// 工单上的 项目 字段落到哪个仓。空值是**合法的**——不带项目的单只跑不提交，
// 那是既定行为，不是配错了。
function 解析(配置, 名) {
  const s = String(名 || '').trim();
  if (!s) return { ok: true, 名: '', 路径: null, 说: '未指定项目：只跑不提交' };
  const 项 = 注册表(配置)[s];
  if (!项) {
    const 有 = Object.keys(注册表(配置));
    return {
      ok: false,
      错误: `项目「${s}」不在注册表里。`
        + (有.length ? `已注册：${有.join('、')}` : '注册表是空的——先在界面上登记一个项目')
        + '。注册表同时是**写操作白名单**：不在表里的仓，工作区服务一律拒绝往里提交。',
    };
  }
  const 检 = 体检(s, 项);
  if (!检.就绪) return { ok: false, 错误: `项目「${s}」不可用：${检.说}`, 体检: 检 };
  return { ok: true, 名: s, 路径: 检.路径 };
}

// 建单时校验。**在建单那一刻拦住**，而不是等到真跑：
// 中间要经过投出、排队、派活好几步，每一步都显示正常，最后才在花钱的那一刻炸。
function 校验工单项目(配置, 名) {
  const s = String(名 || '').trim();
  if (!s) return null;
  if (!合法名.test(s)) return `项目名非法：${JSON.stringify(s)}。只允许中英文数字开头，其后 . _ - 与中英文数字，最长 64 字符。`;
  const r = 解析(配置, s);
  return r.ok ? null : r.错误;
}

// 从界面登记一个项目。与工单库落位同一个路子：位置仍然人给，产品只负责收好。
function 落位(平台根, 名, 路径, 设为默认) {
  const n = String(名 || '').trim();
  const p = String(路径 || '').trim();
  if (!n) return { ok: false, 错误: '没填项目名' };
  if (!合法名.test(n)) return { ok: false, 错误: `项目名非法：${JSON.stringify(n)}。只允许中英文数字开头，其后 . _ - 与中英文数字。` };
  if (!p) return { ok: false, 错误: '没填仓库路径' };
  if (!path.isAbsolute(p)) {
    return { ok: false, 错误: `请填绝对路径（实得 ${p}）。相对路径的基准是服务进程的工作目录，换个方式启动就指向别处了。` };
  }
  const 仓 = path.resolve(p);
  if (!fs.existsSync(仓)) return { ok: false, 错误: `路径不存在：${仓}` };

  // 自我注册闸——**必须排在 git 检查之前**。
  //
  // 注册表同时是写操作白名单：登记一个仓，就等于允许 AI 往里提交。
  // 登记了包含平台自己的仓，AI 就能改自己的闸门——真跑开关、预算上限、门禁令牌，
  // 全在 config/ 里。这不是洁癖，是自我修改的口子。
  //
  // ⚠ 两个方向都要挡，第一版只挡了一个方向，当场被自己的测试打脸：
  //   · 仓在平台目录里     → path.relative(平台, 仓) 不以 .. 开头
  //   · **平台在仓里**     → 反过来算才看得出来。而这个方向才是真会发生的那个：
  //     D:/Ticketflow 是仓根、里面装着 apps/platform，注册它完全是个自然动作，
  //     而第一版原样放行了。
  // 排在 git 检查之前，是因为「不是 git 仓」这条会先把它拦掉、给出一句
  // 完全无关的理由，把真正的危险盖住。
  const 平台 = path.resolve(平台根);
  const 套住 = (外, 内) => {
    const r = path.relative(外, 内);
    return r === '' || (!r.startsWith('..') && !path.isAbsolute(r));
  };
  if (套住(平台, 仓) || 套住(仓, 平台)) {
    return {
      ok: false,
      错误: `不能注册与平台自身重叠的仓（${仓}）。注册表是写操作白名单，登记它就等于`
        + '允许 AI 往平台自己的代码里提交——包括改真跑开关、预算上限与门禁令牌。'
        + `\n平台在 ${平台}。请指向别的仓。`,
    };
  }

  if (!fs.existsSync(path.join(仓, '.git'))) {
    return {
      ok: false,
      错误: `${仓} 不是 git 仓（没有 .git）。提交链要在这里建隔离 worktree 并快进合并，`
        + '不是仓就无从谈起。先 git init，或改指向真正的仓根。',
    };
  }

  const 文件 = 配置文件(平台根);
  let 旧 = {};
  try { 旧 = JSON.parse(fs.readFileSync(文件, 'utf8')); } catch { /* 没有就新建 */ }
  const 注册 = { ...(旧.注册 || {}) };
  const 覆盖 = !!注册[n];
  注册[n] = { ...(注册[n] || {}), 路径: 仓 };
  const 新 = {
    ...旧,
    _说明: 旧._说明 || ['项目注册表（不入库，路径机器相关）。', '注册表同时是写操作白名单：不在表里的仓，工作区服务一律拒绝往里提交。'],
    注册,
    默认: 设为默认 || !旧.默认 ? n : 旧.默认,      // 头一个登记的自动成默认，省一步
  };
  fs.mkdirSync(path.dirname(文件), { recursive: true });
  fs.writeFileSync(文件, JSON.stringify(新, null, 2) + '\n', 'utf8');
  return { ok: true, 名: n, 路径: 仓, 文件, 覆盖, 默认: 新.默认 };
}

module.exports = { 列, 解析, 体检, 校验工单项目, 落位, 注册表, 默认项目, 配置文件, 合法名 };
