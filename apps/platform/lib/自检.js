// 自检 —— 回答「这台机器现在能干什么、不能干什么、为什么」（协-005）。
//
// 为什么需要它：这个平台有**五份不入库的本地配置**，缺任何一份都会让某条链路失效，
// 而失效的表现各不相同（503 / 403 / 空看板 / 静默不派）。首次使用的人只能靠试错
// 一条条撞出来，撞到哪条算哪条。
//
// 自检把「能力 → 前提 → 缺什么 → 怎么补」摆成一张表。**不做修复动作**，只报事实：
// 自动补配置意味着替人决定业务数据落哪、要不要花钱，那些都不该由一个自检函数拍板。
//
// 纯计算 + 只读文件，零 IO 副作用。
'use strict';

const fs = require('fs');
const path = require('path');

// 一条能力：名字、前提是否满足、缺了会怎样、怎么补。
// 「缺了会怎样」是这张表最有价值的一列——只说「未配置」等于让人自己去猜后果。
function 查(平台根, 配置, 工单根) {
  const 条 = [];
  const 有 = (p) => fs.existsSync(path.join(平台根, p));
  // 可写那一份要去**可写配置目录**找，不能拿 平台根 拼（协-036）。
  //
  // 打包态 平台根 落在 app.asar 里，而 .local.json 与 api-token.txt 全在 exe 同级
  // （lib/配置位置.js 的分法）。拿 平台根 去找它们，打包态**永远找不到**——
  // 实测：真打包件开机后 config\api-token.txt 明明在、令牌也真的能用，
  // 自检却一直把「命令行调接口」标红。诊断工具报假红比不报更坏：
  // 人会跑去修一个根本没坏的东西。
  const 有可写 = (名) => {
    try { return fs.existsSync(path.join(require('./配置位置').可写配置目录(平台根), 名)); }
    catch { return 有(`config/${名}`); }
  };
  // 参数缺了也得出表，不能抛。自检是**出事之后才会被跑**的东西——
  // 一个在环境不全时自己先崩掉的诊断工具，正好在最需要它的时刻掉链子。
  配置 = 配置 || {};
  工单根 = 工单根 || { ok: false, 来源: '(调用方没传)' };

  条.push({
    能力: '开机与只读接口',
    就绪: true,
    说明: 'health / providers / toolchain / routing 这些不需要任何本地配置',
  });

  条.push({
    能力: '工单库（建单、看板、流转）',
    就绪: 工单根.ok,
    ...(工单根.ok ? { 现值: 工单根.根, 来源: 工单根.来源 } : {
      缺: 'config/工单库.local.json 或 PLATFORM_TICKETS',
      后果: '所有 /api/tickets* 返回 503，看板是空的——不是没工单，是根本没地方放',
      补法: '写 config/工单库.local.json：{ "根目录": "D:/你的私仓/工单" }。'
        + '**本产品不替你选位置**：工单是业务数据，猜一个路径往里写比报错严重得多。',
    }),
  });

  const 允许真跑 = !!(配置.执行 && 配置.执行.允许真跑);
  const 预算池 = Object.keys((配置.预算 && 配置.预算.池) || {});
  // 「真跑」不等于「花钱」——协-008 改的口径，这里漏了一处（2026-08-12 自检输出上看到的）。
  // 走订阅额度时月费已付，边际成本是零；真花钱只发生在额度耗尽后落到 API 计费。
  // 自检是产品对自己的描述，口径不一致比措辞难看严重：人照着它判断要不要点下去。
  const 计费 = require('./计费.js');
  const 池表 = Object.keys(配置.providers || {});
  const 计费面 = 池表.map((池) => ({ 池, ...计费.说明(配置, 池) }));
  const 未声明 = 计费面.filter((x) => 计费.模式(配置, x.池) === 计费.未声明).map((x) => x.池);
  条.push({
    能力: '真跑（调用 AI CLI）',
    就绪: 允许真跑 && 预算池.length > 0,
    现值: {
      允许真跑,
      配了上限的池: 预算池,
      // 每个池到底怎么计费，摆在自检里——这正是人点「真跑」之前要知道的那件事，
      // 而它此前只在执行器的 /health 里，界面上看不到。
      计费: Object.fromEntries(计费面.map((x) => [x.池, x.标签])),
      ...(未声明.length ? { 提醒: `${未声明.join('、')} 没在 config/计费.local.json 里声明计费模式，一律按会计费对待` } : {}),
    },
    ...(允许真跑 && 预算池.length ? {} : {
      缺: [!允许真跑 && 'config/执行.local.json 的 允许真跑', !预算池.length && 'config/预算.local.json 的 池上限'].filter(Boolean).join(' + '),
      后果: '只能干跑。干跑走完整链路但不 spawn，零消耗——够验逻辑，不产出真结果',
      补法: '两份都要：允许真跑是总开关；逐池上限对订阅池守的是**订阅窗口**（一口气烧完几小时都跑不了），对 API 池才是守钱包。'
        + '四闸缺一即拒（另两闸：请求体显式 干跑:false；订阅额度耗尽后落到 API 计费须显式同意）',
    }),
  });

  const 允许写 = !!(配置.workspace && 配置.workspace.允许写);
  const 项目 = Object.keys((配置.项目 && 配置.项目.注册) || {});
  条.push({
    能力: '提交链（改代码并合回目标仓）',
    就绪: 允许写 && 项目.length > 0,
    现值: { 允许写, 已注册项目: 项目 },
    ...(允许写 && 项目.length ? {} : {
      缺: [!允许写 && 'config/workspace.local.json 的 允许写', !项目.length && 'config/项目.local.json 的 注册'].filter(Boolean).join(' + '),
      后果: '带「项目」的工单起不了隔离工作区，执行完停在在途，代码合不回去',
      补法: '项目注册表同时是**写操作白名单**——不在表里的仓，工作区服务一律拒绝往里提交',
    }),
  });

  // 写权白名单（协-020）。这一条不是「配置缺了个可选项」，是**产线会不会白跑**：
  // 白名单空 = 所有角色受限 = claude 拿 `--permission-mode plan`、codex 拿只读沙箱，
  // 于是任何要落盘的单跑完都是零改动，被空转闸退回待投——而每一次都要花掉几分钟真额度。
  // 2026-08-23 HW-3 实测：7 分 21 秒、退出码 0、一个文件都没改。
  //
  // 「不就绪」不等于「配错了」：一台只用来跑评审/问答的机器，白名单空是对的。
  // 所以这里报的是**后果**，不是错误。默认最严那条纪律不动（缺配置即全部受限）。
  const 放开 = ((配置.执行 && 配置.执行.权限) || {}).放开;
  const 放开表 = Array.isArray(放开) ? 放开 : [];
  条.push({
    能力: '写权（agent 能不能真的改文件）',
    就绪: 放开表.length > 0,
    现值: { 放开: 放开表, 受限即只读: 'claude-cli → --permission-mode plan；codex-cli → --sandbox read-only' },
    ...(放开表.length ? {} : {
      缺: 'config/执行.local.json 的 执行.权限.放开',
      后果: '所有角色受限 → 只读 → 任何「产出物类型=代码/文档/资产/规格」或声明了 write_scope 的单，'
        + '跑完必然零改动（空转退回待投）。派活前会被写权矛盾闸拦下，不会再白烧额度',
      补法: '要让它真的改代码：`"权限": { "放开": ["backend", "frontend", "integrator"] }`。'
        + '**这是授予写权限**——受限模式覆盖掉的正是适配器默认的权限绕过开关。'
        + 'reviewer 不该进这个名单：它判活时的权限**不走这条**，由 lib/派单.js 的 判官参数 单独定'
        + '（协-034：只在自己那个一次性审阅区内可写，判完当场查篡改）。'
        + '把它放进 放开 等于给它全盘绕过，那是另一回事',
    }),
  });

  条.push({
    能力: '质检（另一个 Provider 判一次）',
    就绪: (配置.质检 || {}).启用 !== false,
    现值: { 启用: (配置.质检 || {}).启用 !== false, 免检角色: (配置.质检 || {}).免检角色 || [] },
    说明: '默认开。关掉意味着「AI 说自己做完了就算做完」——真派活的产线上这不成立',
  });

  // 令牌是自动生成的，但明文副本可能因为老装机而缺失
  条.push({
    能力: '命令行调接口',
    就绪: 有可写('api-token.txt'),
    ...(有可写('api-token.txt') ? { 现值: 'config/api-token.txt' } : {
      缺: 'config/api-token.txt',
      后果: 'PowerShell 5.1 读不了带中文键的 JSON 令牌文件（GBK 解 UTF-8 整份失败），命令行没法调接口',
      补法: '重启服务会自动补写这份明文副本，令牌值不变',
    }),
  });

  return 条;
}

// 一句话总结：能干到哪一步。比一堆勾叉更有用——人第一眼想知道的是「我现在能干嘛」。
function 结论(条) {
  const 得 = (名) => (条.find((x) => x.能力.startsWith(名)) || {}).就绪;
  if (!得('工单库')) return { 级别: '未就绪', 一句话: '连工单都没地方放——先配工单库根目录，其余都谈不上' };
  if (!得('真跑')) return { 级别: '干跑可用', 一句话: '能建单、能派活、能走完整链路，但不 spawn、零消耗。验逻辑够用' };
  if (!得('提交链')) return { 级别: '能执行不能提交', 一句话: '能真跑 AI 并拿到输出，但代码合不回目标仓，工单会停在在途' };
  return { 级别: '全链路就绪', 一句话: '建单 → 派活 → 真跑 → 质检 → 提交，整条链都通' };
}

module.exports = { 查, 结论 };
