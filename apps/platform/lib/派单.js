// 冻结：哪些池现在不许派。**两道闸并进同一个 挡 map**——
//   · 预算闸（packages/budget）：token 上限，守的是钱包（按量计费池）
//   · 额度闸（packages/quota，协-018）：订阅窗口百分比，守的是「接下来几小时还跑不跑得动」
// 合流在这里，是为了让池序降级、编制快照可用性、/tick 归因三处**零额外接线**地跟着走
// （budget 当初就是这么接的，额度闸照抄这条先例）。
//
// 两道闸的失效方向刻意相反，别把它们合并成一个 ok：
//   · budget 缺位 → ok:false → 真跑前提 503 拒跑（钱的事，读不到数就别跑）
//   · quota 缺位 → 照常 ok:true，只在 额度.盲区 里吭声（订阅窗口的事，
//     查不着就把管线卡死是本末倒置——包 README 的红线也是 fail-open）
function 冻结情况(公用件, 配置, 账本根) {
  const 根 = 账本根;
  // 额度闸先算：它自己内部全程不抛（解读件失效也只是返回 失效:true），不会影响下面预算那段。
  let 额度 = null;
  try { 额度 = require('./额度闸').现况(配置, 根); } catch (e) { 额度 = { ok: false, 挡: {}, 盲区: [{ 池: '(全部)', 因: `额度闸不可用：${e.message}` }], 错误: e.message }; }
  try {
    const budget = 公用件.载入('budget', 'budget.js');
    const 冻 = budget.并入({}, budget.冻结池(配置, 根));
    const 挡 = {}; const 警戒 = [];
    // 订阅池的 token 上限**不是刹车，是警戒线**（协-022，实测撞出来）。
    //
    // 2026-08-23：HW-4 派不出去，因为 codex 被冻结——「日用量 1439944 token ≥ 上限 200000」。
    // 而 codex 是订阅池（Codex Plus），它的**周窗口当时只用了 19%**。也就是说：
    // 真实风险（把订阅窗口烧穿、几天干不了活）离得远得很，拦住它的是一个跟风险无关的数字。
    //
    // 那个 200000 是怎么来的？`config/预算.local.json` 自己的注释写着：
    // 「给它配上限只是为了过第三道闸，实际刹车对 codex 无效，这一点要清醒。」
    // ——**为了过闸而编的数**，如今变成了真的拦路石。
    //
    // 订阅池花的不是钱（月费已付，边际成本为零，见 lib/计费.js），能烧穿的只有窗口；
    // 而窗口现在有额度闸真的在管（协-018）。所以：
    //   · 额度闸对这个池**有读数** → token 上限降级为警戒（超了吭声，不冻结），窗口说了算；
    //   · 额度闸对这个池是**盲区** → token 上限照旧冻结**兜底**。没有读数时宁可误刹。
    // api 池不受影响：它按 token 计费，token 上限守的正是钱包，那是刹车不是警戒线。
    const 计费 = require('./计费');
    const 额度明细 = new Map(((额度 && 额度.明细) || []).map((m) => [m.池, m]));
    for (const [池, 信息] of Object.entries(冻)) {
      if (!信息 || !信息.locked) continue;
      const 是订阅 = 计费.模式(配置, 池) === 计费.订阅;
      const m = 额度明细.get(池);
      const 有读数 = !!(m && m.适用 && !m.盲区);
      if (是订阅 && 有读数) {
        警戒.push({ 池, 因: 信息.reason || '预算闸告警',
          说: `订阅池不按 token 刹车：${信息.reason || '超了配置的 token 上限'}。`
            + '它花的不是钱（月费已付），能烧穿的只有订阅窗口，而窗口由额度闸在管'
            + `（当前${m.挡 ? '已被额度闸锁住' : `${(m.窗口 || []).map((w) => `${w.label} ${w.pct}%`).join('、') || '有读数'}，未越线`}）。`
            + '这条只是警戒线——要它真的刹车，请调 config/预算.local.json 里那个数或把该池改成 api 计费。' });
        continue;
      }
      // 括号不能省：`||` 比 `+` 结合得松，写成 `a || 'x' + b` 时那个后缀只会在
      // reason 缺失时才出现——而 reason 恰恰总是有的，于是「兜底冻结」这句永远不会露面。
      挡[池] = (信息.reason || '预算闸冻结')
        + (是订阅 ? '（额度闸此刻是盲区，token 上限兜底冻结——没有读数时宁可误刹）' : '');
    }
    // 同一个池两道闸都挡时，两句因都要留住——只留一句的话，人解掉其中一道
    // 会发现它还是派不出去，而界面上刚刚那条理由已经不见了。
    for (const [池, 因] of Object.entries((额度 && 额度.挡) || {})) {
      挡[池] = 挡[池] ? `${挡[池]}；额度闸：${因}` : `额度闸：${因}`;
    }
    let 账本 = null;
    try { 账本 = 账本体检(budget.账本(根)); } catch { /* 体检本身失败就当没体检 */ }
    return { ok: true, 挡, 原始: 冻, 账本, 额度, ...(警戒.length ? { 警戒 } : {}) };
  } catch (e) {
    return { ok: false, 挡: { ...((额度 && 额度.挡) || {}) }, 错误: `预算闸不可用：${e.message}`, 额度 };
  }
}

// 账本体检 —— 「这份账读全了没有」。
//
// budget.读账 对坏行的处置是**丢弃不抛**。这在读的层面是对的：一次崩在半路的写
// 会留下半截行，为一行坏账让整个闸罢工不划算。但丢弃是**静默**的，于是
// 「账本坏了」和「这个池今天没用过」在返回值上长得一模一样——都是零用量、
// 都不冻结、ok 照旧为 true。而少算用量的方向，恰恰是费钱的方向。
//
// 放在 platform 自己这边而不是 packages/budget：那是双签的共建包，
// 而这条判断是**我方要不要因此停跑**的判断，不该替对方决定他们的产品怎么处置。
// 代价是这里另有一份读账逻辑——只读文件、只数坏行，不参与任何计算，
// 与 budget 的口径无关（它算用量，这里只回答「读全了没有」）。
// 账本文件的路径仍向 budget 要（budget.账本），不在两处各写一遍文件名。
function 账本体检(文件) {
  let raw = null;
  try { raw = fs.readFileSync(文件, 'utf8'); } catch { return { 文件, 存在: false, 行数: 0, 坏行数: 0, 完好: true }; }
  const 行表 = raw.split('\n');
  const 非空 = 行表.filter((l) => l.trim()).length;
  let 行数 = 0; let 坏行数 = 0; let 首个坏行 = 0;
  for (let i = 0; i < 行表.length; i++) {
    const s = 行表[i].trim();
    if (!s) continue;
    行数++;
    let ok = false;
    try { const j = JSON.parse(s); ok = !!(j && j.池); } catch { ok = false; }
    if (!ok) { 坏行数++; if (!首个坏行) 首个坏行 = i + 1; }
  }
  // 末行半截单独标出来：那是写到一半进程没了留下的，最常见也最无害，
  // 和「整份文件成了乱码」不该同等对待。
  const 只坏末行 = 坏行数 === 1 && 首个坏行 === 非空;
  return { 文件, 存在: true, 行数, 坏行数, 首个坏行: 首个坏行 || null, 只坏末行, 完好: 坏行数 === 0 };
}

// 闸③的后半截：**上限吃满没有**。
//
// 「配没配上限」是读配置，稳；「超没超」要载 budget 公用件来算，会失效。
// 而 冻结情况 失效时返回的是 挡:{}——一个池都不冻，跟「都没超」长得**一模一样**。
// 于是闸门静默消失，人看到的仍是「一切正常」。
// 钱这件事上，读不到数就别跑：全线停摆很响，静默放行很贵。干跑不受影响。
function 真跑前提(冻) {
  if (!冻 || 冻.ok !== true) {
    const 因 = (冻 && 冻.错误) || '预算闸读数缺失';
    return {
      准: false, 码: 503,
      错: `${因}。读不到用量就不许真跑——这道闸失效时的表现是「什么都不冻」，`
        + '跟「都没超」分不出来。修好公用件再来，干跑不受影响。',
    };
  }
  // 闸能载入，不代表它算的数是全的。账本有坏行 = 那部分用量没算进去，
  // 而少算的方向就是费钱的方向。
  //
  // 只坏末行**不停**：那是一次写到半路进程没了留下的半截，最多丢一条记录，
  // 为它罢工会让人转头把整道闸关掉——一道会误报的闸，最后一定被绕过去。
  const 账 = 冻.账本;
  if (账 && 账.完好 === false && !账.只坏末行) {
    return {
      准: false, 码: 503,
      错: `预算账本有 ${账.坏行数} 行读不出来（首个在第 ${账.首个坏行} 行，${账.文件}）。`
        + '这些用量没被算进去，而少算的方向就是费钱的方向——修好或挪走这份账本再真跑。干跑不受影响。',
    };
  }
  return { 准: true, ...(账 && !账.完好 ? { 提醒: `账本末行是半截（丢一条记录），已放行：${账.文件}` } : {}) };
}

// 选人：排名 → 过冻结 → 候选链降级（留痕）
// 工单要递进去：router 的 crossProviderReview 靠 task.fm.执行池 知道「原执行方是谁」，
// 才能在评审时优先挑**别家**（同源盲区是真的——同一个模型往往看不出自己的错）。
// 不递的话它拿不到 original，跨厂避让整个失效，而且**不会报错**，只会安静地挑回同一家。
function 选派(仓根, 配置, { 角色, 类别 = '执行', 公用件, 账本根, 工单 = null }) {
  const 排名 = 路由器.rankProviders(仓根, 配置, {
    role: 角色, kind: 类别,
    task: 工单 ? { fm: 工单.fm || {} } : null,
  });
  if (!排名.length) return { ok: false, error: '无候选 Provider：检查是否启用、能力是否匹配' };

  const 冻 = 冻结情况(公用件, 配置, 账本根 || 仓根);
  let 择 = 加固.择候选(排名, 冻.挡);

  // 跨厂避让是**偏好，不是硬性要求**。
  //
  // 两层各自正确，合起来会把活卡死：router 在排名阶段排除了原执行方（跨厂），
  // 预算冻结在这一层才发生。于是「替代者全被冻结」时，剩下的候选是空的——
  // 而原执行方明明可用。实测（海投王 HW-1）：claude 干的活，跨厂排除 claude、
  // codex 被预算闸冻结，结果报「全部候选都不可用」，质检卡死。
  //
  // 同源评审弱于跨厂（同一个模型往往看不出自己的错），但**弱于跨厂 ≠ 不如不判**。
  // 所以退回原执行方，并如实标出来——回执里 跨厂:false，人一眼看得见这次
  // 判官和执行方是同一家，可以自己决定信几分。
  let 同源兜底 = null;
  if (!择.选中 && 类别 !== '执行' && 工单 && 工单.fm && 工单.fm.执行池) {
    const 原 = 路由器.rankProviders(仓根, 配置, { role: 角色, kind: 类别, task: null })
      .filter((c) => c.name === 工单.fm.执行池);
    const 再择 = 加固.择候选(原, 冻.挡);
    if (再择.选中) {
      择 = 再择;
      同源兜底 = `跨厂评审的替代者全不可用，退回原执行方 ${工单.fm.执行池}——`
        + '同源评审弱于跨厂（同一个模型往往看不出自己的错），但弱于跨厂不等于不如不判。';
    }
  }

  if (!择.选中) {
    return {
      ok: false,
      error: '全部候选都不可用',
      跳过: 择.跳过,
      ...(冻.ok ? {} : { 预算闸: 冻.错误 }),
    };
  }
  // adapter 从配置里查：受限参数按适配器分，不知道是哪家就注不对参数。
  const adapter = ((配置.providers || {})[择.选中.name] || {}).adapter || null;
  const 权 = 权限参数(配置, 角色, adapter);
  return {
    ok: true,
    选中: 择.选中.name,
    adapter,
    分数: 择.选中.score,
    理由: 择.选中.reasons,
    降级: 择.降级 || !!同源兜底,
    跳过: 择.跳过,          // 降级必须留痕：不留的话账单与战绩对不上号
    权限: 权,
    // 同源兜底必须说出来。质检的价值全在「另一个模型看一遍」上，
    // 悄悄退回同一家而回执照常写「已判过」，是把这次质检的含金量偷偷降级了。
    ...(同源兜底 ? { 同源兜底 } : {}),
    ...(冻.ok ? {} : { 预算闸: 冻.错误 }),
  };
}

// 工单流转：待投 → 在途，并把派单结果写进 fm。
// 只在**确实要执行**时调用；干跑不流转工单（干跑是演练，不该改变工单状态）。
// 依赖就绪判定（协-004）。
//
// plan.materialize 生成的子单带 fm.依赖，但此前没人检查过——于是子单可以在依赖还没干完时
// 就被派出去，拿到一个缺半截的工作区。DAG 写在工单里却不被执行，等于没有 DAG。
//
// 判据：依赖单必须已「完成」。未完成就拒派，并逐个说清卡在谁身上——
// 只说「依赖未就绪」等于让人自己去翻，那是把排查成本转嫁给使用者。
function 依赖就绪(工单库, 根, 工单) {
  const 依赖 = 工单.fm && 工单.fm.依赖;
  const 表 = Array.isArray(依赖) ? 依赖 : (依赖 ? [依赖] : []);
  if (!表.length) return { ok: true, 依赖单: [] };
  const 未完成 = []; const 缺失 = []; const 依赖单 = [];
  for (const id of 表) {
    const t = 工单库.find(根, String(id));
    if (!t) { 缺失.push(String(id)); continue; }
    // 归档的上游**永远不会完成**——等它就是死等。归进「缺失」而不是「未完成」：
    // 两者的处置不同，前者要改依赖或把上游捞回来，后者只需要等。
    // 混成一类的话，人会一直等一张已经废掉的单。
    if (t.state === '已归档') { 缺失.push(String(id) + '（已归档）'); continue; }
    if (t.state !== '完成') { 未完成.push({ id: t.id, 当前状态: t.state }); continue; }
    依赖单.push(t);
  }
  if (缺失.length || 未完成.length) {
    return {
      ok: false, 依赖单,
      error: '依赖未就绪，拒绝派活'
        + (未完成.length ? `；未完成：${未完成.map((x) => `${x.id}(${x.当前状态})`).join('、')}` : '')
        + (缺失.length ? `；找不到：${缺失.join('、')}` : ''),
      未完成, 缺失,
    };
  }
  return { ok: true, 依赖单 };
}

function 落单(工单库, 根, id, 派单结果) {
  const t = 工单库.find(根, id);
  if (!t) return { ok: false, error: `工单不存在：${id}` };
  if (t.state !== '待投') {
    return { ok: false, error: `只有「待投」的工单可以派发，当前是「${t.state}」` };
  }
  const r = 工单库.move(根, id, '待投', '在途', (fm) => {
    fm.执行池 = 派单结果.选中;
    fm.派单时间 = new Date().toISOString();
    fm.权限模式 = 派单结果.权限.模式;
    if (派单结果.降级) fm.降级留痕 = 派单结果.跳过;
    // worktree.integrate 靠 fm.workspace.commit 找依赖单的检查点，prepare 靠
    // fm.workspace.path 复用已存在的工作树。这两处是 worktree.js 的既有契约——
    // 只写 fm.检查点 它们看不见，依赖集成会**静默跳过所有依赖**（skipped 而非报错）。
    if (派单结果.工作区) {
      fm.workspace = {
        path: 派单结果.工作区.path,
        branch: 派单结果.工作区.branch,
        mode: 派单结果.工作区.mode,
      };
    }
  });
  return r.ok ? { ok: true, id, 状态: '在途', 执行池: 派单结果.选中 } : r;
}

