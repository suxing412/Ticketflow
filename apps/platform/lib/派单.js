// 2026-08-26 HW-4 第四轮实测：判官（codex）把能静态核对的全核对了——接口导出、
// 两个 store 都 implements、service 走注入、8 对迁移、SQL 全参数化——然后卡在同一句话上：
//   typecheck → 缺 vitest/globals 类型，退出码 1
//   unit      → EPERM: mkdir 'tooling\node_modules\.vite-temp'
//   build     → EPERM: mkdir 'services\api\dist'，error TS5033
// 第一条是审阅区没装依赖（协-033 已补）。**后两条不是依赖问题，是 --sandbox read-only**：
// tsc 要写 dist、vitest 要写临时目录，只读沙箱下这两条命令**永远**跑不完。
// 也就是说，凡验收标准里带「跑构建/跑测试」的工单，判官只能出「验不了」——
// 跟协-026 之前执行侧那次是同一个病，只是换到了判官这一侧。
//
// 放宽是不是在拆自己的墙？先看清这堵墙挡的到底是什么：它挡的是**判官改掉它正在判的东西**
// （把不过的顺手修好再判过），不是「判官不许产生任何字节」。tsc 写 dist、vitest 写临时目录，
// 跟前者毫无关系。所以边界重画成两条，缺一不可：
//   ① **空间上**：可写范围收在判官自己那个一次性 detached worktree 里
//      （codex 的 workspace-write 正是这个语义：cwd 之外写不了，网络仍关）。
//      它没有分支、判完 --force 收掉，交付不了任何东西；
//   ② **事后**：判完当场查一次篡改（见 lib/质检.js 的 作废）。动了受管文件的判词一律作废，
//      按判官失败处理待重判。**靠 flag 让它自觉不改是没有保证的，查一次才有。**
//
// 表达不出①的适配器**退回只读**，不许拿全盘放开顶替：claude-cli 只有
// --dangerously-skip-permissions 这一档能让命令真跑起来，而那是全盘的、不是工作区内的
// （它自己的适配器注释就写着「acceptEdits 只放行编辑，测试命令仍会反复被拒」）。
// 缺配置即最严这条不为了让某张单过而破例——要跑命令型验收，把判官派给 codex。
const 默认判官区内可写 = {
  // cwd = 审阅区。codex 的 workspace-write 把写限制在它里面，且默认不开网络。
  'codex-cli': ['--sandbox', 'workspace-write', '--skip-git-repo-check'],
  'command-cli': [],                       // echo 桩没有权限概念，给空表示「不必退回只读」
};

// 选项.审阅区：这一次判官到底有没有一个属于它自己的一次性工作区。
// 没有（没项目 / 没检查点 / 建不起来）就没有「区内」可言，只读——
// 在一个跟被审代码无关的临时目录里给写权，既没用也没有边界。
function 判官参数(配置, adapter, 选项 = {}) {
  // 只读那一档沿用既有的受限参数：reviewer 本来就不在放开白名单里，
  // 两处各写一套的话，人改了配置只有一处生效，而那种漏改看不出来。
  const 只读 = { ...权限参数(配置, 'reviewer', adapter), 判官模式: '只读' };
  if (!选项.审阅区) {
    return { ...只读, 因: '这次没有审阅区（没项目 / 没检查点 / 建不起来），没有「区内」可言 → 只读。' };
  }
  const 权 = (配置.执行 && 配置.执行.权限) || {};
  const 配的 = (权.判官区内可写 || {})[adapter];
  const 参数 = Array.isArray(配的) ? 配的 : 默认判官区内可写[adapter];
  if (!参数) {
    return {
      ...只读,
      因: `适配器 ${adapter || '(未知)'} 没有「只在工作区内可写」的表达方式 → 退回只读。`,
      警告: `判官跑在 ${adapter || '未知适配器'} 上，只读。**命令型验收（跑构建 / 跑测试）会因为写不了 `
        + 'dist 与临时目录而得出「验不了」**，这不是被评审方的问题。要判这类单，'
        + `把判官派给 codex；或在 执行.权限.判官区内可写.${adapter || '<适配器>'} 里显式配一套`
        + '**确实只放开工作区内**的参数——全盘放开的开关不算，那不是这里要的东西。',
    };
  }
  return {
    模式: '受限',
    判官模式: '区内可写',
    adapter: adapter || null,
    参数,
    说明: '判官可写，但只在它自己那个一次性审阅区内（detached、无分支、判完 --force 收掉）——'
      + '否则 tsc 写不了 dist、vitest 写不了临时目录，命令型验收永远是「验不了」。'
      + '判完当场查篡改：动了受管文件的判词作废、按判官失败待重判。',
  };
}

// 写权矛盾 —— 「这张单要落盘，可它的角色在受限模式下写不了」（协-020）。
