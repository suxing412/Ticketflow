//
// 判据放在**派活之前**：读的是配置与工单 frontmatter，零成本、零 token。
// 拦下来时必须给出路——只说「矛盾」等于把问题原样丢回给人。
const 只读标记 = [
  ['--permission-mode', 'plan'],          // claude-cli：plan 模式只读
  ['--sandbox', 'read-only'],             // codex-cli：只读沙箱
];
function 受限即只读(权) {
  const 参 = (权 && 权.参数) || [];
  return 只读标记.some(([a, b]) => {
    const i = 参.indexOf(a);
    return i >= 0 && String(参[i + 1] || '') === b;
  });
}

