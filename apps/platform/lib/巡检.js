// 巡检 —— 找出「没人会主动告诉你」的那类问题（协-004）。
//
// 纯计算，不碰 IO。给它工单快照和当前时刻，它返回一组告警。
//
// 要找的都是**安静的失败**：不会报错、不会中断、只会让活停在那儿。
// 这类问题的共同点是「看起来一切正常」——所以必须有人定期主动去问，
// 而不是等它自己喊。
'use strict';

const 分钟 = 60 * 1000;

// 在途超时：派出去了但迟迟没有回来。
// 可能是执行器挂了、进程被外部杀了、或者服务重启把在跑的活丢了。
// 无论哪种，工单会**永远停在在途**——没人管它就一直占着并发额度。
function 卡在途(在途表, 现在, 阈值毫秒) {
  const 出 = [];
  for (const t of 在途表 || []) {
    const 起 = Date.parse((t.fm && t.fm.派单时间) || '');
    if (!Number.isFinite(起)) {
      // 在途但没有派单时间：多半是人手工挪进来的，或者流转中途崩了。
      出.push({ 级别: '常', 单: t.id, 类型: '在途无派单时间', 说明: '无法判断跑了多久，建议人工看一眼' });
      continue;
    }
    const 龄 = 现在 - 起;
    if (龄 > 阈值毫秒) {
      出.push({
        级别: '急', 单: t.id, 类型: '在途超时',
        说明: `已在途 ${Math.round(龄 / 分钟)} 分钟（阈值 ${Math.round(阈值毫秒 / 分钟)} 分钟）。`
          + '执行器可能已挂或进程被外部杀掉——工单会永远停在这里并一直占着并发额度。',
      });
    }
  }
  return 出;
}

// 零派发：有待投的活，却一张都派不出去。
// 单看某一张的拒派理由都「合理」，但**整体停摆**是另一回事——
// 产线不动了，而每一步都没报错。
function 零派发(待投数, 本轮派出, 本轮跳过) {
  if (!待投数 || 本轮派出) return [];
  const 理由 = {};
  for (const x of 本轮跳过 || []) 理由[x.原因] = (理由[x.原因] || 0) + 1;
  return [{
    级别: '急', 类型: '零派发',
    说明: `有 ${待投数} 张待投但本轮一张都没派出。原因分布：`
      + (Object.entries(理由).map(([k, v]) => `${k}×${v}`).join('；') || '未知'),
  }];
}

// 预算冻结：池被闸住了。这条是「常」不是「急」——闸住是设计行为，
// 但人得知道，否则会以为是平台坏了。
function 预算告警(冻结) {
  return Object.entries(冻结 || {}).map(([池, 因]) => ({
    级别: '常', 类型: '预算冻结', 说明: `池 ${池} 被冻结：${因}。该池的活会顺位到别家或积压。`,
  }));
}

// 依赖死结：一张单依赖的上游**永远不会完成**（上游不存在，或上游反过来依赖它）。
// 这类单会一直卡在待投而不报错——巡检不找出来，它就在那儿躺到天荒地老。
function 依赖死结(全部工单) {
  const 表 = new Map((全部工单 || []).map((t) => [String(t.id), t]));
  const 出 = [];
  for (const t of 全部工单 || []) {
    if (t.state === '完成') continue;
    const 依 = (t.fm && t.fm.依赖) || [];
    const 表依 = Array.isArray(依) ? 依 : [依];
    for (const d of 表依) {
      const id = String(d);
      if (!表.has(id)) {
        出.push({ 级别: '急', 单: t.id, 类型: '依赖缺失', 说明: `依赖的 ${id} 在工单库里找不到——本单永远不会就绪` });
        continue;
      }
      // 只查一层互依（A↔B）。深环留给将来——一层已经覆盖 plan.materialize
      // 能生成的绝大多数情况，而查深环要引图算法，现在加是过度设计。
      const 上 = 表.get(id);
      const 上依 = (上.fm && 上.fm.依赖) || [];
      if ((Array.isArray(上依) ? 上依 : [上依]).map(String).includes(String(t.id))) {
        出.push({ 级别: '急', 单: t.id, 类型: '依赖成环', 说明: `与 ${id} 互相依赖，两张都不会就绪` });
      }
    }
  }
  return 出;
}

// 反复回炉：一张单被判不过多次。
// 单次判不过是正常的——重做就是了。但同一张单反复被打回，说明**问题不在这一轮执行上**：
// 要么验收标准本身写得不可能满足，要么工单描述和判官的理解对不上。
// 再让它自动重跑只是烧钱，得有人去看那张单。
function 反复回炉(全部工单, 战绩, 阈值 = 3) {
  const 次数 = {};
  for (const r of 战绩 || []) {
    // qualityPassed === false 才算被判不过；判官自己失败的不算——那不是工单的错
    if (r.role === 'reviewer' && r.qualityPassed === false && r.ticket) {
      次数[r.ticket] = (次数[r.ticket] || 0) + 1;
    }
  }
  const 出 = [];
  for (const [单, n] of Object.entries(次数)) {
    if (n < 阈值) continue;
    const t = (全部工单 || []).find((x) => x.id === 单);
    if (t && t.state === '完成') continue;         // 后来过了就不必再提
    出.push({
      级别: '急', 单, 类型: '反复回炉',
      说明: `已被判不过 ${n} 次。单次不过是正常的，反复不过说明问题不在这一轮执行上。`
        + '三种可能，按排查成本从低到高：'
        + '① 调质检时喂错了参数（比如变更文件列表与「不许改文件」冲突——实测踩过，'
        + '而且最容易被误判成单子写得烂）；'
        + '② 工单描述与判官的理解对不上；'
        + '③ 验收标准本身不可能满足。'
        + '继续重跑只是烧钱，请人工看这张单。',
    });
  }
  return 出;
}

function 巡一轮(配置, { 全部工单, 现在, 冻结, 本轮派出, 本轮跳过, 战绩 }) {
  const 阈值 = Number((配置.巡检 && 配置.巡检.在途超时毫秒) || 30 * 分钟);
  const 在途 = (全部工单 || []).filter((t) => t.state === '在途');
  const 待投 = (全部工单 || []).filter((t) => t.state === '待投');
  return [
    ...卡在途(在途, 现在, 阈值),
    ...零派发(待投.length, 本轮派出, 本轮跳过),
    ...预算告警(冻结),
    ...依赖死结(全部工单),
    ...反复回炉(全部工单, 战绩, Number((配置.巡检 || {}).回炉阈值) || 3),
  ];
}

module.exports = { 卡在途, 零派发, 预算告警, 依赖死结, 反复回炉, 巡一轮 };
