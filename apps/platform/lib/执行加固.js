// ——————————————————————————————————————————————————————————
// ① 软超时验尸
// ——————————————————————————————————————————————————————————
// 硬超时（到点就 kill）会把「正在慢慢产出」和「已经卡死」一视同仁地砍掉，
// 于是长任务永远做不完，且现场全毁、无从判断死因。
// 软超时的做法：到点先看**还有没有活口**——最近一段时间里有没有新输出。
// 有就续命，没有才验尸；验尸报告带上最后一段输出（活尾巴），让人能看出死在哪。
function 软超时判定({ 现在, 起时, 末次输出时, 上限毫秒, 静默毫秒 = 120000 }) {
  const 已跑 = 现在 - 起时;
  if (已跑 < 上限毫秒) return { 该杀: false, 原因: null };
  const 静默 = 现在 - (末次输出时 || 起时);
  if (静默 < 静默毫秒) {
    // 超时了但还在吐东西 → 续命一个静默窗口，别砍活人
    return { 该杀: false, 原因: '超时但仍有输出，续命', 续命至: 现在 + 静默毫秒 };
  }
  return {
    该杀: true,
    原因: `软超时验尸：已跑 ${Math.round(已跑 / 1000)}s（上限 ${Math.round(上限毫秒 / 1000)}s），`
      + `且最近 ${Math.round(静默 / 1000)}s 无任何输出`,
  };
}

// 活尾巴：验尸报告里带最后 N 行。取尾不取头——死因在尾巴上，开头那段永远是套话。
function 活尾巴(输出, 行数 = 20) {
  const 行 = String(输出 || '').split(/\r?\n/).filter(Boolean);
  return 行.slice(-行数).join('\n');
}

// ——————————————————————————————————————————————————————————
// ② 判官失败不打整单
// ——————————————————————————————————————————————————————————
// 评审/质检环节自己挂了（进程崩、超时、输出不可解析），**不等于被评审的工作不合格**。
// 早期把两者混为一谈，结果是判官一抽风就把好好的工单打成失败，人要手动捞回来。
// 正确做法：判官失败是**判官的**失败，工单维持原状待重判。
function 判官结果归类({ 退出码, 输出, 解析出结论 }) {
  if (退出码 !== 0) {
    return { 类别: '判官失败', 打回工单: false, 说明: `判官进程退出码 ${退出码}——是判官挂了，不是被评审方不合格` };
  }
  if (!String(输出 || '').trim()) {
    return { 类别: '判官失败', 打回工单: false, 说明: '判官零输出——无从判断，不作数' };
  }
  if (解析出结论 == null) {
    return { 类别: '判官失败', 打回工单: false, 说明: '判官输出中找不到结论字段——不猜，按判官失败处理' };
  }
  return { 类别: 解析出结论 ? '通过' : '不过', 打回工单: !解析出结论, 说明: null };
}

// ——————————————————————————————————————————————————————————
// ③ 空输出不作数
// ——————————————————————————————————————————————————————————
// 退出码 0 但一个字都没吐 —— CLI 静默失败的典型形态（登录态过期、参数被吃、管道断）。
// 记成功会双重污染：工单被当作已完成，且路由历史给这家厂商记一笔虚假战绩，
// 于是 rank 会**越来越偏向那个其实什么都没干的 Provider**。
function 成败判定({ 退出码, 输出, 最短有效字符 = 1 }) {
  const 净 = String(输出 || '').trim();
  if (退出码 !== 0) return { 成: false, 原因: `退出码 ${退出码}` };
  if (净.length < 最短有效字符) {
    return { 成: false, 原因: '退出码 0 但输出为空——静默失败，不记成功（记了会污染路由战绩）' };
  }
  return { 成: true, 原因: null };
}

// ——————————————————————————————————————————————————————————
// ④ 候选链降级
// ——————————————————————————————————————————————————————————
// 首选 Provider 不可用（被预算闸冻结 / 禁用 / 能力不匹配）时，按排名顺位往下取，
// 而不是直接失败。**但降级必须留痕**——不留痕的话，用户以为在 A 上跑，实际在 B 上跑，
// 账单和战绩全对不上号。
function 择候选(排名, 不可用) {
  const 挡 = 不可用 || {};
  const 记 = [];
  for (const 候选 of 排名 || []) {
    const 因 = 挡[候选.name];
    if (因) { 记.push({ 名称: 候选.name, 跳过原因: 因 }); continue; }
    return { 选中: 候选, 跳过: 记, 降级: 记.length > 0 };
  }
  return { 选中: null, 跳过: 记, 降级: false };
}

module.exports = { 软超时判定, 活尾巴, 判官结果归类, 成败判定, 择候选 };
