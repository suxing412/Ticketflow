// ——— 运行态落盘（协-019）———
// 自动派发是**运行态**：人可以在界面上开关它，config 里那个只是开机默认。
// server 要回答「待投单到底在等人点，还是自动派发接管了」就得知道这个——
// 而两个进程之间没有共享内存，落一份盘是最笨也最不会坏的传法。
// 顺带把 pid/起于 也写上：进程死了这份文件还在，人能看出它是什么时候没的。
//
// **写的时机就是它的全部价值**（协-021，实测发现）：协-019 只在 上岗/自动开关/停机
// 四个点写，于是 `在跑` 字段永远是开机那一刻的快照——HW-3 真跑到第 5 分钟时，
// 工单明明在「在途」，态文件里的 在跑 还是 `[]`。一个**永远为空的在跑清单**
// 比没有这个字段更坏：它看起来像个答案。所以每次进出在跑清单都补一次写盘。
// 代价是一次几百字节的写，跟一次真跑动辄几分钟比可以忽略。
function 写态(因) {
  try {
    const p = path.join(账本根, 'journal', '执行器态.json');
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, JSON.stringify({
      pid: process.pid, 起于: 起于, 更新于: new Date().toISOString(), 因,
      允许真跑, 自动派发: 自动快照(),
      // 在跑要带够信息：单号说明不了「它在干什么」，而执行与质检的处置完全不同。
      // **只落 起于，不落「已跑多久」**：后者在写盘那一刻算出来就冻住了，而写盘只发生在
      // 进出清单的两个瞬间——于是读到的永远是 0。谁读谁现算（见 server.js 的 /api/attn）。
      在跑: [...在跑单].map(([单, v]) => ({ 单, ...v })),
    }, null, 2) + '\n', 'utf8');
  } catch { /* 写不了就算了：它是旁证不是账本，不该反过来打断执行 */ }
}
const 起于 = new Date().toISOString();

// ——— 优雅停机（协-019）———
//
// 此前 Ctrl-C 直接把进程带走，在跑的工单**没有任何标记**——它会永远停在「在途」，
// 只能等巡检按超时猜。`巡检.js` 自己的注释里就写着这条成因：
// 「可能是执行器挂了、进程被外部杀掉、或者服务重启把在跑的活丢了」。
// 现在显式盖章：谁是被我们自己中断的，与谁是跑太久卡住的，分得开——
// 前者重投是安全的（它根本没跑完），后者得先弄清它在干什么。
//
// **不自动重派**。重派是花钱的决定，留给人（协-019 施工令「不要做」第三条）。
let 停机中 = false;
function 停机(信号) {
  if (停机中) return;
  停机中 = true;
  const 名单 = [...在跑单];
  process.stdout.write(`[执行器] 收到 ${信号}，停机。在跑 ${名单.length} 张，逐张盖章…\n`);
  const 根 = 取工单根();
  let 盖 = 0;
  if (根.ok) {
    for (const [id, 情] of 名单) {
      try {
        const r = 工单库.update(根.根, id, (fm) => {
          // 类别要写进去：被中断的「执行」重投是安全的（活没干完），
          // 被中断的「质检」重判也是安全的（判定没出来）——但这两件事点的按钮不同。
          fm.中断 = `服务停机（${信号}）中断了${情.类别}（池 ${情.池}），未跑完`;
          fm.中断类别 = 情.类别;
          fm.中断于 = new Date().toISOString();
        });
        if (r.ok) 盖++;
      } catch { /* 单张盖不上不影响其余，下面会如实报数 */ }
    }
  }
  if (名单.length) {
    呼叫.急(账本根, '停机中断在途单',
      `执行器收到 ${信号} 停机，${名单.length} 张在跑的单被中断（盖章 ${盖} 张）：${名单.join('、')}。`
      + '这些单没跑完，**不会自动重派**——重派要花额度，得你点。', { 静默秒: 0 });
  }
  写态(`停机(${信号})`);
  try { 服务.close(); } catch { /* 已经关了 */ }
  setTimeout(() => process.exit(0), 500).unref();
}
for (const 信号 of ['SIGINT', 'SIGTERM']) process.on(信号, () => 停机(信号));
// IPC 是 Windows 上**唯一**能让停机处理真正跑起来的通道：node 在 Windows 把
// SIGTERM/SIGINT 映射成无条件终止，上面那两个 handler 在被监工杀掉时一次都不会执行。
// 监工（scripts/开机.js）收摊时先送这条，再落硬杀兜底。
process.on('message', (m) => { if (m && m.停机) 停机(`IPC:${m.停机}`); });

// ——— 额度取数巡回（协-018）———
// 开机取一次，之后每 执行.额度间隔分钟 一次（默认 10）。claude 那一口另有节流盘守着
// （默认 600s 硬间隔 + 失败退避 ×3），间隔调小也不会真的把请求打上去——
// 节流跳过时这里会如实报出来，不会假装取到了。
const 额度间隔毫秒 = Math.max(1, Number((配置.执行 && 配置.执行.额度间隔分钟) || 10)) * 60 * 1000;
// 取数会**起进程**（codex app-server）并**发外网请求**（claude usage）。两种场合要能关掉它：
// 测试（不该因为跑一遍测试就去打厂商的端点）、以及离线/受限网络的机器。
// 关掉不是「假装额度充足」——额度闸照旧 fail-open 并把每个池标成盲区，界面上看得见。
const 不取额度 = String(process.env.PLATFORM_NO_QUOTA_FETCH || '') === '1';
function 额度巡() {
  if (不取额度) { process.stdout.write('[执行器] 额度取数：PLATFORM_NO_QUOTA_FETCH=1，本进程不取数（额度闸恒不锁，接口标盲区）\n'); return; }
  额度取数.取一轮(配置, 账本根).then((r) => {
    const 摘 = (r.动作 || []).map((a) => `${a.池}:${a.结果}${a.因 ? `(${String(a.因).slice(0, 60)})` : ''}`).join(' ');
    // 取数失败**必须响亮**：它失败的表现是「没有池被锁」，跟「额度都还宽裕」一模一样。
    // 一行控制台是这条信息唯一的落点（快照文件里也留了 因，接口的 盲区 字段读它）。
    process.stdout.write(`[执行器] 额度取数：${摘 || '无订阅池，跳过'}\n`);
  }).catch((e) => process.stdout.write(`[执行器] 额度取数异常（额度闸此刻恒不锁）：${e.message}\n`))
    .then(() => { const t = setTimeout(额度巡, 额度间隔毫秒); if (t.unref) t.unref(); });
}
