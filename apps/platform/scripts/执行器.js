// 只读的那几个走 GET。中文路径同样要编码——见下面那段血泪。
function 工作区读(路径, 查询) {
  const 串 = new URLSearchParams(查询 || {}).toString();
  const 编码路径 = String(路径).split('/').map(encodeURIComponent).join('/');
  return new Promise((resolve) => {
    const req = http.request({
      host: '127.0.0.1', port: 工作区端口, path: 编码路径 + (串 ? '?' + 串 : ''), method: 'GET',
      headers: { Authorization: `Bearer ${令牌}` },
    }, (上游) => {
      let s = '';
      上游.on('data', (d) => s += d);
      上游.on('end', () => {
        try { resolve({ 码: 上游.statusCode, 体: JSON.parse(s) }); }
        catch { resolve({ 码: 502, 体: { ok: false, error: '工作区服务返回非 JSON' } }); }
      });
    });
    req.on('error', () => resolve({ 码: 503, 体: { ok: false, error: '工作区服务连不上' } }));
    req.end();
  });
}

// 选项.方法：默认 POST。GET 是给**只读**路由用的（/changes、/含有）——
// 工作区服务把它们特意放在写闸外面，正是因为它们一个 git 对象都不改；
// 这边要是只会 POST，就只能为了读一次状态去走写路由，那等于把读挂在写权限上（协-034）。
function 工作区请求(路径, 体, 选项 = {}) {
  const 方法 = String(选项.方法 || 'POST').toUpperCase();
  return new Promise((resolve) => {
    const 数据 = JSON.stringify(体 || {});
    // 路径里的中文必须编码。node 的 http.request 对未转义字符**直接抛**
    // ERR_UNESCAPED_CHARACTERS——不是返回错误，是同步抛，整个执行器进程就此挂掉。
    // `/write/审阅区`、`/write/收工` 都是中文路径，两条都会踩。
    // 在助手里统一编码，比让每个调用点自己记得靠谱（今天已经在测试里踩过一次同款）。
    let 编码路径 = String(路径).split('/').map(encodeURIComponent).join('/');
    // GET 没有请求体：字段走 query。这里也得编码，审阅区路径里带中文（`审阅-HW-4`），
    // 拼进 path 不编码同样会踩上面那个同步抛。
    if (方法 === 'GET') {
      const q = new URLSearchParams(
        Object.entries(体 || {}).filter(([, v]) => v !== undefined && v !== null).map(([k, v]) => [k, String(v)]),
      ).toString();
      if (q) 编码路径 += `?${q}`;
    }
    const req = http.request({
      host: '127.0.0.1', port: 工作区端口, path: 编码路径, method: 方法,
      headers: {
        Authorization: `Bearer ${令牌}`,
        ...(方法 === 'GET' ? {} : { 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(数据) }),
      },
    }, (上游) => {
      let s = '';
      上游.on('data', (d) => s += d);
      上游.on('end', () => {
        try { resolve({ 码: 上游.statusCode, 体: JSON.parse(s) }); }
        catch { resolve({ 码: 502, 体: { ok: false, error: '工作区服务返回非 JSON' } }); }
      });
    });
    req.on('error', () => resolve({
      码: 503,
      体: { ok: false, error: `工作区服务未在 127.0.0.1:${工作区端口} 应答——提交链需要它。拉起：npm run workspace` },
    }));
    if (方法 !== 'GET') req.write(数据);
    req.end();
  });
}

