/**
 * 等我(root, opts) —— 全系统唯一的「欠人几笔」谓词。
 * @param {object} opts.归属 只看某人的债：'制作人' | '总监'（'双' 归属两边都收）；不传即全收。
 * @returns {{债: Array, 计数: number, 失败: Array, 注册: Array}}
 *   债[i] = { gateKey, 闸号, 闸名, 归属, 落点, 按钮, id, title, 停摆自, 停摆小时 }
 *   按停摆时长降序——最久的排最前，这是催办的天然序，不是按单号或字母序。
 */
function 等我(root, opts = {}) {
  const d = { ...deps默认(), ...(opts.deps || {}) };
  const now = opts.现在 ? new Date(opts.现在).getTime() : Date.now();
  const 谁 = opts.归属 ? String(opts.归属) : null;
  const 表 = 注册表(root);
  const 债 = []; const 失败 = []; const 见过 = new Set();

  for (const g of 表) {
    if (!g.判据) continue;                       // 发起型：无队列，不是「欠着」
    if (谁 && g.归属 !== 谁 && g.归属 !== '双') continue;
    const fn = 判据表[g.判据];
    if (!fn) { 失败.push({ 闸号: g.闸号, 因: '未知判据 ' + g.判据 }); continue; }
    let rows = [];
    try { rows = fn(root, d) || []; }
    catch (e) { 失败.push({ 闸号: g.闸号, 因: String(e.message).slice(0, 120) }); continue; }
    for (const r of rows) {
      const gateKey = g.闸号 + ':' + r.id;
      if (见过.has(gateKey)) continue;            // 幂等：同闸同实体只算一笔
      见过.add(gateKey);
      const ts = r.停摆自 ? new Date(r.停摆自).getTime() : NaN;
      债.push({
        gateKey, 闸号: g.闸号, 闸名: g.名称, 归属: g.归属 || '制作人', 落点: g.落点, 按钮: g.按钮,
        id: r.id, title: r.title || r.id, 停摆自: r.停摆自 || null,
        停摆小时: isNaN(ts) ? null : Math.max(0, Math.round((now - ts) / 36e5 * 10) / 10),
      });
    }
  }
  // 停摆时长降序；时长未知的排最后（不知道多久 ≠ 刚发生，但也不该冒充最久）
  债.sort((a, b) => (b.停摆小时 == null ? -1 : b.停摆小时) - (a.停摆小时 == null ? -1 : a.停摆小时));
  return { 债, 计数: 债.length, 失败, 注册: 表 };
}

/** 超时升格（施工令-061 二·4）：停摆超 T 小时的债。T 缺省 24（总监默认值，候制作人改）。 */
function 逾期(root, T, opts = {}) {
  const t = Number(T == null ? 24 : T);
  return 等我(root, opts).债.filter((x) => x.停摆小时 != null && x.停摆小时 >= t);
}

