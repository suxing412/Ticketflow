/**
 * 填路由(模板, r, 回落) —— 路由占位替换，**全系统只此一处**（消费端不许再按 id 形状猜）。
 * {id} 之外还有 {落页}/{管线} 这类实体自带的段：值一律从债行同名字段取，
 * **任一格取不到就整条回落**，绝不拼出 '#/tickets/undefined' 这种死链（2026-08-22 体检 #67③）。
 * 值按**路径段**编码（先按 / 切开再逐段 encodeURIComponent）：{落页} 装的可能是 'P-1/F-7'
 * 这种两段尾巴，整串 encode 会把斜杠也吃掉，拼出来的 hash 前端一段都认不出。
 */
function 填路由(模板, r, 回落) {
  let h = String(模板 || '');
  if (!h) return null;
  for (;;) {
    const a = h.indexOf('{'); if (a < 0) break;
    const b = h.indexOf('}', a); if (b < 0) break;
    const v = r[h.slice(a + 1, b)];
    if (v == null || v === '') return 回落 || null;
    h = h.slice(0, a) + String(v).split('/').map(encodeURIComponent).join('/') + h.slice(b + 1);
  }
  return h || null;
}

/**
 * 等我(root, opts) —— 全系统唯一的「欠人几笔」谓词。
 * @param {object} opts.归属 只看某人的债：'制作人' | '总监'（'双' 归属两边都收）；不传即全收。
 * @param {string[]} opts.只闸 轻查口（H112 调度器用）：只跑点名的闸号，其余整条跳过。
 *   60s 一拍的今时线调度器没必要每分钟把专项/想法/值守全盘扫一遍——但判据本体仍是这里这一份，
 *   轻查不是第二套口径，只是同一张表少跑几行。
 * @returns {{债: Array, 计数: number, 失败: Array, 注册: Array}}
 *   债[i] = { gateKey, 闸号, 闸名, 归属, 落点, 按钮, id, title, 停摆自, 停摆小时 }
 *   按停摆时长降序——最久的排最前，这是催办的天然序，不是按单号或字母序。
 */
function 等我(root, opts = {}) {
  const d = { ...deps默认(), ...(opts.deps || {}) };
  const now = opts.现在 ? new Date(opts.现在).getTime() : Date.now();
  d.现在 = now; // 判据里凡要看「此刻」的（G20 心跳龄）一律读这格，别各自 Date.now()——那样测不了
  const 谁 = opts.归属 ? String(opts.归属) : null;
  const 只 = Array.isArray(opts.只闸) && opts.只闸.length ? new Set(opts.只闸.map(String)) : null;
  const 表 = 注册表(root);
  const 债 = []; const 失败 = []; const 见过 = new Set();

  for (const g of 表) {
    if (!g.判据) continue;                       // 发起型：无队列，不是「欠着」
    if (只 && !只.has(g.闸号)) continue;          // 轻查口：没点名的闸整条跳过（见函数头注）
    if (谁 && g.归属 !== 谁 && g.归属 !== '双') continue;
    const fn = 判据表[g.判据];
    if (!fn) { 失败.push({ 闸号: g.闸号, 因: '未知判据 ' + g.判据 }); continue; }
    let rows = [];
    try { rows = fn(root, d) || []; }
    catch (e) { 失败.push({ 闸号: g.闸号, 因: String(e.message).slice(0, 120) }); continue; }
    for (const r of rows) {
      const gateKey = g.闸号 + ':' + r.id;
      if (见过.has(gateKey)) continue;            // 幂等：同闸同实体只算一笔
      见过.add(gateKey);
      const ts = r.停摆自 ? new Date(r.停摆自).getTime() : NaN;
      债.push({
        gateKey, 闸号: g.闸号, 闸名: g.名称, 归属: g.归属 || '制作人', 落点: g.落点, 按钮: g.按钮,
        id: r.id, title: r.title || r.id, 停摆自: r.停摆自 || null,
        // 路由随债下发（2026-08-21）：消费端不许再按 id 形状猜跳哪儿。
        // 占位在这里就替换掉——替换规则只许有一处，散到各消费端就是各猜各的。
        路由: 填路由(g.路由, r, g.路由回落),
        停摆小时: isNaN(ts) ? null : Math.max(0, Math.round((now - ts) / 36e5 * 10) / 10),
      });
    }
  }
  // 停摆时长降序；时长未知的排最后（不知道多久 ≠ 刚发生，但也不该冒充最久）
  债.sort((a, b) => (b.停摆小时 == null ? -1 : b.停摆小时) - (a.停摆小时 == null ? -1 : a.停摆小时));
  return { 债, 计数: 债.length, 失败, 注册: 表 };
}

/**
 * 逾期阈值(cfg) —— T 的**唯一取值口**（2026-08-21 体检）。
 * 案源：runner.js 用 `?? 24` 并注明「0 是合法值＝关闭升格」，server.js 的 /api/attn 用 `|| 24`。
 * 于是把 闸值.人闸超时小时 设成 0：runner 侧按「关闭升格」执行，/api/attn 仍按 24 小时判逾期
 * 并把债标红——**两边口径打架，界面照常显示，无任何提示**。
 * 这正是 T=24h 那个旋钮本身，一旦要临时关升格就会踩上。
 * 抽成一处不是为了少写几个字，是**为了让第三处不可能再各写一遍**。
 */
function 逾期阈值(cfg) {
  const v = ((cfg || {}).闸值 || {}).人闸超时小时;
  const n = Number(v ?? 24); // ?? 不是 ||：0 是合法值（=关闭升格），|| 会把它吃成 24
  return Number.isFinite(n) ? n : 24;
}

/** 超时升格（施工令-061 二·4）：停摆超 T 小时的债。T 缺省 24（总监默认值，候制作人改）。 */
function 逾期(root, T, opts = {}) {
  const t = Number(T == null ? 24 : T);
  // T<=0 = **关闭升格**，不是「立刻全红」（2026-08-21 案，2026-08-22 收口）。
  // 口径原本散在调用方各记一遍：runner.js:150 那侧自带 `!(T>0)` 早退，server.js 的 /api/attn 那侧
  // 后来也补了 `T > 0 ? … : []`——两处各记一遍，就等着第三个调用方不知道这回事。
  // 落进判定本身之后，谁调都一个口径；调用方那两处早退保留无害（同值），删不删是他们的事。
  if (!(t > 0)) return [];
  return 等我(root, opts).债.filter((x) => x.停摆小时 != null && x.停摆小时 >= t);
}

