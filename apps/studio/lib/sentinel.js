// sentinel.js — Q20 状态目录互斥哨兵：同号双态即**熔断派发** + 发急件。
//
// 案源（2026-08-18 伪单事故）：制作人往「在途」目录里的单尾追加内容，等于凭空造出一张幻影单，
// 同一单号在两个状态目录各住一份。store.find() 按 STATES 顺序返回第一命中，静默挑了一个；
// 派发引擎照此把 QA 派去审一张近乎空的单，判官出不了判词，链路无限重试约 61 轮 ≈ 117 万 token。
// 整条链上没有任何一处会为「事实源自相矛盾」停下来——这就是本哨兵要补的那一环。
//
// 纪律：
//   · **全线熔断，不是只拦那一张**。目录即状态机是全库不变量，它破了就说明事实源不可信，
//     这时候继续派任何一张单都是在赌。宁可停线等人删掉多余那份，不可再喂一次幻影单。
//   · 急件按冲突签名去重：同一组冲突只喊一次（15 秒一拍的派发循环否则会把信箱刷爆），
//     冲突内容变了、或修好后再复发，照样重喊。journal 与急件同进同退。
//   · 扫不动（权限/路径异常）**不误熔断**：哨兵自己出问题不该把产线拖停。
//   · 本模块只读工单目录、只写 journal/呼叫，不改任何工单。
const store = require('./core/store');

const 上次 = new Map(); // root → 已告警过的冲突签名

function 签名Of(冲突) {
  return (冲突 || []).map((c) => `${c.id}@${(c.状态 || []).join('+')}`).join('；');
}

function 摘要Of(签名) {
  return `派发已熔断（Q20 同号双态）：${签名}。一张单只许住一个状态目录——同号双态说明事实源自相矛盾，`
    + `派发会按目录顺序静默挑一张照派不误（2026-08-18 伪单事故：QA 审幻影单空转约 61 轮 ≈117 万 token）。`
    + `人工删掉多余那一份即自动恢复派发。`;
}

// 熔断判定。opts.静默=true 时只判不喊（给 UI/自检这类高频只读调用用）。
// 返回 { 熔断, 冲突, 签名, 摘要 }。
function 熔断(root, opts = {}) {
  let 冲突;
  try { 冲突 = store.双态(root); } catch { return { 熔断: false, 冲突: [] }; }
  if (!冲突.length) { 上次.delete(root); return { 熔断: false, 冲突: [] }; }
  const 签名 = 签名Of(冲突);
  const 摘要 = 摘要Of(签名);
  if (!opts.静默 && 上次.get(root) !== 签名) {
    上次.set(root, 签名);
    try {
      require('./inbox').post(root, '急', '同号双态', 摘要, 冲突.length === 1 ? { 单号: 冲突[0].id } : undefined);
    } catch { /* 信箱写不动也不能让哨兵自己炸 */ }
    try { require('./journal').append(root, 摘要); } catch { /* 留痕失败不阻塞熔断 */ }
  }
  return { 熔断: true, 冲突, 签名, 摘要 };
}

module.exports = { 熔断, 签名Of, 摘要Of };
