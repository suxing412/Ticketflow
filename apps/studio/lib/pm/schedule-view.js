// pm/schedule-view.js — 排程台账的消费口径（施工令-041 · Q2 三消费接线）
// 040 把「接下来要做什么」立成了计划粒（lib/pm/schedule.js）；本模块回答的是另一个问题：
// **哪一粒该出现在哪张脸上、以什么面目出现**。三消费（流程页 / 总览摘要条 / 晨晚报切片）
// 共用这一份判据，理由与 040 的排序口径同源——三处各判各的，迟早出现
// 「流程页说还有 6 项、总览说 4 项、晨报说 9 项」的三口径打架，而制作人无从知道该信哪个。
//
// 纯函数：不碰 fs、不认 ROOT。调用方（server 路由）把 schedule.现态() 的结果喂进来即可，
// 于是整层可单测——施工令-041 §六.1 的「5 态 × 3 消费 = 15 组呈现断言」正是打在这里，
// 不必起浏览器，也不必造 jsdom。
//
// 一条硬口径（改它就是改「接下来」这个词的含义）：
//   **只有 计划 / 起草中 两态算「接下来」**。已成单/完成的粒在流程页上已经有一张真工单在现身
//   （工单条才是它此刻的脸），再画一条计划粒 = 同一件事在同一行数两遍；撤销 = 已经决定不做了，
//   不占版面。晨晚报切片是唯一例外：它报的是「今天发生了什么」，成单/完成/撤销当日变更都要报。

const 待办态 = ['计划', '起草中'];
const 是待办 = (g) => 待办态.includes(String((g || {}).状态 || ''));

const p2 = (n) => String(n).padStart(2, '0');
// 本地日（YYYY-MM-DD）：晨晚报是给人看的「今天」，必须按本机时区切日。
// 拿 ISO 串前 10 位当日期会把 08:00 之前的 UTC 串算到前一天去（东八区实测差一整天）。
function 本地日(iso) {
  const d = new Date(iso || '');
  return Number.isNaN(d.getTime()) ? null : `${d.getFullYear()}-${p2(d.getMonth() + 1)}-${p2(d.getDate())}`;
}

// 计划卡：三消费共用的呈现体。前端只负责画，不再从原始粒里各取各的字段——
// 「悬浮/点击显示来源与预估」这句话的落点就是 提示 字段，措辞在这里定死一次。
function 卡(g) {
  const x = g || {};
  const 预估 = x.预估单元 == null || x.预估单元 === '' ? null : Number(x.预估单元);
  return {
    粒ID: x.粒ID || null,
    批: x.批 || '',
    型: x.型 || '工单', 上级: x.上级 || null,
    序: Number(x.序) || 0,
    题: x.题 || '',
    状态: x.状态 || '',
    管线: x.管线 || null,
    单号: x.单号 || null,
    // 徽章 = 状态本身，不另造一套词：流程页只出 计划/起草中 两态（起草中 = 已经在起草台上了，
    // 跟纯计划不是一回事，制作人一眼要分得出）；晨晚报切片会出到 已成单/完成/撤销，
    // 若徽章写死「计划」，晚报里一条已完成的粒会挂着「计划」牌子——本令冒烟实测抓到过这一幕。
    徽章: x.状态 || '计划',
    来源: x.来源 || '',
    预估单元: Number.isFinite(预估) ? 预估 : null,
    池衡建议: x.池衡建议 || null,
    提示: `${x.题 || ''}\n来源：${x.来源 || '（未注明）'}\n预估：${Number.isFinite(预估) ? 预估 + ' 单元' : '无'}`
      + (x.池衡建议 ? `\n池衡建议：${x.池衡建议}` : '')
      + (x.状态 === '起草中' ? `\n已在起草台${x.单号 ? '：' + x.单号 : ''}` : ''),
  };
}

// ---- 消费① 流程页 ----
// 管线行：本管线的待办粒，续在已建单队列之后。批字段无管线的（Q 队列）不进管线行——
// 它们是监制台自身的维护活，塞进某条产品管线会让那条线的「接下来」凭空多出不属于它的活。
// 入参已由 schedule.现态() 按 批/序 排好，此处只分桶不重排（排序口径唯一，见 040）。
function 流程页(粒们) {
  const 管线行 = {}; const 维护队列 = [];
  for (const g of (粒们 || [])) {
    if (!是待办(g)) continue;
    const c = 卡(g);
    if (c.管线) (管线行[c.管线] = 管线行[c.管线] || []).push(c);
    else 维护队列.push(c);
  }
  const 计数 = { 管线: Object.values(管线行).reduce((a, x) => a + x.length, 0), 维护: 维护队列.length };
  return { 管线行, 维护队列, 计数, 总数: 计数.管线 + 计数.维护 };
}

// ---- 消费② 总览「今日排程」摘要条 ----
// 一行话回答三问：现在在做什么、接下来是什么、有几件等我。
// 数据三源：runner 执行中（在做）+ 排程现态待办（接下来）+ 决策台待签（等你）。
// 空态不留空格子：三段各有各的空话术，不然横幅会渲染成「现在在做 0（）→ 接下来 0 项（）」。
function 摘要(input) {
  const i = input || {};
  const 在跑 = (i.在跑 || []).filter(Boolean);
  const 待办 = (i.粒们 || []).filter(是待办);
  const 等你 = Math.max(0, Number(i.待签) || 0);
  const 首条题 = 在跑.length ? String(在跑[0].title || 在跑[0].题 || 在跑[0].id || '').slice(0, 40) : null;
  const 下一项题 = 待办.length ? String(待办[0].题 || '').slice(0, 40) : null;
  const 段 = [
    在跑.length ? `现在在做 ${在跑.length}（${首条题}）` : '现在无在做',
    待办.length ? `接下来 ${待办.length} 项（${下一项题}）` : '接下来无计划',
    等你 ? `等你 ${等你} 项` : '无待你处理',
  ];
  return { 在做: 在跑.length, 首条题, 接下来: 待办.length, 下一项题, 等你, 文: 段.join(' → ') };
}

// ---- 消费③ 晨晚报切片（纯读）----
// 当日相关粒 = ①今天状态变更过的（不论转到哪一态，撤销也算——晚报要说得出「今天砍了什么」）
//            + ②仍在计划中的前 N 条（明天要干的活，晨报组稿直接引用）
// 判「变更过」用 更新时刻：登记事件也会写 更新时刻，所以当日新登记的粒天然进①，不必另判。
function 切片(粒们, opts) {
  const o = opts || {};
  const now = typeof o.now === 'number' ? o.now : Date.now();
  const 日 = (!o.日 || o.日 === 'today' || o.日 === '今日') ? 本地日(now) : String(o.日);
  const 上限 = Number.isInteger(o.上限) && o.上限 > 0 ? o.上限 : 5;
  const 变更 = []; const 计划 = [];
  for (const g of (粒们 || [])) {
    const c = 卡(g);
    if (本地日(g.更新时刻 || g.登记时刻) === 日) 变更.push({ ...c, 更新时刻: g.更新时刻 || g.登记时刻 || null });
    else if (是待办(g)) 计划.push(c);
  }
  return {
    日,
    变更,
    计划: 计划.slice(0, 上限),
    计数: { 变更: 变更.length, 计划: 计划.length, 计划已截: Math.max(0, 计划.length - 上限) },
  };
}

// ---- 消费④ 项目内「队列」页（施工令-042 §一）----
// 流程页回答「这条管线现在在做什么、接下来轮到谁」，队列页回答的是另一个问题：
// **这个项目一共排了多少活、按批怎么排的、哪几条被卡着**。三处差别，别把它当流程页的复制品：
//   ① 全量五态（流程页只出待办两态）——「这批还剩几件」必须看得见已完成的那几件才答得出；
//   ② 按 批→序 分组，不按管线分行——批是拍板单位，制作人问的是「批C 还剩什么」；
//   ③ 依赖未满足的粒显式置灰并说出在候谁——队列里最要紧的一句话是「这条为什么还不能开」。

const 终态 = ['完成', '撤销'];    // 粒状态机的终态（粒五态不随 H108 改）
// 依赖指向工单时的「解除」口径（DS-9 · H108）：**只认 归档**——归档=验收过、真做完。
// 新「完成」未经专项级验收（判官过而已），拿它解依赖等于让下游踩在没验收的活上开工，故不算。
// 前置 废弃/挂起 更不解除：它们不是「还没好」而是「不会好/暂停了」，在 依赖判 里单独标成
// 依赖异常（供 P2 立债链开债），不与普通「候前置」混为一谈。
const 单已了 = ['归档'];

// 依赖索引：粒表按粒ID，单号态按单号。两张表都由调用方喂**全量**——
// 依赖可以指向项目视界之外的粒（跨项目的前置活是常态），拿过滤后的表判会把它判成「认不出」。
function 依赖索引(粒们, 单号态) {
  const 粒表 = {};
  for (const g of (粒们 || [])) if (g && g.粒ID) 粒表[String(g.粒ID)] = g;
  return { 粒表, 单号态: 单号态 || {} };
}

// 依赖判据（施工令-042 §一「有未满足依赖的置灰并标『候：xxx』」）：
// 规则逐项带在依赖项上（040 数据层如此），故此处按规则分两组判——
//   全部完成组：每一条都得满足；任一完成组：组内有一条满足即可。
// 认不出的 ref **不据此置灰**（沿用流程页 depsOf 对无法解析依赖的既有处置）：
// 一条指向已被清理的旧单的依赖，若按「未满足」处理，会把一条其实可以开工的活永久钉死在灰里。
// 但也不静默——认不出的 ref 原样回报，提示里写明，制作人自己判断要不要去改依赖。
function 依赖判(g, 索) {
  const 粒表 = (索 && 索.粒表) || {};
  const 单号态 = (索 && 索.单号态) || {};
  const 项 = (Array.isArray((g || {}).依赖) ? g.依赖 : []).map((d) => {
    const ref = String((d || {}).ref || '').trim();
    const 规则 = String((d || {}).规则 || '全部完成');
    const 粒 = 粒表[ref] || null;
    const 单态 = 粒 ? null : (单号态[ref] || null);
    return {
      ref, 规则,
      名: 粒 ? (粒.题 || ref) : ref,
      态: 粒 ? 粒.状态 : 单态,
      认得: !!(粒 || 单态),
      满足: 粒 ? 粒.状态 === '完成' : (单态 ? 单已了.includes(单态) : false),
    };
  }).filter((x) => x.ref);
  const 认得的 = 项.filter((x) => x.认得);
  const 未知 = 项.filter((x) => !x.认得);
  const 全部组 = 认得的.filter((x) => x.规则 !== '任一完成');
  const 任一组 = 认得的.filter((x) => x.规则 === '任一完成');
  const 未满足 = [
    ...全部组.filter((x) => !x.满足),
    ...((任一组.length && !任一组.some((x) => x.满足)) ? 任一组 : []),
  ];
  // DS-9 后半句：卡住这条粒的前置里若有 废弃/挂起 的工单，单独点名——
  // 「候：xxx」是等得来的，「前置已废弃」是等不来的，P2 立债链只认后者。
  // 只从 未满足 里取（任一组已有别的满足项时，组不卡活，不为它白开一条债）。
  const 依赖异常 = 未满足
    .filter((x) => x.态 === '废弃' || x.态 === '挂起')
    .map((x) => `${x.ref} 已${x.态}`);
  return { 依赖数: 项.length, 未满足, 未知, 就绪: !未满足.length, 候: 未满足.length ? 未满足[0].名 : null, 依赖异常 };
}

// 队列卡 = 卡() + 依赖判据。提示在 卡() 那句之上续写「候：X（态）」与「依赖认不出」，
// 措辞仍只定死一次——悬浮显全文这件事三个消费共用同一根字符串。
function 队列卡(g, 索) {
  const c = 卡(g);
  const d = 依赖判(g, 索);
  const 未完 = !终态.includes(c.状态);
  // 置灰只打在**还没成单**的粒上：已成单的粒有一张真工单，它的依赖是工单流程的事（流程页在管）；
  // 已完成/已撤销的更没有「在候谁」可言——给终态粒标「候」是纯噪音。
  const 置灰 = 是待办(g) && !d.就绪;
  return {
    ...c,
    未完,
    依赖数: d.依赖数,
    未满足: d.未满足.map((x) => ({ ref: x.ref, 名: x.名, 态: x.态, 规则: x.规则 })),
    未知依赖: d.未知.map((x) => x.ref),
    依赖异常: d.依赖异常,       // DS-9：['ref 已废弃', 'ref 已挂起', …]——等不来的前置，供 P2 立债
    就绪: d.就绪,
    置灰,
    候: 置灰 ? d.候 : null,
    提示: c.提示
      + (d.未满足.length ? `\n候：${d.未满足.map((x) => x.名 + (x.态 ? `（${x.态}）` : '')).join('、')}` : '')
      + (d.依赖异常.length ? `\n依赖异常：${d.依赖异常.join('、')}（前置等不来，需人裁改依赖或废弃本粒）` : '')
      + (d.未知.length ? `\n依赖 ${d.未知.map((x) => x.ref).join('、')} 认不出（不据此置灰）` : ''),
  };
}

// 项目视界（施工令-042 §一「按管线字段过滤，含无管线的项目相关批」）：
// 计划粒身上没有项目章——040 的字段表里就没有这一格，管线才是它与项目之间唯一的绳子。
// 于是归属这样判（调用方给两份佐证：本项目工单出现过的管线集、本项目工单编号集）：
//   ① 粒挂在本项目的管线上 → 收；
//   ② 粒无管线但已回填的单号是本项目的单 → 收（成了单之后，单号比管线更硬）；
//   ③ **批传染**：同批只要有一粒认亲成功，整批同收——批是拍板单位，
//      一批里前两粒已在本项目管线上跑、后三粒还没排管线，逐粒判会把一批活拦腰砍断，
//      页面上那句「批C 还剩 3 项」就是错的。这正是施工令说的「含无管线的项目相关批」。
//      但明确挂在**别的管线**上的粒不被传染进来（跨项目共用一个批名时不许串味）。
// 项目为空（单项目部署 / 未选项目）＝ 不过滤：那时全部活都是本项目的。
// 判不出归属的粒不静默丢弃——数目原样回报，页面照实说一句「另有 N 粒未归属」。
function 项目视界(粒们, opts) {
  const o = opts || {};
  const 全 = (粒们 || []).filter(Boolean);
  const 项目 = String(o.项目 || '').trim();
  if (!项目) return { 收: 全, 未归属: [] };

  // **有权威字段就不猜**（2026-08-21 三把尺案）。
  // 下面那套「管线/单号/批传染」认亲法，是 待办没有 项目 这一格时的推断术；
  // 当日 待办 补了 项目 字段并回填 122 条之后，推断就该退位——否则同一屏三个数字：
  // 页头按 项目 算 13、队列卡不传参给 37、后端这把旧滤镜只认出 2 条、45 条判「未归属」。
  // 三把尺里错得最离谱的正是这一把，而它错的原因是**它看不见新加的权威字段**。
  // 分两路：带 项目 的直接认（权威）；没带的才落回旧推断（老账兼容，不砸历史条目）。
  const 有章 = 全.filter((g) => g.项目);
  const 无章 = 全.filter((g) => !g.项目);
  const 收 = 有章.filter((g) => String(g.项目) === 项目);
  const 未归属 = [];
  const 外项目 = 有章.filter((g) => String(g.项目) !== 项目); // 明确属于别的项目：不是「未归属」，是别人家的

  const 管线集 = new Set((o.管线集 || []).map((x) => String(x)).filter(Boolean));
  const 单号集 = new Set((o.单号集 || []).map((x) => String(x)).filter(Boolean));
  const 本线 = (g) => !!(g.管线 && 管线集.has(String(g.管线)));
  const 外线 = (g) => !!(g.管线 && !管线集.has(String(g.管线)));
  const 认亲 = (g) => 本线(g) || !!(g.单号 && 单号集.has(String(g.单号)));
  const 本批 = new Set(无章.filter(认亲).map((g) => String(g.批 || '')));
  for (const g of 无章) ((认亲(g) || (本批.has(String(g.批 || '')) && !外线(g))) ? 收 : 未归属).push(g);

  // 排序口径唯一在 040：两路合流后要按入参原序还原，不然分组的「出场序＝入参序」就破了
  const 序 = new Map(全.map((g, i) => [g, i]));
  收.sort((a2, b2) => 序.get(a2) - 序.get(b2));
  return { 收, 未归属, 外项目 };
}

const 合计预估 = (卡们) => Math.round(卡们.reduce((a, c) => a + (Number.isFinite(c.预估单元) ? c.预估单元 : 0), 0) * 100) / 100;

function 队列页(粒们, opts) {
  const o = opts || {};
  const 全 = (粒们 || []).filter(Boolean);
  const 索 = 依赖索引(全, o.单号态);           // 依赖判据吃全量，不吃过滤后的
  const { 收, 未归属, 外项目 = [] } = 项目视界(全, o);
  // 分组轴 = **上级**（2026-08-21 换轴，原为 批）。
  // 制作人：「待办队列里放着的就是专项或是工单，不要给我放什么批什么批，这个会很奇怪，
  // 这不是我们的正常工作单元」——「批」是总监随手起的分组名，四层架构里没有这一层，
  // 实测那一格已混着五种东西（批名/真专项名/战役名/整句任务描述/职能名）。
  // 只按遍历序推组（入参已由 schedule.现态() 按 上级/序 排好，排序口径唯一，此处不重排）。
  // 组名要**读得懂**：F-10 本身没意义，得显示「手修编辑器」。名字由调用方经 o.名册 喂进来
  // （特性/专项各自的权威源在别的模块，本模块是纯函数，不去读盘）。
  const 名册 = o.名册 || {};
  const 组名 = (up) => (up ? (名册[up] ? `${up} ${名册[up]}` : up) : '散单');
  const 序 = []; const 桶 = new Map();
  for (const g of 收) {
    const k = 组名(g.上级);
    if (!桶.has(k)) { 桶.set(k, []); 序.push(k); }
    桶.get(k).push(队列卡(g, 索));
  }
  const 批们 = 序.map((k) => {
    const 粒 = 桶.get(k);
    const 未完 = 粒.filter((c) => c.未完);
    return {
      批: k, 粒,
      计数: { 总: 粒.length, 未完: 未完.length, 完: 粒.length - 未完.length },
      预估: 合计预估(未完),
      // 一批全是终态 = 这批的活已经了了。默认折叠（施工令 §一「已完成批默认折叠」），
      // 但不隐藏——「这批做完了」本身是制作人要看的答案之一。
      完结: 未完.length === 0,
      折叠: 未完.length === 0,
    };
  });
  const 未完数 = 批们.reduce((a, b) => a + b.计数.未完, 0);
  const 预估合计 = 合计预估(批们.flatMap((b) => b.粒.filter((c) => c.未完)));
  return {
    批们,
    // 摘要只数**未完**的活与它们的预估：队列摘要回答的是「还要花多少」，
    // 把已落袋的单元数也加进去，这个数就永远只涨不落，看一眼就知道没用。
    摘要: { 批数: 批们.length, 未完: 未完数, 预估合计, 文: `${批们.length} 批 · ${未完数} 项未完 · 预估合计 ${预估合计} 单元` },
    未归属: 未归属.length,
    // 「别家的」与「判不出归属的」不是一回事，分两个数回（2026-08-21 三把尺案）：
    // 前者有归属只是不归我，后者是真的没写——把两者混成一个数，页面上就说不清
    // 「另有 N 粒未归属」到底该不该有人去补章。
    外项目: 外项目.length,
    空: !批们.length,
    空文: '队列空——批次拍板后由总监/项管登记',
  };
}

// ---- 消费⑤ 主页工程队队列卡（施工令-042 §二）----
// hub 的工程队卡从「当前施工令一行」扩成队列卡：制作人开机第一眼要看见的是
// **监制台自己接下来要修什么**。取的是「整批都没有管线」的批里的待办粒——生产账里正是 Q队列。
//
// 判据比流程页的「监制台维护队列」严一格，是本令冒烟实测逼出来的：流程页按**粒**判（这一粒没管线
// 就进维护队列），于是一条产品批里还没排线的粒（批C·3）会跑到这张卡上，冒充「监制台自己要修的活」。
// 在流程页那是可接受的（那行标的是「无管线归属的计划粒」，如实），在这张卡上就是撒谎。
// 改按**批**判：本批只要有任何一粒挂着管线，整批就是产品线的活，不上工程队卡。
// 不写死批名字符串「Q队列」：批名是人手起的，改一次名这张卡就会默默变空——那种空是查不出来的。
// 流程页的既有口径本令未动（不在令内），差异见回执 §二。
function 工程队队列(粒们, opts) {
  const o = opts || {};
  const 上限 = Number.isInteger(o.上限) && o.上限 > 0 ? o.上限 : 8;
  const 全 = (粒们 || []).filter(Boolean);
  const 索 = 依赖索引(全, o.单号态);
  const 产品批 = new Set(全.filter((g) => g.管线).map((g) => String(g.批 || '')));
  const 全行 = 全.filter((g) => 是待办(g) && !g.管线 && !产品批.has(String(g.批 || ''))).map((g) => 队列卡(g, 索));
  return {
    行: 全行.slice(0, 上限),
    总数: 全行.length,
    余数: Math.max(0, 全行.length - 上限),  // 折叠掉的条数如实回报，不静默截断
    上限,
    预估合计: 合计预估(全行),
    批: [...new Set(全行.map((c) => c.批).filter(Boolean))],
  };
}

