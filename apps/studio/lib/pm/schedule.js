// ---- 排期算术（纯函数 · 零 I/O · 可整片单测）----
// 2026-08-20 制作人：「待办队列的排期全权由项目管理维护并产出一份甘特图，并不断维护，
// 发生延期或是超期完成需要重新排期」。甘特图与「延期/超期」的判定必须是**纯函数**：
// 画图的那一层（前端/视图模块）不该各算各的，算错了也没处单测。写盘的 API 与看图的视图共用这里。

const 天毫秒 = 86400000;
const 日期形 = /^(\d{4})-(\d{2})-(\d{2})$/;
// 规范日期：接 'YYYY-MM-DD' 或完整 ISO 时刻串（取日部分），一律归一成 'YYYY-MM-DD'。
// 归一而不是原样存：字符串比较即日期比较（'2026-08-20' < '2026-09-01'），排序与比大小都不必造 Date。
// 校真实日历：2026-02-30 这种能过正则但不存在的日子必须拦——排期表上一个不存在的截止日
// 会一路静默传到甘特图上，画出来还挺像那么回事。
function 规范日期(v, 名 = '日期') {
  if (v == null || v === '') return { 值: null };
  let s = String(v).trim();
  if (/^\d{4}-\d{2}-\d{2}T/.test(s)) s = s.slice(0, 10);
  const m = 日期形.exec(s);
  if (!m) return { error: `${名}须为 ISO 日期串 YYYY-MM-DD（收到 ${String(v).slice(0, 40)}）` };
  const d = new Date(`${s}T00:00:00Z`);
  if (Number.isNaN(d.getTime()) || d.toISOString().slice(0, 10) !== s) return { error: `${名}不是真实存在的日期：${s}` };
  return { 值: s };
}
// 日差(起, 止)：止 − 起，整数天（同日 = 0，止在前 = 负）。任一缺/坏 → null（不拿 0 冒充「没差」）。
function 日差(起, 止) {
  const a = 规范日期(起); const b = 规范日期(止);
  if (a.error || b.error || !a.值 || !b.值) return null;
  return Math.round((Date.parse(b.值 + 'T00:00:00Z') - Date.parse(a.值 + 'T00:00:00Z')) / 天毫秒);
}

// 工期判定(待办, {今日, 完成日}) —— 延期 / 超期 / 超期完成 的唯一判定处。三者不是一回事：
//   · 延期     ＝ **现计划完成** 晚于 **基线完成**（计划往后挪了。挪的那一刻就成立，与今天几号无关）
//   · 超期     ＝ 还没了结，而今天已经过了现计划完成（说好的日子到了，活还在）
//   · 超期完成 ＝ 已完成，但完成日晚于现计划完成（做完了，只是晚了）
// 基线一经立下不随重排变 → 延期是**累计**的：连挪三次每次三天，延期是 9 天，不是「跟上次比又没延期」。
// 完成日缺省取 完成态粒的 更新时刻（完成是终态，之后不再有事件，那一刻就是完成时刻）。
function 工期判定(待办, opts = {}) {
  const g = 待办 || {};
  const 今日 = 规范日期(opts.今日 || new Date().toISOString(), '今日').值;
  const 计划开始 = 规范日期(g.计划开始).值;
  const 计划完成 = 规范日期(g.计划完成).值;
  const 基线开始 = 规范日期(g.基线开始).值;
  const 基线完成 = 规范日期(g.基线完成).值;
  const 已完成 = g.状态 === '完成';
  const 了结 = 终态.includes(g.状态);
  const 完成日 = 规范日期(opts.完成日 != null && opts.完成日 !== '' ? opts.完成日 : (已完成 ? g.更新时刻 : null)).值;
  const 延期天 = 日差(基线完成, 计划完成);
  const 余量天 = 了结 ? null : 日差(今日, 计划完成);      // 正 = 还有几天，负 = 已经拖了几天
  const 超期完成天 = 已完成 ? 日差(计划完成, 完成日) : null;
  const 超期 = 余量天 != null && 余量天 < 0;
  const 超期完成 = 超期完成天 != null && 超期完成天 > 0;
  return {
    已排期: !!(计划开始 || 计划完成),
    计划开始, 计划完成, 基线开始, 基线完成,
    工期天: g.工期天 == null ? null : Number(g.工期天),
    延期天, 延期: 延期天 != null && 延期天 > 0,
    余量天, 超期, 超期天: 超期 ? -余量天 : (余量天 == null ? null : 0),
    完成日, 超期完成, 超期完成天,
    // 项管的行动信号（制作人原话：「发生延期或是超期完成需要重新排期」）。
    // 只对**未了结**的粒举旗——一张已经超期完成的粒自己无处可重排（终态不可重排），
    // 该重排的是它后面那些还没做的；那件事看的是它们各自的 超期，不是这条已完成粒的旗。
    需重排: 超期,
  };
}

// ---- 校验（登记入口的唯一把关处，整批一条不合法则整批不写，同 roster.apply 口径）----
function 规范依赖(d) {
  if (d == null || d === '') return { 值: [] };
  if (!Array.isArray(d)) return { error: '依赖必须是数组' };
  const out = [];
  for (const it of d) {
    if (!it || typeof it !== 'object') return { error: '依赖项必须是 {ref,规则} 对象' };
    const ref = String(it.ref || '').trim();
    if (!ref) return { error: '依赖项缺 ref（粒ID 或单号）' };
    const 规则 = String(it.规则 || '全部完成').trim();
    if (!依赖规则集.includes(规则)) return { error: `依赖规则只能是 ${依赖规则集.join('/')}（收到 ${规则}）` };
    out.push({ ref: ref.slice(0, 80), 规则 });
  }
  return { 值: out };
}
function 规范粒(raw) {
  const x = raw || {};
  const 批 = String(x.批 ?? '').trim();
  const 题 = String(x.题 ?? '').trim();
  const 来源 = String(x.来源 ?? '').trim();
  if (!批) return { error: '批必填' };
  if (!题) return { error: '题必填' };
  if (!来源) return { error: '来源必填（文档§引用——判重与追溯都靠它）' };
  const 序 = x.序 == null || x.序 === '' ? 0 : Number(x.序);
  if (!Number.isInteger(序) || 序 < 0) return { error: `序须为非负整数（收到 ${x.序}）` };
  const 状态 = String(x.状态 ?? '计划').trim();
  if (!状态全集.includes(状态)) return { error: `未知状态：${状态}（可选 ${状态全集.join('/')}）` };
  const dep = 规范依赖(x.依赖);
  if (dep.error) return { error: dep.error };
  const 单号 = String(x.单号 ?? '').trim();
  // 已成单/完成 必须带单号：没有单号的「已成单」是对不上账的账——迁移终态回填走的正是这条路
  if (['已成单', '完成'].includes(状态) && !单号) return { error: `状态 ${状态} 必须回填单号` };
  let 预估单元 = null;
  if (x.预估单元 != null && x.预估单元 !== '') {
    预估单元 = Number(x.预估单元);
    if (!(预估单元 >= 0) || !Number.isFinite(预估单元)) return { error: `预估单元须为非负数（收到 ${x.预估单元}）` };
  }
  // ── 时间字段（2026-08-20）：没有日期就画不出甘特图。此前白名单里一格时间都没有，
  // 「产出甘特图并维护、延期超期重排」在数据层是**物理上做不到**的（登记时日期会被白名单静默丢掉）。
  // 三格全可选、缺省 null：既有 173 张粒一格都没有，强制必填等于把整本老账判成非法。
  const 始 = 规范日期(x.计划开始, '计划开始'); if (始.error) return { error: 始.error };
  const 终 = 规范日期(x.计划完成, '计划完成'); if (终.error) return { error: 终.error };
  if (始.值 && 终.值 && 始.值 > 终.值) return { error: `计划开始须早于或等于计划完成（收到 ${始.值} → ${终.值}）` };
  let 工期天 = null;
  if (x.工期天 != null && x.工期天 !== '') {
    工期天 = Number(x.工期天);
    if (!(工期天 >= 0) || !Number.isFinite(工期天)) return { error: `工期天须为非负数（收到 ${x.工期天}）` };
  }
  // 就绪：项管排完了、说「这批可以放了」的那面旗。**它不是放行**——放行是 G8 人闸（gatereg 判据
  // 待办候放行 读的正是这一格）。缺了它，那条闸的判据永远筛不出东西，项管页上「待办放行」恒显 0 笔。
  if (x.就绪 != null && x.就绪 !== '' && typeof x.就绪 !== 'boolean') return { error: `就绪须为布尔 true/false（收到 ${String(x.就绪).slice(0, 20)}）` };
  const 就绪 = x.就绪 === true;
  return {
    值: {
      批: 批.slice(0, 40), 序, 题: 题.slice(0, 120), 状态,
      管线: String(x.管线 ?? '').trim().slice(0, 40) || null,
      依赖: dep.值,
      池衡建议: String(x.池衡建议 ?? '').trim().slice(0, 60) || null,
      预估单元,
      计划开始: 始.值, 计划完成: 终.值, 工期天,
      // 基线 = **首次排期**时的计划日期，此后不随重排变——延期正是拿现计划完成跟它比出来的。
      // 登记就带日期的，这一刻就是首次排期；没带日期的基线留空，等第一次 重排 时立。
      // 基线不进入参：它是系统按「首次」这一事实推出来的，开成入参就成了「可以随便宣称的基线」，
      // 那延期天数也就成了可以随便宣称的数。
      基线开始: 始.值, 基线完成: 终.值,
      就绪,
      来源: 来源.slice(0, 200),
      单号: 单号 ? 单号.slice(0, 40) : null,
    },
  };
}

// 拒绝留痕（状态机第 3 条「非法转移一律拒绝并留痕」）：审计事件进账 + journal 一行。
// 留在账里而不是只留 journal——排程账才是这个实体的事实源，翻它就该看得见谁在什么时候想干什么被拦了。
function 拒(root, g, 因, 操作者) {
  const 文 = String(因).slice(0, 200);
  try {
    写事件(root, { 粒ID: g.粒ID, 事件类型: '拒绝', 字段变更: {}, 版本号: g.版本号, 时刻: nowIso(), 操作者: String(操作者 || '').slice(0, 40), 因: 文 });
  } catch (e) { console.error('排程账拒绝留痕失败：' + e.message); }
  journal(root, `排程台账拒绝 ${g.粒ID}「${g.题 || ''}」：${文}`);
  return { ok: false, error: 文, 现态: g };
}

// CAS 校验（第 4 条）：写 API 的公共前置。冲突不进账（重试是正常流量，不该刷审计），
// 但必须把**现态**回给调用方——「拒了」不告诉对方现在是什么样，等于逼它盲猜重试。
function 校验版本(g, 预期版本) {
  if (预期版本 == null || 预期版本 === '') return { error: '预期版本必填（CAS：写前先读现态，把版本号带回来）' };
  const v = Number(预期版本);
  if (!Number.isInteger(v)) return { error: `预期版本须为整数（收到 ${预期版本}）` };
  if (v !== g.版本号) return { error: `版本冲突：预期 ${v}，现 ${g.版本号}——请按现态重试`, 冲突: true };
  return {};
}

