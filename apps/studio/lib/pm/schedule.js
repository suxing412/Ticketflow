// 登记（整批）：新粒入账。幂等按 来源+题 判重，重复项跳过并如实回报（迁移重跑靠它）。
function 登记(root, 粒们, 操作者, opts = {}) {
  if (!Array.isArray(粒们) || !粒们.length) return { ok: false, error: '登记需要非空的待办数组' };
  const 人 = String(操作者 || '').trim();
  if (opts.校验操作域 !== false && !操作域.登记.includes(人)) {
    return { ok: false, 越权: true, error: `登记权在 ${操作域.登记.join('/')}（收到「${人 || '空'}」）` };
  }
  const 已有 = new Map(现态(root).map((g) => [判重键(g), g]));
  const 引用检 = 建引用检(root, opts); // P0-4：调用方注入 opts.查引用 才校验依赖 ref 存在性；opts.强制 旁路
  const 待写 = []; const 跳过 = []; const 错 = [];
  粒们.forEach((raw, i) => {
    const v = 规范粒(raw, 引用检);
    if (v.error) { 错.push(`第 ${i + 1} 条「${String((raw || {}).题 || '').slice(0, 20)}」：${v.error}`); return; }
    const k = 判重键(v.值);
    const 命中 = 已有.get(k);
    if (命中) { 跳过.push({ 题: v.值.题, 来源: v.值.来源, 已有粒ID: 命中.粒ID }); return; }
    已有.set(k, { ...v.值, 粒ID: '(本批)' }); // 同一批里的重复项也算重，否则一次登记就能造出两条同粒
    待写.push(v);
  });
  if (错.length) return { ok: false, error: '整批未写入：' + 错.join('；') }; // 整批校验：一条不合法则一条都不落
  const 时刻 = nowIso();
  const 新增 = 待写.map(({ 值: g, 因 }) => {
    const 粒ID = crypto.randomUUID();
    // 因 走事件顶层不进 字段变更（P0-8）：它是这一次登记动作的审计载荷，不是粒的现态字段
    写事件(root, { 粒ID, 事件类型: '登记', 字段变更: { ...g }, 版本号: 1, 时刻, 操作者: 人, ...(因 ? { 因 } : {}) });
    return { ...g, 粒ID, 版本号: 1, 登记时刻: 时刻, 更新时刻: 时刻, 末次操作者: 人 };
  });
  if (新增.length || 跳过.length) {
    journal(root, `排程台账登记（${人}）：新增 ${新增.length} 粒${跳过.length ? ` · 判重跳过 ${跳过.length} 粒（来源+题）` : ''}`);
  }
  return { ok: true, 新增, 跳过 };
}

// 转移：状态机唯一写口。带 CAS；非法转移拒绝并留痕。
function 转移(root, { 粒ID, 目标, 预期版本, 操作者, 单号, 说明 } = {}, opts = {}) {
  const g = 取(root, 粒ID);
  if (!g) return { ok: false, error: `待办不存在：${粒ID}` };
  const 人 = String(操作者 || '').slice(0, 40);
  const to = String(目标 || '').trim();
  if (!状态全集.includes(to)) return 拒(root, g, `未知目标状态：${to || '空'}（可选 ${状态全集.join('/')}）`, 人);
  const cas = 校验版本(g, 预期版本);
  if (cas.error) return { ok: false, error: cas.error, ...(cas.冲突 ? { 冲突: true } : {}), 现态: g };
  // 已成单→撤销 单列一条拒因：这不是"忘了配转移表"，是**业务上必须先收回工单**。
  // 只回一句「不合法的转移」，调用方会去改状态机；回这句，他会去收单。
  if (g.状态 === '已成单' && to === '撤销') {
    return 拒(root, g, `已成单不可直接撤销——先收回对应工单 ${g.单号 || '(未回填)'}，再撤粒`, 人);
  }
  if (g.状态 === to) return 拒(root, g, `已经是 ${to}，无需转移`, 人);
  if (!转移表[g.状态].includes(to)) {
    return 拒(root, g, `不合法的转移：${g.状态} → ${to}（${g.状态} 只能去 ${转移表[g.状态].join('/') || '无（终态）'}）`, 人);
  }
  // 逐边操作域（2026-08-20）。系统方（台账对齐/派发/派发补链）不受人闸约束——
  // 它们不是"谁在行使权力"，是机器在如实记录已经发生的事实（工单真建出来了、真完成了）。
  // 拿人闸去拦机器回填，只会让台账停在错的状态上，这与人闸要防的事恰好相反。
  const 系统方 = /^系统/.test(人);
  if (opts.校验操作域 !== false && !系统方) {
    const 域 = 转移域[`${g.状态}→${to}`] || 操作域.转移;
    if (!域.includes(人)) {
      return 拒(root, g, `${g.状态}→${to} 的转移权在 ${域.join('/')}（收到「${人 || '空'}」）`
        + (to === '起草中' ? '——派单是人闸：待办进工单队列由总监与制作人按产线节奏放行' : ''), 人);
    }
  }
  const 新单号 = String(单号 || '').trim() || g.单号 || null;
  if (to === '已成单' && !新单号) return 拒(root, g, '转「已成单」必须回填单号', 人);
  const 变更 = { 状态: to };
  if (新单号 !== g.单号) 变更.单号 = 新单号;
  if (String(说明 || '').trim()) 变更.末次说明 = String(说明).trim().slice(0, 200);
  const e = 写事件(root, { 粒ID: g.粒ID, 事件类型: '转移', 字段变更: 变更, 版本号: g.版本号 + 1, 时刻: nowIso(), 操作者: 人 });
  journal(root, `排程粒转移 ${g.粒ID}「${g.题}」：${g.状态} → ${to}${变更.单号 ? ` · 单号 ${变更.单号}` : ''}（${人 || '未署名'}）`);
  return { ok: true, 粒: { ...g, ...变更, 版本号: e.版本号, 更新时刻: e.时刻, 末次操作者: 人 } };
}

// 调整（H99 项管域）：改序 / 改依赖 / 改池衡建议 / 标就绪。带 CAS。
// 只开这四个字段：题/来源是身份（判重键），批/状态各有专路，单号只由钩子回填，
// **排期日期走 重排**（它要留「原计划→新计划＋延期几天」的痕，混进这里就只剩一行「改了几个字段」）——
// 开成通用 patch 口，台账立刻退化成一张可以随便改的表，事件日志就白留了。
function 调整(root, { 粒ID, 预期版本, 序, 依赖, 池衡建议, 就绪, 项目, 型, 上级, 预估单元, 操作者, 说明 } = {}, opts = {}) {
  const g = 取(root, 粒ID);
  if (!g) return { ok: false, error: `待办不存在：${粒ID}` };
  const 人 = String(操作者 || '').trim();
  if (opts.校验操作域 !== false && !操作域.调整.includes(人)) {
    return { ok: false, 越权: true, error: `调整权在 ${操作域.调整.join('/')}（H99 项管域，收到「${人 || '空'}」）` };
  }
  const cas = 校验版本(g, 预期版本);
  if (cas.error) return { ok: false, error: cas.error, ...(cas.冲突 ? { 冲突: true } : {}), 现态: g };
  // 终态闸：终态粒不可改**计划**（序/依赖/就绪/池衡建议都是计划面的东西，活都做完了再改计划是改史）。
  // **归属是唯一的例外**：项目 是分类不是计划。这一格 2026-08-21 才加，存量 122 条全空，其中 82 条
  // 已是完成/撤销——若一并拒掉，历史账就**永远无法归属**，按项目过滤的报表与队列会永久缺一大块，
  // 而那正是加这一格要解决的问题。故：只带 项目 的调整放行终态，掺了别的字段照拒。
  const 仅改归属 = (项目 !== undefined || 型 !== undefined || 上级 !== undefined)
    && [序, 依赖, 池衡建议, 就绪, 预估单元].every((v) => v === undefined || v === '');
  if (终态.includes(g.状态) && !仅改归属) return 拒(root, g, `终态待办不可调整（当前 ${g.状态}）——归属（项目）除外，它是分类不是计划`, 人);
  const 变更 = {};
  if (序 != null && 序 !== '') {
    const n = Number(序);
    if (!Number.isInteger(n) || n < 0) return 拒(root, g, `序须为非负整数（收到 ${序}）`, 人);
    变更.序 = n;
  }
  if (依赖 !== undefined) {
    const d = 规范依赖(依赖, 建引用检(root, opts)); // P0-4：登记/调整 两个写口同一道引用检，不许只堵一头
    if (d.error) return 拒(root, g, d.error, 人);
    if (d.值.some((x) => x.ref === g.粒ID)) return 拒(root, g, '依赖不能指向自己', 人);
    变更.依赖 = d.值;
  }
  if (池衡建议 !== undefined) 变更.池衡建议 = String(池衡建议 || '').trim().slice(0, 60) || null;
  // 预估单元（P0-6 · 2026-08-24 落实表）：进调整白名单。它是排期算力的输入（额度感知排程读它），
  // 项管在排期时修正预估是日常活；但它是计划面字段——终态闸照旧拦（见上面 仅改归属 的口径）。
  if (预估单元 !== undefined) {
    const n = Number(预估单元);
    if (!(n > 0) || !Number.isFinite(n)) return 拒(root, g, `预估单元须为正数（收到 ${String(预估单元).slice(0, 20)}）`, 人);
    变更.预估单元 = n;
  }
  // 项目归属可改（2026-08-21）：122 条存量粒全是空归属——字段是今天才有的，老账只能补。
  // 显式传空串即「退回未归属」，不传即不动（同其余各格的口径）。
  if (项目 !== undefined) 变更.项目 = String(项目 || '').trim().slice(0, 40) || null;
  // 归属轴（型/上级）可改：122 条存量是「批」时代的账，得能补。同 项目 的口径——
  // 归属是**分类**不是计划，故也走终态例外（见下面的终态闸）。
  if (型 !== undefined) {
    const v = String(型 || '').trim();
    if (!型集.includes(v)) return 拒(root, g, `型只能是 ${型集.join('/')}（收到 ${v}）`, 人);
    变更.型 = v;
  }
  if (上级 !== undefined) {
    const v = String(上级 || '').trim();
    if (v && !/^[FS]-\d+$/.test(v)) return 拒(root, g, `上级须为特性号 F-n 或专项号 S-n（收到 ${v}）`, 人);
    const 新型 = 变更.型 || g.型 || '工单';
    if (新型 === '专项' && v && !/^F-\d+$/.test(v)) return 拒(root, g, `型=专项 的上级只能是特性 F-n（收到 ${v}）`, 人);
    变更.上级 = v || null;
  }
  // 就绪：**标就绪 ≠ 放行**。项管排完了把旗举起来（这是它的权），放行成单是 G8 人闸、
  // 归总监与制作人（见 转移域 计划→起草中）。两件事混成一件，就等于让项管自己给自己开闸。
  // 旗只对**计划态**待办有意义：已过闸的粒再举旗，只会往 G8 的清单里塞已经放行过的东西。
  if (就绪 !== undefined) {
    if (typeof 就绪 !== 'boolean') return 拒(root, g, `就绪须为布尔 true/false（收到 ${String(就绪).slice(0, 20)}）`, 人);
    if (就绪 && g.状态 !== '计划') return 拒(root, g, `只有计划态待办能标就绪（当前 ${g.状态}，已过派单闸）`, 人);
    变更.就绪 = 就绪;
  }
  if (!Object.keys(变更).length) return { ok: false, error: '调整未给任何可改字段（序/依赖/池衡建议/就绪/项目/型/上级/预估单元）', 现态: g };
  if (String(说明 || '').trim()) 变更.末次说明 = String(说明).trim().slice(0, 200);
  const e = 写事件(root, { 粒ID: g.粒ID, 事件类型: '调整', 字段变更: 变更, 版本号: g.版本号 + 1, 时刻: nowIso(), 操作者: 人 });
  journal(root, `排程粒调整 ${g.粒ID}「${g.题}」：${Object.keys(变更).filter((k) => k !== '末次说明').join('、')}（${人}）`);
  return { ok: true, 粒: { ...g, ...变更, 版本号: e.版本号, 更新时刻: e.时刻, 末次操作者: 人 } };
}

// 重排（2026-08-20 · 待办队列排期归项管全权维护）：改 计划开始 / 计划完成 / 工期天。
// 操作域同 调整（项管+总监），走 CAS，事件类型「重排」并带上 原计划→新计划 与 延期天数。
//
// 为什么另开一口，不并进 调整：排期的每一次改动都必须留下「从哪天挪到哪天、较基线延了几天、为什么」。
// 这是一张甘特图**唯一能自证**的东西——没有它，三周后没人答得上「这条为什么从 8/20 挪到 9/3」，
// 图就退化成一张随时可以重画、因而毫无约束力的装饰。所以本口**强制带因**。
//
// 首次排期也走这口：原计划为空 → 顺手立基线，延期 0。基线一经立下不再随重排变，
// 于是延期是**累计**的（连挪三次每次三天 = 延期 9 天），不是「跟上次比又没延期」。
// 终态不可重排：一张已经完成/撤销的粒无处可排——制作人说的「超期完成要重新排期」，
// 要重排的是它后面那些还没做的，不是它自己。
function 重排(root, { 粒ID, 计划开始, 计划完成, 工期天, 因, 操作者, 预期版本 } = {}, opts = {}) {
  const g = 取(root, 粒ID);
  if (!g) return { ok: false, error: `待办不存在：${粒ID}` };
  const 人 = String(操作者 || '').trim();
  if (opts.校验操作域 !== false && !操作域.重排.includes(人)) {
    return { ok: false, 越权: true, error: `重排权在 ${操作域.重排.join('/')}（排期由项管主动维护，收到「${人 || '空'}」）` };
  }
  const cas = 校验版本(g, 预期版本);
  if (cas.error) return { ok: false, error: cas.error, ...(cas.冲突 ? { 冲突: true } : {}), 现态: g };
  if (终态.includes(g.状态)) return 拒(root, g, `终态待办不可重排（当前 ${g.状态}）——超期完成后要重排的是后面还没做的那些`, 人);
  if (计划开始 === undefined && 计划完成 === undefined && 工期天 === undefined) {
    return { ok: false, error: '重排未给任何排期字段（计划开始/计划完成/工期天）', 现态: g };
  }
  const 由 = String(因 || '').trim();
  if (!由) return 拒(root, g, '重排必须带因（延期/超期/依赖变更…）——没有因的甘特图没人敢照着排产', 人);

  // 三格各自「不传＝不动，传 null/'' ＝清空」：改完成日不该顺手把开始日抹了。
  // 刻钟计划（H112）：吃两形态，先后比较走 计划毫秒（纯日期按当日 00:00，跨形态字符串比会误判）。
  let 新开始 = 规范计划时刻(g.计划开始).值;
  let 新完成 = 规范计划时刻(g.计划完成).值;
  if (计划开始 !== undefined) {
    const v = 规范计划时刻(计划开始, '计划开始');
    if (v.error) return 拒(root, g, v.error, 人);
    新开始 = v.值;
  }
  if (计划完成 !== undefined) {
    const v = 规范计划时刻(计划完成, '计划完成');
    if (v.error) return 拒(root, g, v.error, 人);
    新完成 = v.值;
  }
  if (新开始 && 新完成 && 计划毫秒(新开始) > 计划毫秒(新完成)) return 拒(root, g, `计划开始须早于或等于计划完成（收到 ${新开始} → ${新完成}）`, 人);
  const 变更 = {};
  if (新开始 !== (规范计划时刻(g.计划开始).值)) 变更.计划开始 = 新开始;
  if (新完成 !== (规范计划时刻(g.计划完成).值)) 变更.计划完成 = 新完成;
  if (工期天 !== undefined) {
    let n = null;
    if (工期天 != null && 工期天 !== '') {
      n = Number(工期天);
      if (!(n >= 0) || !Number.isFinite(n)) return 拒(root, g, `工期天须为非负数（收到 ${工期天}）`, 人);
    }
    if (n !== (g.工期天 == null ? null : Number(g.工期天))) 变更.工期天 = n;
  }
  // 首次排期立基线：既有 173 张粒一格日期都没有，它们的基线就是第一次排出来的那份。
  const 有基线 = !!(规范计划时刻(g.基线完成).值 || 规范计划时刻(g.基线开始).值);
  if (!有基线 && 新完成) { 变更.基线开始 = 新开始; 变更.基线完成 = 新完成; }
  if (!Object.keys(变更).length) return { ok: false, error: '重排未改变任何排期字段（新旧计划一致）', 现态: g };

  const 基线完成 = 变更.基线完成 !== undefined ? 变更.基线完成 : 规范计划时刻(g.基线完成).值;
  const 延期天 = 日差(基线完成, 新完成);   // >0 = 较基线往后挪；首次排期时基线=新计划 → 0（刻钟形归日参与日算术）
  const 原计划 = { 开始: 规范计划时刻(g.计划开始).值, 完成: 规范计划时刻(g.计划完成).值 };
  const 新计划 = { 开始: 新开始, 完成: 新完成 };
  变更.末次说明 = 由.slice(0, 200);
  // 因/原计划/新计划/延期天 走**事件顶层**而不进 字段变更：它们是这一次动作的审计载荷，
  // 不是粒的现态（同 拒绝 事件的 因 一样，折叠时自然不会落进现态）。延期天要看历史就翻事件流。
  const e = 写事件(root, {
    粒ID: g.粒ID, 事件类型: '重排', 字段变更: 变更, 版本号: g.版本号 + 1, 时刻: nowIso(), 操作者: 人,
    因: 由.slice(0, 200), 原计划, 新计划, 延期天,
  });
  journal(root, `待办重排 ${g.粒ID}「${g.题}」：${原计划.完成 || '未排'} → ${新计划.完成 || '未排'}`
    + (延期天 ? ` · 较基线延期 ${延期天} 天` : '') + `（${人}）：${由.slice(0, 60)}`);
  const 果 = { ok: true, 粒: { ...g, ...变更, 版本号: e.版本号, 更新时刻: e.时刻, 末次操作者: 人 }, 原计划, 新计划, 延期天 };
  同步已排期态(root, 果.粒);   // H116：排期即迁态（有计划→已排期；清计划→退回）
  return 果;
}

// ---- H116 已排期态同步（2026-08-26 制作人拍板「待办加已排期小状态」）----
// 排期是粒的事，目录态是单的事——本函数是两者的唯一桥：粒的计划变动后，把对应工单在
// 待派/待重派 ⇄ 已排期 之间迁移。规则：**已排期 = 已放行 ∧ 有计划开始**；
// 排期落上（重排/表态重排/排期作业）→ 待派/待重派 迁入 已排期；计划被清 → 已排期 退回 待派。
// 未放行的单排了期不迁（放行是项管闸，排期不代闸）——放行动作侧（lifecycle）对称补一次同步。
function 同步已排期态(root, g) {
  try {
    if (!g || !g.单号 || !/^[A-Za-z]+-\d+$/.test(String(g.单号))) return;
    const store = require('../core/store');
    const t = store.find(root, g.单号);
    if (!t) return;
    const 有计划 = !!规范计划时刻(g.计划开始).值;
    if (有计划 && ['待派', '待重派'].includes(t.state) && t.fm.放行) {
      const r = store.move(root, t.id, t.state, '已排期', null, nowIso());
      if (r.ok) journal(root, `进已排期 ${t.id}（${t.state}→已排期 · H116 排期即迁态）`);
    } else if (!有计划 && t.state === '已排期') {
      const r = store.move(root, t.id, '已排期', '待派', null, nowIso());
      if (r.ok) journal(root, `退排期 ${t.id}（已排期→待派 · 计划被清，H116）`);
    }
  } catch { /* 迁态失败不拖垮排期写口——单账不同步会被 G 闸巡出来，不静默丢写 */ }
}

// ---- 表态（H112 今时线触发制 + H113 重排类别制 · 2026-08-24 落实表 P2-3）----
// 今时线越线（计划开始≤now 而单还停在待派/待重派）立债给项管，项管消化债的**唯一写口**就是这里。
// 越线强制二选一：决定∈{派发,重排}，无第三值——「无需调整」只留给非越线触发源（巡检/人工点名），且必带因。
// 决定=派发 本函数**只落表态事件与校验**：真正的放行动作由消费方走 lifecycle（转移/派单链）。
// 表态与放行分两步，是因为放行有自己的闸与操作域——混成一步等于给表态口开了绕闸的旁路。
// 决定=重排 必带 类别（H113 五类）+新计划+因；估值变化类须**同事务**携带预估变更（同一条事件落盘）。
// 任何类别推迟累计≥3 次，返回体带 升格:true——消费方据此立债总监，本函数不直接建债（闸债归 gatereg）。
const 重排类别集 = ['前置依赖未到', '额度不够', '并发满', '估值变化', '优先级不够'];
function 表态(root, { 粒ID, 预期版本, 触发源, 决定, 类别, 新计划开始, 新计划完成, 预估单元, 因, 操作者 } = {}, opts = {}) {
  const g = 取(root, 粒ID);
  if (!g) return { ok: false, error: `待办不存在：${粒ID}` };
  const 人 = String(操作者 || '').trim();
  if (opts.校验操作域 !== false && !操作域.表态.includes(人)) {
    return { ok: false, 越权: true, error: `表态权在 ${操作域.表态.join('/')}（越线债消费是项管的活，收到「${人 || '空'}」）` };
  }
  const cas = 校验版本(g, 预期版本);
  if (cas.error) return { ok: false, error: cas.error, ...(cas.冲突 ? { 冲突: true } : {}), 现态: g };
  const 源 = String(触发源 || '').trim().slice(0, 40);
  if (!源) return { ok: false, error: '表态必须带触发源（今时线/巡检/人工…）——没有触发源的表态无从对账', 现态: g };
  const 定 = String(决定 || '').trim();
  const 由 = String(因 || '').trim();
  const 越线 = 源 === '今时线';
  if (!['派发', '重排', '无需调整'].includes(定) || (越线 && 定 === '无需调整')) {
    return 拒(root, g, 越线
      ? `今时线越线强制二选一：决定∈{派发,重排}，无第三值（收到「${定 || '空'}」）`
      : `未知决定：${定 || '空'}（可选 派发/重排/无需调整）`, 人);
  }
  const 给了 = (v) => v !== undefined && v !== null && v !== '';

  if (定 === '派发') {
    if (g.状态 !== '计划') return 拒(root, g, `决定=派发 只对计划态待办有意义（当前 ${g.状态}，已过派单闸）`, 人);
    if (给了(新计划开始) || 给了(新计划完成)) {
      return 拒(root, g, '决定=派发 禁带新计划——要挪日子就表态 重排，派发就是按现计划放行', 人);
    }
    // 表态是审计痕不顶版本（同 拒绝 事件的口径）：真正的转移由消费方带 CAS 走 lifecycle
    写事件(root, { 粒ID: g.粒ID, 事件类型: '表态', 字段变更: {}, 版本号: g.版本号, 时刻: nowIso(), 操作者: 人, 触发源: 源, 决定: 定, ...(由 ? { 因: 由.slice(0, 200) } : {}) });
    journal(root, `待办表态 ${g.粒ID}「${g.题}」：${源} → 派发${g.单号 ? ` · 单号 ${g.单号}` : ''}（${人}）`);
    return { ok: true, 动作: '派发', 单号: g.单号 || null, 粒: 取(root, g.粒ID) };
  }

  if (定 === '无需调整') {
    if (!由) return 拒(root, g, '决定=无需调整 必须带因——不动也要说得清凭什么不动', 人);
    写事件(root, { 粒ID: g.粒ID, 事件类型: '表态', 字段变更: {}, 版本号: g.版本号, 时刻: nowIso(), 操作者: 人, 触发源: 源, 决定: 定, 因: 由.slice(0, 200) });
    journal(root, `待办表态 ${g.粒ID}「${g.题}」：${源} → 无需调整（${人}）：${由.slice(0, 60)}`);
    return { ok: true, 动作: '无需调整', 粒: 取(root, g.粒ID) };
  }

  // 定 === '重排'（H113 重排类别制：类别是归档轴，因才是这一次的实情，两样都要）
  if (终态.includes(g.状态)) return 拒(root, g, `终态待办不可重排（当前 ${g.状态}）`, 人);
  const 类 = String(类别 || '').trim();
  if (!重排类别集.includes(类)) return 拒(root, g, `决定=重排 必带类别 ∈ ${重排类别集.join('/')}（收到「${类 || '空'}」）`, 人);
  if (!由) return 拒(root, g, '决定=重排 必须带因——类别是归档轴，因才是这一次的实情', 人);
  if (!给了(新计划开始) && !给了(新计划完成)) {
    return 拒(root, g, '决定=重排 必带新计划（新计划开始/新计划完成 至少一格）——重排而不给新排期等于没表态', 人);
  }
  let 新开始 = 规范计划时刻(g.计划开始).值;
  let 新完成 = 规范计划时刻(g.计划完成).值;
  if (给了(新计划开始)) { const v = 规范计划时刻(新计划开始, '新计划开始'); if (v.error) return 拒(root, g, v.error, 人); 新开始 = v.值; }
  if (给了(新计划完成)) { const v = 规范计划时刻(新计划完成, '新计划完成'); if (v.error) return 拒(root, g, v.error, 人); 新完成 = v.值; }
  if (新开始 != null && 新完成 != null && 计划毫秒(新开始) > 计划毫秒(新完成)) {
    return 拒(root, g, `计划开始须早于或等于计划完成（收到 ${新开始} → ${新完成}）`, 人);
  }
  const 变更 = {};
  if (新开始 !== 规范计划时刻(g.计划开始).值) 变更.计划开始 = 新开始;
  if (新完成 !== 规范计划时刻(g.计划完成).值) 变更.计划完成 = 新完成;
  if (类 === '估值变化') {
    // 同事务＝同一条事件：预估变更与新计划一次落盘——分两步写，中间断掉就成了「改了估没改期」的半截账
    if (!给了(预估单元)) return 拒(root, g, '类别=估值变化 须同事务携带 预估单元（估没变就不叫估值变化）', 人);
    const n = Number(预估单元);
    if (!(n > 0) || !Number.isFinite(n)) return 拒(root, g, `预估单元须为正数（收到 ${String(预估单元).slice(0, 20)}）`, 人);
    if (n === (g.预估单元 == null ? null : Number(g.预估单元))) return 拒(root, g, `类别=估值变化 的新预估须不同于现值（现 ${g.预估单元}）`, 人);
    变更.预估单元 = n;
  } else if (给了(预估单元)) {
    return 拒(root, g, `预估单元只随 类别=估值变化 走同事务变更（收到类别 ${类}）——别的类别改预估走 调整`, 人);
  }
  if (!('计划开始' in 变更) && !('计划完成' in 变更)) {
    return 拒(root, g, '重排未改变任何排期字段（新计划与现计划一致）——不挪就该表态 派发 或（非越线）无需调整', 人);
  }
  // 首次排期立基线 + 延期算术：与 重排() 同一套口径，别让两口各算各的
  const 有基线 = !!(规范计划时刻(g.基线完成).值 || 规范计划时刻(g.基线开始).值);
  if (!有基线 && 新完成) { 变更.基线开始 = 新开始; 变更.基线完成 = 新完成; }
  // 推迟次数：任何类别混着累计（H112：累计≥3 次升格总监）。进现态字段，闸与页面都读得到。
  const 推迟次数 = (Number(g.推迟次数) || 0) + 1;
  变更.推迟次数 = 推迟次数;
  变更.末次说明 = 由.slice(0, 200);
  const 基线完成 = 变更.基线完成 !== undefined ? 变更.基线完成 : 规范计划时刻(g.基线完成).值;
  const 延期天 = 日差(基线完成, 新完成);
  const 原计划 = { 开始: 规范计划时刻(g.计划开始).值, 完成: 规范计划时刻(g.计划完成).值 };
  const 新计划 = { 开始: 新开始, 完成: 新完成 };
  const e = 写事件(root, {
    粒ID: g.粒ID, 事件类型: '重排', 字段变更: 变更, 版本号: g.版本号 + 1, 时刻: nowIso(), 操作者: 人,
    因: 由.slice(0, 200), 触发源: 源, 决定: 定, 类别: 类, 原计划, 新计划, 延期天,
  });
  journal(root, `待办表态重排 ${g.粒ID}「${g.题}」[${类}]：${原计划.完成 || '未排'} → ${新计划.完成 || '未排'}`
    + (延期天 ? ` · 较基线延期 ${延期天} 天` : '') + (推迟次数 >= 3 ? ` · 累计推迟 ${推迟次数} 次升格总监` : '') + `（${人}）：${由.slice(0, 60)}`);
  const 粒果 = { ...g, ...变更, 版本号: e.版本号, 更新时刻: e.时刻, 末次操作者: 人 };
  同步已排期态(root, 粒果);   // H116：表态重排同样是排期落账（与 重排() 同一座桥）
  return {
    ok: true, 动作: '重排', 粒: 粒果,
    原计划, 新计划, 延期天, 推迟次数, ...(推迟次数 >= 3 ? { 升格: true } : {}),
  };
}

// ── 越线待表态判（H112/G23 · 终审 T2/T3 · 2026-08-24）──
// 「哪些粒在等表态」的**唯一谓词**：gatereg 判据表.今时线越线 与 server GET /api/schedule 的
// 待表态 下发标记共用这一条——两处各写一遍就是两把尺（甘特灰显一套、闸债另一套，正是终审点名的病）。
// 纯函数零 I/O：可派（待派∪待重派 单号集）与 停表（产线闸）由调用方按自己的快照注入。
// 四段判据，缺一即不欠：
//   ① 停表短路（H112 制作人拍板）：产线闸关 = 债在数据层不成立，不是有债不报；
//   ② 计划态才可能欠（已成单/终态的粒线越了也没债）；
//   ③ 有单号的粒：单还窝在 待派/待重派（可派集）才欠——单已在途/落袋 ⇒ 不欠（两把尺病例正身）；
//      无单号的已排期粒：越线即欠（排了日子没成单，防承诺蒸发的那一半）；
//   ④ 越线：计划开始 ≤ 现在（计划毫秒 唯一比较轴，纯日期当日 00:00、一律本地钟面）。
// 表态豁免（终审 T3①）：末次表态时刻 ≥ 越线时刻（=计划开始毫）⇒ 这次越线已被表态（任一决定），
// 债消；表态后计划再挪到未来又越线（新计划开始 > 表态时刻）⇒ 豁免失效，新越线新表态。
function 越线待表态判(g, { 现在, 可派, 停表 } = {}) {
  if (停表) return false;
  if (!g || g.状态 !== '计划') return false;
  if (g.单号 && !(可派 && 可派.has(String(g.单号)))) return false;
  const t = 计划毫秒(g.计划开始);
  const now = Number.isFinite(现在) ? 现在 : Date.now();
  if (t == null || t > now) return false;
  const s = Date.parse(String(g.末次表态时刻 || ''));
  if (Number.isFinite(s) && s >= t) return false; // 表态豁免：删掉这一刀，表态派发后债不消（变异自证）
  return true;
}

// 未排期粒（DS-12 防僵尸单）：状态=计划 且无计划开始 的待办清单。纯读不写，给闸判据（未排期债聚合）与项管页用。
// 「只有完成日没有开始日」也算未排期——今时线触发判据看的就是 计划开始，这一格空着，
// 粒永远不会被今时线扫到，恰是僵尸单的形态。
function 未排期粒(root) {
  return 现态(root).filter((x) => x.状态 === '计划' && !规范计划时刻(x.计划开始).值);
}

// ---- H57 挂接钩子（第 6 条）----
// 两个钩子都是**系统动作**：CAS 的预期版本由钩子自己读现态取——没有第二个调用方跟它抢同一粒，
// 抢的话也该由人那边的 API 拒绝。钩子失败一律只回结果不抛：起草/派发是主干，台账是账，
// 账记不上不能把主干带崩（调用点一律 try 包一层，与 pmLedger.event 同待遇）。

// 起草落草稿：计划 → 起草中 + 回填单号
function 挂钩起草(root, 粒ID, 单号) {
  const g = 取(root, 粒ID);
  if (!g) return { ok: false, error: `待办不存在：${粒ID}`, 无关: true };
  return 转移(root, { 粒ID: g.粒ID, 目标: '起草中', 预期版本: g.版本号, 操作者: '系统·H57起草', 单号, 说明: `项管起草落草稿 ${单号 || ''}` });
}

// 派发：起草中 → 已成单。粒ID 优先，缺则按单号回查（老单 frontmatter 没有 粒ID，认不出就当无关，不猜）。
function 挂钩派发(root, 单号, 粒ID) {
  let g = 粒ID ? 取(root, 粒ID) : null;
  if (!g && 单号) g = 现态(root).find((x) => x.单号 === 单号 && !终态.includes(x.状态)) || null;
  if (!g) return { ok: false, error: '无对应待办（该单不出自排程台账）', 无关: true };
  // 重复派发（收回→重投）不该报错：粒已经是已成单了，这次派发对台账就是个空操作。
  if (g.状态 === '已成单') return { ok: true, 幂等: true, 粒: g };
  // 补链：粒还停在「计划」（工单是手工起草的，没走 /api/pm/draft），先补一步起草中再成单。
  // 宁可补链也不放宽状态机——状态机一旦允许 计划→已成单，「起草中」这一态就名存实亡。
  if (g.状态 === '计划') {
    const r0 = 转移(root, { 粒ID: g.粒ID, 目标: '起草中', 预期版本: g.版本号, 操作者: '系统·派发补链', 单号, 说明: '派发时发现粒仍在计划态，补起草中一步' });
    if (!r0.ok) return r0;
    g = 取(root, g.粒ID);
  }
  return 转移(root, { 粒ID: g.粒ID, 目标: '已成单', 预期版本: g.版本号, 操作者: '系统·派发', 单号: 单号 || g.单号, 说明: `派发 ${单号 || ''}` });
}

// 排期合同消化（2026-08-25「委托项管排期」键）：项管作业会话产 JSON 合同（逐粒计划），
// 本函数代为逐粒走 重排 公开写口落账（操作者=项管）——模型只产计划不碰账，写口纪律不破。
// 逐粒 CAS（消化时现取版本号），单粒失败不回滚如实报（与清算 38 条同口径）。
function 消化排期合同(root, items) {
  const 成 = [], 败 = [];
  for (const it of (Array.isArray(items) ? items : [])) {
    const g = 取(root, String(it.粒ID || ''));
    if (!g) { 败.push({ 粒ID: it.粒ID, error: '粒不存在' }); continue; }
    const r = 重排(root, { 粒ID: g.粒ID, 预期版本: g.版本号,
      计划开始: it.计划开始 || null, 计划完成: it.计划完成 || null, 工期天: it.工期天 != null ? it.工期天 : null,
      因: String(it.因 || '项管排期作业'), 操作者: '项管' });
    if (r.ok) 成.push(g.粒ID); else 败.push({ 粒ID: g.粒ID, error: r.error });
  }
  return { ok: 败.length === 0, 成, 败 };
}

