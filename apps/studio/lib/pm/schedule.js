// 登记（整批）：新粒入账。幂等按 来源+题 判重，重复项跳过并如实回报（迁移重跑靠它）。
function 登记(root, 粒们, 操作者, opts = {}) {
  if (!Array.isArray(粒们) || !粒们.length) return { ok: false, error: '登记需要非空的待办数组' };
  const 人 = String(操作者 || '').trim();
  if (opts.校验操作域 !== false && !操作域.登记.includes(人)) {
    return { ok: false, 越权: true, error: `登记权在 ${操作域.登记.join('/')}（收到「${人 || '空'}」）` };
  }
  const 已有 = new Map(现态(root).map((g) => [判重键(g), g]));
  const 待写 = []; const 跳过 = []; const 错 = [];
  粒们.forEach((raw, i) => {
    const v = 规范粒(raw);
    if (v.error) { 错.push(`第 ${i + 1} 条「${String((raw || {}).题 || '').slice(0, 20)}」：${v.error}`); return; }
    const k = 判重键(v.值);
    const 命中 = 已有.get(k);
    if (命中) { 跳过.push({ 题: v.值.题, 来源: v.值.来源, 已有粒ID: 命中.粒ID }); return; }
    已有.set(k, { ...v.值, 粒ID: '(本批)' }); // 同一批里的重复项也算重，否则一次登记就能造出两条同粒
    待写.push(v.值);
  });
  if (错.length) return { ok: false, error: '整批未写入：' + 错.join('；') }; // 整批校验：一条不合法则一条都不落
  const 时刻 = nowIso();
  const 新增 = 待写.map((g) => {
    const 粒ID = crypto.randomUUID();
    写事件(root, { 粒ID, 事件类型: '登记', 字段变更: { ...g }, 版本号: 1, 时刻, 操作者: 人 });
    return { ...g, 粒ID, 版本号: 1, 登记时刻: 时刻, 更新时刻: 时刻, 末次操作者: 人 };
  });
  if (新增.length || 跳过.length) {
    journal(root, `排程台账登记（${人}）：新增 ${新增.length} 粒${跳过.length ? ` · 判重跳过 ${跳过.length} 粒（来源+题）` : ''}`);
  }
  return { ok: true, 新增, 跳过 };
}

// 转移：状态机唯一写口。带 CAS；非法转移拒绝并留痕。
function 转移(root, { 粒ID, 目标, 预期版本, 操作者, 单号, 说明 } = {}, opts = {}) {
  const g = 取(root, 粒ID);
  if (!g) return { ok: false, error: `待办不存在：${粒ID}` };
  const 人 = String(操作者 || '').slice(0, 40);
  const to = String(目标 || '').trim();
  if (!状态全集.includes(to)) return 拒(root, g, `未知目标状态：${to || '空'}（可选 ${状态全集.join('/')}）`, 人);
  const cas = 校验版本(g, 预期版本);
  if (cas.error) return { ok: false, error: cas.error, ...(cas.冲突 ? { 冲突: true } : {}), 现态: g };
  // 已成单→撤销 单列一条拒因：这不是"忘了配转移表"，是**业务上必须先收回工单**。
  // 只回一句「不合法的转移」，调用方会去改状态机；回这句，他会去收单。
  if (g.状态 === '已成单' && to === '撤销') {
    return 拒(root, g, `已成单不可直接撤销——先收回对应工单 ${g.单号 || '(未回填)'}，再撤粒`, 人);
  }
  if (g.状态 === to) return 拒(root, g, `已经是 ${to}，无需转移`, 人);
  if (!转移表[g.状态].includes(to)) {
    return 拒(root, g, `不合法的转移：${g.状态} → ${to}（${g.状态} 只能去 ${转移表[g.状态].join('/') || '无（终态）'}）`, 人);
  }
  // 逐边操作域（2026-08-20）。系统方（台账对齐/派发/派发补链）不受人闸约束——
  // 它们不是"谁在行使权力"，是机器在如实记录已经发生的事实（工单真建出来了、真完成了）。
  // 拿人闸去拦机器回填，只会让台账停在错的状态上，这与人闸要防的事恰好相反。
  const 系统方 = /^系统/.test(人);
  if (opts.校验操作域 !== false && !系统方) {
    const 域 = 转移域[`${g.状态}→${to}`] || 操作域.转移;
    if (!域.includes(人)) {
      return 拒(root, g, `${g.状态}→${to} 的转移权在 ${域.join('/')}（收到「${人 || '空'}」）`
        + (to === '起草中' ? '——派单是人闸：待办进工单队列由总监与制作人按产线节奏放行' : ''), 人);
    }
  }
  const 新单号 = String(单号 || '').trim() || g.单号 || null;
  if (to === '已成单' && !新单号) return 拒(root, g, '转「已成单」必须回填单号', 人);
  const 变更 = { 状态: to };
  if (新单号 !== g.单号) 变更.单号 = 新单号;
  if (String(说明 || '').trim()) 变更.末次说明 = String(说明).trim().slice(0, 200);
  const e = 写事件(root, { 粒ID: g.粒ID, 事件类型: '转移', 字段变更: 变更, 版本号: g.版本号 + 1, 时刻: nowIso(), 操作者: 人 });
  journal(root, `排程粒转移 ${g.粒ID}「${g.题}」：${g.状态} → ${to}${变更.单号 ? ` · 单号 ${变更.单号}` : ''}（${人 || '未署名'}）`);
  return { ok: true, 粒: { ...g, ...变更, 版本号: e.版本号, 更新时刻: e.时刻, 末次操作者: 人 } };
}

// 调整（H99 项管域）：改序 / 改依赖 / 改池衡建议 / 标就绪。带 CAS。
// 只开这四个字段：题/来源是身份（判重键），批/状态各有专路，单号只由钩子回填，
// **排期日期走 重排**（它要留「原计划→新计划＋延期几天」的痕，混进这里就只剩一行「改了几个字段」）——
// 开成通用 patch 口，台账立刻退化成一张可以随便改的表，事件日志就白留了。
function 调整(root, { 粒ID, 预期版本, 序, 依赖, 池衡建议, 就绪, 操作者, 说明 } = {}, opts = {}) {
  const g = 取(root, 粒ID);
  if (!g) return { ok: false, error: `待办不存在：${粒ID}` };
  const 人 = String(操作者 || '').trim();
  if (opts.校验操作域 !== false && !操作域.调整.includes(人)) {
    return { ok: false, 越权: true, error: `调整权在 ${操作域.调整.join('/')}（H99 项管域，收到「${人 || '空'}」）` };
  }
  const cas = 校验版本(g, 预期版本);
  if (cas.error) return { ok: false, error: cas.error, ...(cas.冲突 ? { 冲突: true } : {}), 现态: g };
  if (终态.includes(g.状态)) return 拒(root, g, `终态待办不可调整（当前 ${g.状态}）`, 人);
  const 变更 = {};
  if (序 != null && 序 !== '') {
    const n = Number(序);
    if (!Number.isInteger(n) || n < 0) return 拒(root, g, `序须为非负整数（收到 ${序}）`, 人);
    变更.序 = n;
  }
  if (依赖 !== undefined) {
    const d = 规范依赖(依赖);
    if (d.error) return 拒(root, g, d.error, 人);
    if (d.值.some((x) => x.ref === g.粒ID)) return 拒(root, g, '依赖不能指向自己', 人);
    变更.依赖 = d.值;
  }
  if (池衡建议 !== undefined) 变更.池衡建议 = String(池衡建议 || '').trim().slice(0, 60) || null;
  // 就绪：**标就绪 ≠ 放行**。项管排完了把旗举起来（这是它的权），放行成单是 G8 人闸、
  // 归总监与制作人（见 转移域 计划→起草中）。两件事混成一件，就等于让项管自己给自己开闸。
  // 旗只对**计划态**待办有意义：已过闸的粒再举旗，只会往 G8 的清单里塞已经放行过的东西。
  if (就绪 !== undefined) {
    if (typeof 就绪 !== 'boolean') return 拒(root, g, `就绪须为布尔 true/false（收到 ${String(就绪).slice(0, 20)}）`, 人);
    if (就绪 && g.状态 !== '计划') return 拒(root, g, `只有计划态待办能标就绪（当前 ${g.状态}，已过派单闸）`, 人);
    变更.就绪 = 就绪;
  }
  if (!Object.keys(变更).length) return { ok: false, error: '调整未给任何可改字段（序/依赖/池衡建议/就绪）', 现态: g };
  if (String(说明 || '').trim()) 变更.末次说明 = String(说明).trim().slice(0, 200);
  const e = 写事件(root, { 粒ID: g.粒ID, 事件类型: '调整', 字段变更: 变更, 版本号: g.版本号 + 1, 时刻: nowIso(), 操作者: 人 });
  journal(root, `排程粒调整 ${g.粒ID}「${g.题}」：${Object.keys(变更).filter((k) => k !== '末次说明').join('、')}（${人}）`);
  return { ok: true, 粒: { ...g, ...变更, 版本号: e.版本号, 更新时刻: e.时刻, 末次操作者: 人 } };
}

// 重排（2026-08-20 · 待办队列排期归项管全权维护）：改 计划开始 / 计划完成 / 工期天。
// 操作域同 调整（项管+总监），走 CAS，事件类型「重排」并带上 原计划→新计划 与 延期天数。
//
// 为什么另开一口，不并进 调整：排期的每一次改动都必须留下「从哪天挪到哪天、较基线延了几天、为什么」。
// 这是一张甘特图**唯一能自证**的东西——没有它，三周后没人答得上「这条为什么从 8/20 挪到 9/3」，
// 图就退化成一张随时可以重画、因而毫无约束力的装饰。所以本口**强制带因**。
//
// 首次排期也走这口：原计划为空 → 顺手立基线，延期 0。基线一经立下不再随重排变，
// 于是延期是**累计**的（连挪三次每次三天 = 延期 9 天），不是「跟上次比又没延期」。
// 终态不可重排：一张已经完成/撤销的粒无处可排——制作人说的「超期完成要重新排期」，
// 要重排的是它后面那些还没做的，不是它自己。
function 重排(root, { 粒ID, 计划开始, 计划完成, 工期天, 因, 操作者, 预期版本 } = {}, opts = {}) {
  const g = 取(root, 粒ID);
  if (!g) return { ok: false, error: `待办不存在：${粒ID}` };
  const 人 = String(操作者 || '').trim();
  if (opts.校验操作域 !== false && !操作域.重排.includes(人)) {
    return { ok: false, 越权: true, error: `重排权在 ${操作域.重排.join('/')}（排期由项管主动维护，收到「${人 || '空'}」）` };
  }
  const cas = 校验版本(g, 预期版本);
  if (cas.error) return { ok: false, error: cas.error, ...(cas.冲突 ? { 冲突: true } : {}), 现态: g };
  if (终态.includes(g.状态)) return 拒(root, g, `终态待办不可重排（当前 ${g.状态}）——超期完成后要重排的是后面还没做的那些`, 人);
  if (计划开始 === undefined && 计划完成 === undefined && 工期天 === undefined) {
    return { ok: false, error: '重排未给任何排期字段（计划开始/计划完成/工期天）', 现态: g };
  }
  const 由 = String(因 || '').trim();
  if (!由) return 拒(root, g, '重排必须带因（延期/超期/依赖变更…）——没有因的甘特图没人敢照着排产', 人);

  // 三格各自「不传＝不动，传 null/'' ＝清空」：改完成日不该顺手把开始日抹了。
  let 新开始 = 规范日期(g.计划开始).值;
  let 新完成 = 规范日期(g.计划完成).值;
  if (计划开始 !== undefined) {
    const v = 规范日期(计划开始, '计划开始');
    if (v.error) return 拒(root, g, v.error, 人);
    新开始 = v.值;
  }
  if (计划完成 !== undefined) {
    const v = 规范日期(计划完成, '计划完成');
    if (v.error) return 拒(root, g, v.error, 人);
    新完成 = v.值;
  }
  if (新开始 && 新完成 && 新开始 > 新完成) return 拒(root, g, `计划开始须早于或等于计划完成（收到 ${新开始} → ${新完成}）`, 人);
  const 变更 = {};
  if (新开始 !== (规范日期(g.计划开始).值)) 变更.计划开始 = 新开始;
  if (新完成 !== (规范日期(g.计划完成).值)) 变更.计划完成 = 新完成;
  if (工期天 !== undefined) {
    let n = null;
    if (工期天 != null && 工期天 !== '') {
      n = Number(工期天);
      if (!(n >= 0) || !Number.isFinite(n)) return 拒(root, g, `工期天须为非负数（收到 ${工期天}）`, 人);
    }
    if (n !== (g.工期天 == null ? null : Number(g.工期天))) 变更.工期天 = n;
  }
  // 首次排期立基线：既有 173 张粒一格日期都没有，它们的基线就是第一次排出来的那份。
  const 有基线 = !!(规范日期(g.基线完成).值 || 规范日期(g.基线开始).值);
  if (!有基线 && 新完成) { 变更.基线开始 = 新开始; 变更.基线完成 = 新完成; }
  if (!Object.keys(变更).length) return { ok: false, error: '重排未改变任何排期字段（新旧计划一致）', 现态: g };

  const 基线完成 = 变更.基线完成 !== undefined ? 变更.基线完成 : 规范日期(g.基线完成).值;
  const 延期天 = 日差(基线完成, 新完成);   // >0 = 较基线往后挪；首次排期时基线=新计划 → 0
  const 原计划 = { 开始: 规范日期(g.计划开始).值, 完成: 规范日期(g.计划完成).值 };
  const 新计划 = { 开始: 新开始, 完成: 新完成 };
  变更.末次说明 = 由.slice(0, 200);
  // 因/原计划/新计划/延期天 走**事件顶层**而不进 字段变更：它们是这一次动作的审计载荷，
  // 不是粒的现态（同 拒绝 事件的 因 一样，折叠时自然不会落进现态）。延期天要看历史就翻事件流。
  const e = 写事件(root, {
    粒ID: g.粒ID, 事件类型: '重排', 字段变更: 变更, 版本号: g.版本号 + 1, 时刻: nowIso(), 操作者: 人,
    因: 由.slice(0, 200), 原计划, 新计划, 延期天,
  });
  journal(root, `待办重排 ${g.粒ID}「${g.题}」：${原计划.完成 || '未排'} → ${新计划.完成 || '未排'}`
    + (延期天 ? ` · 较基线延期 ${延期天} 天` : '') + `（${人}）：${由.slice(0, 60)}`);
  return { ok: true, 粒: { ...g, ...变更, 版本号: e.版本号, 更新时刻: e.时刻, 末次操作者: 人 }, 原计划, 新计划, 延期天 };
}

// ---- H57 挂接钩子（第 6 条）----
// 两个钩子都是**系统动作**：CAS 的预期版本由钩子自己读现态取——没有第二个调用方跟它抢同一粒，
// 抢的话也该由人那边的 API 拒绝。钩子失败一律只回结果不抛：起草/派发是主干，台账是账，
// 账记不上不能把主干带崩（调用点一律 try 包一层，与 pmLedger.event 同待遇）。

// 起草落草稿：计划 → 起草中 + 回填单号
function 挂钩起草(root, 粒ID, 单号) {
  const g = 取(root, 粒ID);
  if (!g) return { ok: false, error: `待办不存在：${粒ID}`, 无关: true };
  return 转移(root, { 粒ID: g.粒ID, 目标: '起草中', 预期版本: g.版本号, 操作者: '系统·H57起草', 单号, 说明: `项管起草落草稿 ${单号 || ''}` });
}

// 派发：起草中 → 已成单。粒ID 优先，缺则按单号回查（老单 frontmatter 没有 粒ID，认不出就当无关，不猜）。
function 挂钩派发(root, 单号, 粒ID) {
  let g = 粒ID ? 取(root, 粒ID) : null;
  if (!g && 单号) g = 现态(root).find((x) => x.单号 === 单号 && !终态.includes(x.状态)) || null;
  if (!g) return { ok: false, error: '无对应待办（该单不出自排程台账）', 无关: true };
  // 重复派发（收回→重投）不该报错：粒已经是已成单了，这次派发对台账就是个空操作。
  if (g.状态 === '已成单') return { ok: true, 幂等: true, 粒: g };
  // 补链：粒还停在「计划」（工单是手工起草的，没走 /api/pm/draft），先补一步起草中再成单。
  // 宁可补链也不放宽状态机——状态机一旦允许 计划→已成单，「起草中」这一态就名存实亡。
  if (g.状态 === '计划') {
    const r0 = 转移(root, { 粒ID: g.粒ID, 目标: '起草中', 预期版本: g.版本号, 操作者: '系统·派发补链', 单号, 说明: '派发时发现粒仍在计划态，补起草中一步' });
    if (!r0.ok) return r0;
    g = 取(root, g.粒ID);
  }
  return 转移(root, { 粒ID: g.粒ID, 目标: '已成单', 预期版本: g.版本号, 操作者: '系统·派发', 单号: 单号 || g.单号, 说明: `派发 ${单号 || ''}` });
}

