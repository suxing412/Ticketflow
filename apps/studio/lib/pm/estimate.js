// pm/estimate.js — 估时自校准（H101 · 施工令-050）。项管职能的固定流程步，不是可选优化。
// 纯函数：**零 I/O、零全局态、不碰 Date.now**——输入历史完结单样本 + 新单基准估值，
// 输出校准后估值 + 校准记录。取数（读工单库 / 读预算账）在 pm/brain.历史样本 里，可注入。
//
// ---- H101（制作人 2026-08-12 21:14 决议）----
// 病灶：切单/起草时 预计时间 与 预计token 是模型按「单元标准 0.25h / 5 万 token」现拍的，
// 拍完就再也没人回头看实际跑了多久——报表 总览.预估偏差pct 早就把这条缝晾在那儿（>100 = 实际超预计），
// 但那个数只进报表不回流估值，于是同一种偏差每张单重犯一次。本模块把那条回路接上：
// 派单前先算「这类单历史上实际是预计的几倍」，用它校准这次的估值。
//
// 章程「估时校准步」四步（正本：AI-GameStudio/协议库/C-规章/项目管理章程.md）：
//   ①取历史 → ②算偏差 → ③校估值 → ④落痕
// 本模块负责 ②③，①在 brain.历史样本，④由 brain 调 pm/ledger.event('估时校准', 记录) 落台账。
// 章程正本在本会话不可达（同「施工令外部文档不可达」教训），故四条规则按施工令-050 §要件① 实装，
// 且全部参数化收在 参数缺省 里——章程正本若与此不符，改的是这一张表，不是散在代码里的字面量。
//
// 四条规则（施工令-050 §要件①）：
//   · 滚动中位比：偏差系数 = 同职能×同单型 近 N 单「实际 ÷ 预计」的**中位**比。
//     中位而非均值，理由同 progress.滚动均时：一张挂起过夜的单能把均值拉到天上去，中位不动摇。
//   · 样本 <3 用全局系数：一两张单的比值不叫偏差，退回全局（不分组）中位比；全局也不足则不校准（系数 1）。
//   · 系数夹 [0.5, 3.0]：校准是纠偏不是放飞——历史再离谱也不许把 0.25h 的单校成 8 小时，
//     也不许把估值压到原值一半以下（压过头会让软超时盯守误报满天飞）。
//   · 粒度取整 0.25h / 万 token：估值是给人看的刻度，不是精算结果。校后至少一格，永不为 0。
const 参数缺省 = {
  最少样本: 3,        // 组内样本 < 此数 → 回退全局系数
  近N: 8,             // 组内滚动窗口：近 8 单
  全局N: 40,          // 全局滚动窗口（比组窗大一档，全局本就是拿量换稳）
  系数下限: 0.5,
  系数上限: 3.0,
  时间粒度: 0.25,     // 小时
  token粒度: 10000,   // 万 token
  样本上限h: 24,      // 超过一天的「实际耗时」多半是挂起/跨夜滞留，不是真干活时长，不进样本
                      // （同 progress.样本上限h 的口径，两处一起改）
};
const 参 = (o) => ({ ...参数缺省, ...(o || {}) });

// 分组键：同职能×同单型。不跨组借数——程序实现单的偏差喂不了美术装配单。
const 分组键 = (职能, 单型) => `${职能 || '—'}|${单型 || '—'}`;

const 数 = (v) => { const n = parseFloat(v); return Number.isFinite(n) ? n : 0; };
const 位 = (v, n) => Math.round(v * 10 ** n) / 10 ** n;
const 中位 = (arr) => {
  const a = [...arr].sort((x, y) => x - y);
  const m = a.length >> 1;
  return a.length % 2 ? a[m] : (a[m - 1] + a[m]) / 2;
};
const 夹 = (v, p) => Math.min(p.系数上限, Math.max(p.系数下限, v));
// 粒度取整：四舍五入到最近一格，下限一格（0 估值等于没估，比不校准更坏）。
const 取整 = (v, 粒) => 位(Math.max(粒, Math.round(v / 粒) * 粒), 6);

/* ===================== ① 取历史 → 比样本（纯，入参已是读好的单表） ===================== */
/**
 * 从完结单表抽「实际÷预计」比样本，时间与 token 两维分开。
 * @param {Array<{id?:string, fm:object, 实耗token?:number}>} 单表
 *        fm 需含 职能/单型/预计时间/预计token/领单时间/交付时间；实耗token 由取数层从预算账归集。
 * @param {object} [opts] 覆盖 参数缺省
 * @returns {{时间:Array, token:Array}} 每条 {职能,单型,比,预计,实际,时刻}
 *
 * 两维各自独立成样本，因为它们的缺席原因不同：
 *   · 实际耗时 = 领单时间 → 交付时间（口径同 report.aggregate 的 实际h 那一列，不另立一套）；
 *   · 实际 token 只有 claude 家族有（施工令-047 流计量只对 stream-json 成立，codex 是不计量池）。
 *     所以 **claude 外池的单只校时间不校 token**——不臆造数字，同「池衡盲区不编数」纪律。
 */
function 比样本(单表, opts) {
  const p = 参(opts);
  const 时间 = []; const token = [];
  for (const t of 单表 || []) {
    const fm = (t && t.fm) || {};
    const 职能 = fm.职能 || '—'; const 单型 = fm.单型 || '—';
    const 时刻 = fm.交付时间 || fm.更新时间 || '';
    const 估h = 数(fm.预计时间);
    const a = Date.parse(fm.领单时间 || ''); const b = Date.parse(fm.交付时间 || '');
    if (估h > 0 && Number.isFinite(a) && Number.isFinite(b) && b > a) {
      const 实h = (b - a) / 3600000;
      if (实h <= p.样本上限h) 时间.push({ 职能, 单型, 比: 实h / 估h, 预计: 估h, 实际: 位(实h, 3), 时刻 });
    }
    const 估tok = 数(fm.预计token); const 实tok = 数(t && t.实耗token);
    if (估tok > 0 && 实tok > 0) token.push({ 职能, 单型, 比: 实tok / 估tok, 预计: 估tok, 实际: 实tok, 时刻 });
  }
  return { 时间, token };
}

/* ===================== ② 算偏差 → 校准表 ===================== */
const 新在前 = (a, b) => String((b && b.时刻) || '').localeCompare(String((a && a.时刻) || ''));

function 维表(样本, p) {
  const 有效 = (样本 || []).filter((s) => s && Number.isFinite(s.比) && s.比 > 0);
  const 全 = [...有效].sort(新在前).slice(0, p.全局N);
  const 全局 = 全.length >= p.最少样本
    ? { 系数: 位(夹(中位(全.map((x) => x.比)), p), 3), 样本数: 全.length }
    : { 系数: 1, 样本数: 全.length, 不足: true };
  const g = new Map();
  for (const s of 有效) {
    const k = 分组键(s.职能, s.单型);
    if (!g.has(k)) g.set(k, []);
    g.get(k).push(s);
  }
  const 组 = {};
  for (const [k, arr] of g) {
    const 近 = [...arr].sort(新在前).slice(0, p.近N);
    if (近.length < p.最少样本) continue; // 样本不足不上台：回退全局，不拿两张单当偏差
    组[k] = { 系数: 位(夹(中位(近.map((x) => x.比)), p), 3), 样本数: 近.length };
  }
  return { 全局, 组 };
}

/**
 * 校准表：两维（时间/token）× 两级（同组/全局）的偏差系数快照。
 * @returns {{时间:{全局:object,组:object}, token:{全局:object,组:object}, 参数:object}}
 * 表是可序列化的纯数据——提示词注入用它、机器复核用它、台账留痕也用它，
 * 三处同一张表才谈得上「提示词自律 + 机器兜底」是同一把尺（041 §四「同一张单两个百分比」的教训）。
 */
function 校准表(样本, opts) {
  const p = 参(opts);
  return { 时间: 维表(样本 && 样本.时间, p), token: 维表(样本 && 样本.token, p), 参数: p };
}

/** 查某维系数。来源三取值：同组中位比 / 全局中位比 / 无样本（系数 1，不动估值）。 */
function 系数查(表, 职能, 单型, 维名) {
  const d = (表 || {})[维名] || {};
  const 命 = (d.组 || {})[分组键(职能, 单型)];
  if (命 && Number.isFinite(命.系数)) return { 系数: 命.系数, 样本数: 命.样本数, 来源: '同组中位比' };
  const g = d.全局;
  if (g && !g.不足 && Number.isFinite(g.系数)) return { 系数: g.系数, 样本数: g.样本数, 来源: '全局中位比' };
  return { 系数: 1, 样本数: (g && g.样本数) || 0, 来源: '无样本' };
}

/* ===================== ③ 校估值 ===================== */
/**
 * 校准一张新单的基准估值。
 * @param {object} o {表, 职能, 单型, 预计时间, 预计token}
 * @returns {{预计时间:number|*, 预计token:number|*, 记录:object}}
 *   记录 = {职能, 单型, 时间:{校前,校后,系数,样本数,来源}, token:{同左}}，直接进台账事件。
 * 基准估值缺失/非数（模型没填）→ 该维原样返回，来源记「无基准」：校准不负责替模型编一个估值出来。
 */
function 校准(o) {
  const i = o || {};
  const 表 = i.表 || {};
  const p = 参(表.参数 || i.参数);
  const 维 = (维名, 原值, 粒) => {
    const base = 数(原值);
    const c = 系数查(表, i.职能, i.单型, 维名);
    if (!(base > 0)) return { 值: null, 记: { 校前: null, 校后: null, 系数: c.系数, 样本数: c.样本数, 来源: '无基准' } };
    if (c.来源 === '无样本') return { 值: base, 记: { 校前: base, 校后: base, 系数: 1, 样本数: c.样本数, 来源: '无样本' } };
    const 校后 = 取整(base * c.系数, 粒);
    return { 值: 校后, 记: { 校前: base, 校后, 系数: c.系数, 样本数: c.样本数, 来源: c.来源 } };
  };
  const 时 = 维('时间', i.预计时间, p.时间粒度);
  const tk = 维('token', i.预计token, p.token粒度);
  return {
    预计时间: 时.值 == null ? i.预计时间 : 时.值,
    预计token: tk.值 == null ? i.预计token : tk.值,
    记录: { 职能: i.职能 || '—', 单型: i.单型 || '—', 时间: 时.记, token: tk.记 },
  };
}

/** 记录 → 一行人话（台账事件与信道贴文共用；晨报对账照这一行读）。 */
function 记录一行(记录) {
  const r = 记录 || {};
  const 段 = (名, x) => {
    if (!x || x.校前 == null) return `${名} 未校（${(x && x.来源) || '无基准'}）`;
    if (x.来源 === '无样本') return `${名} ${x.校前} 不动（无样本）`;
    return `${名} ${x.校前}→${x.校后}（×${x.系数}，${x.来源} ${x.样本数} 样本）`;
  };
  return `${r.职能 || '—'}×${r.单型 || '—'}：${段('时间', r.时间)}｜${段('token', r.token)}`;
}

/* ===================== 提示词块（注入切单/起草会话） ===================== */
// 「提示词自律 + 机器兜底」的自律那一半：把表和纪律一起给模型看。
// 机器兜底那一半在 brain.校准落fm——所以这段话里明写「拍出来的值不作数」，不是吓唬，是实况。
function 提示词块(表, opts) {
  const p = 参((表 || {}).参数 || opts);
  const 行 = [
    '=== 估时校准表（H101 · 章程「估时校准步」，项管固定流程，不可跳过）===',
    `口径：校准系数 = 同职能×同单型 近 ${p.近N} 单「实际 ÷ 预计」的中位比；组样本 < ${p.最少样本} 回退全局系数；`
      + `系数夹 [${p.系数下限}, ${p.系数上限}]；估值粒度 ${p.时间粒度}h / ${p.token粒度 / 10000} 万 token。`,
    '**你填的 预计时间 / 预计token 必须是「基准估值 × 下表对应系数」（按本单 职能×单型 查，查不到用全局），'
      + '并在拆单简报/起草说明里写出这次引用了哪一格与算式——不得自由拍值。**',
    '机器兜底：落盘前监制台会用同一张表复核并改写这两个字段，拍出来的值不作数，只会让简报与工单对不上（自己打自己的脸）。',
  ];
  if (!表) {
    行.push('本次取数失败或工单库无完结单——**无历史可校，按基准估值原样填**，并在简报里如实写「无样本，未校准」。');
    return 行.join('\n');
  }
  const 维行 = (名, d) => {
    const g = d.全局 || {};
    行.push(g.不足
      ? `【${名}】全局：样本 ${g.样本数 || 0} 不足 ${p.最少样本} → 无样本，本维不校准（估值原样填）`
      : `【${名}】全局系数 ×${g.系数}（${g.样本数} 样本）`);
    const 组 = Object.entries(d.组 || {}).sort((a, b) => b[1].样本数 - a[1].样本数);
    for (const [k, v] of 组) 行.push(`  · ${k.replace('|', '×')}：×${v.系数}（${v.样本数} 样本）`);
    if (!组.length) 行.push('  · （无够样本的分组，全部按全局系数）');
  };
  维行('时间', 表.时间 || {});
  维行('token', 表.token || {});
  行.push('注：token 维只统计得到 claude 家族的实耗（施工令-047 流计量）——'
    + 'codex 是不计量池，那些单只进时间维，不编 token 数。');
  return 行.join('\n');
}

