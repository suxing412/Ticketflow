// 项目落点.js — 起草落盘前的「项目落点一查」（TF-13）
//
// 案源（2026-08-26 一日六例：TK-183/184/197/205/210 …）：模式一律是「监制台/Ticketflow 自身的活
// 被开成 TK 号段单」。执行会话的 cwd 由项目字段派生，TK 沙箱够不着 Ticketflow 工作区，
// 于是必然评估回呈——每例烧一次执行会话 ＋ 一轮裁决。TF-5 就是 TK-184 移编后的替代单，
// 返工成本已有实例。这一查把错配挡在 store.create 之前：号不消耗、盘不落、账不动。
//
// 为什么单独成模块：判定逻辑必须能脱开 spawn 直测（brain.draftTicket 整条链要起假 CLI 才跑得动），
// 所以这里只留纯函数——不碰盘、不读环境、不看 process.env，输入全从参数来。
// brain.js 那边只留接线两行。
//
// 前缀不写死（施工令-061）：项目名 → 号段前缀的事实源是 cfg.项目.注册，
// 这里一律走 brain.前缀Of 取。require 放在函数体内是为了避开与 brain.js 的循环加载——
// brain 在模块体里 require 本模块，本模块若也在模块体里 require brain，拿到的是半成品 exports。
// 调用时刻 brain 早已加载完毕，惰性取值即可，且 require 有缓存，不构成热路径开销。

// 归一化（规则①）：转小写、反斜杠统一成正斜杠。派单文本里 D:\GitHub\Ticketflow 与
// d:/github/ticketflow 是同一件事，特征表只维护一种形。
function 归一(s) { return String(s || '').toLowerCase().replace(/\\/g, '/'); }

// 规则②·强特征（路径形）：这些串出现在需求/正文里，几乎不可能是在说游戏侧的活。
// 命中任一即判疑似 Ticketflow，且不被 TK 反证豁免（见规则⑤）。
const 强特征 = ['apps/studio', 'd:/github/ticketflow', 'studio.config.json', 'lib/pm/'];

// 规则③·TK 写区反证：明写了游戏工程的落点，说明作者心里的写区是 TK。
// 只用来豁免弱特征，压不过强特征。
const TK反证 = ['d:/github/tk', 'assets/'];

// 规则④·弱特征（名词形）：单个词不作数——TK 单正文写「回执贴进监制台」是日常，
// 一词即判会把正常单成片误杀。要 ≥2 个**不同**弱词同时出现才判疑似。
//
// 【2026-08-27 双靶改造（议程第 27 条，制作人拍板「注册，但活存储设禁写区」）】
// 原表把这些词全判给 Ticketflow，那是错的——它们指的是**监制台运行数据根**里的实体，
// 不是源码仓里的文件。TK-193「49 条待拍板分堆」与 TK-205「僵尸台账清账」在装了闸之后
// **仍然错配**，正是因为闸把它们送去了 Ticketflow，而它们的取数与回写都在数据根。
// 源码归源码、数据归数据，两靶各判各的。
const 弱特征 = ['监制台', '排程台账', '白夜馆', '待拍板队列', '瞭望塔', '项管台账', '值守心跳', '工单池'];

// 规则④b·数据根特征：命中即判疑似「监制台」项目（D:/GitHub/AI-GameStudio）。
// 与弱特征同为名词形、同样要 ≥2 词，但靶子不同。两表有意重叠——
// 一张单同时提「排程台账」和「lib/pm/」是真的跨两仓，那种单该被强特征拦去 Ticketflow 后由人拆。
const 数据根特征 = ['排程台账', '项管台账', '待办-制作人议程', '待拍板队列', '白夜馆', '瞭望塔',
  '未读账本', '账本水位', '值守心跳', '坑档案', '决议史', '协议库', 'journal/', '呼叫/inbox'];

// 本项目名：写死的是**项目名**（语义锚），不是前缀——前缀一律从注册表推。
// 注册表改前缀、改路径都不影响这两行；改项目名才需要动。
const 本项目名 = 'Ticketflow';
const 数据根项目名 = 'AI-GameStudio';   // 08-27 改名：原名与程序同名、且比实际范围窄（它是整个工作室根）

// 规则⑦·禁写区（议程第 27 条）：数据根注册成项目之后，**活存储仍然禁止执行会话写**。
// 制作人拍板原话取向：「注册，但活存储设禁写区」。
// 理由不是怕写坏——数据根是 git 仓、每 10 分钟自动记账，写坏了有 undo；
// 真正补不回的是**竞态**：工单目录同时是状态机的活存储，runner 每 15 秒一拍在读写它，
// 执行会话同期写入会产生 git 也还原不了的状态错乱（一个被两边同时改的 fm，
// 回滚到哪一版都是错的）。所以这道闸拦的是「同时」，不是「写」。
const 禁写区 = ['监制台/待审', '监制台/待派', '监制台/待重派', '监制台/已排期', '监制台/在途',
  '监制台/初检', '监制台/核查', '监制台/仲裁', '监制台/完成', '监制台/归档', '监制台/待处理',
  '监制台/挂起', '监制台/废弃', '监制台/journal', '监制台/项管台账', '监制台/排程台账',
  '监制台/呼叫', '监制台/瞭望塔', '监制台/回执'];

// 规则⑦b·禁写区的语境判别（2026-08-28，总监自撞）
//
// 案源：给项管重开 draftguard 单，项管在正文里把三张截断标本的**路径**引作夹具
// （`D:/GitHub/AI-GameStudio/监制台/待审/TF-3.md`），闸按字面命中 `监制台/待审` 当场拒收，
// 号消耗零、盘未落，但那张单本身是对的——**引用一个目录当证据，和声明要写它，是两件事**。
//
// 这与议程第 38 条（H97 引擎门禁字面命中，TF-7/TF-8 两次误拦）是同一型病：
// 特征表按字面匹配、不看这个词出现在什么句子里。那条已修（词边界 + 否定语境），
// 本条是同一修法在另一道闸上的兑现——**一处病修完要回头看同族**，不然它换个地方再犯一次。
//
// 判别是**不对称**的，这是有意的：本闸是安全闸不是路由闸（拦的是并发写活存储，
// 那种错 git 也还原不回）。所以——
//   · 只读/引用/否定语境 → 豁免（读、查、见、位于、标本、夹具、禁碰…）
//   · 但同句里只要还有**明确的写动作**（写入/写进/落盘/新建/删除/移动/覆盖/追加/更新），
//     豁免立即作废。「读 X 并更新它」是写，不是读。
// 写动词一律取**复合词**，不收单字「写」「改」：「写着」「写死」「写明」「改写成」
// 说的是文本长什么样，不是要动谁——单字表会把说明性文字整片误判（这是弱特征表已立的判例）。
const 只读语境 = /(标本|夹具|样本|证据|位于|所在|参见|引用|取自|来自|读取|读|查阅|查|例如|现有|已有|案例|复现|禁碰|禁改|不碰|不改|不写|不动|勿动|别碰|不许写|不得写)/;
// 写动作：复合词为主，外加一个带否定前瞻的单字「写」。
// 前瞻里那几个字是「写」的**非动作义**：写着/写死/写明/写作/写法（说文本长什么样）、
// 写成（改写成…）、写区（名词）。不排它们，「验收方式字段写着自检」会被判成要写盘。
const 写动作 = /(写入|写进|写到|落盘|新建|删除|移动|覆盖|追加|更新|生成到|输出到|移入|挪进|归档到|写(?!着|死|明|作|法|成|区))/;

// 按句读切出命中所在的子句。**不用定长窗口**——议程第 38 条实测：TF-8 的
// 「不涉 enginectl / unity-test / 受控重建」里否定词离第三项 26 字，24 字窗口整个漏掉。
// **全角冒号不算界**：中文里它多半是「引出」而非「隔断」（「活标本：监制台/待审 里的…」，
// 定语在冒号左边）。把它算成界，等于把最相关的那半句切掉。
function 子句(文, 位置) {
  const 前 = 文.slice(0, 位置);
  const 界 = Math.max(前.lastIndexOf('。'), 前.lastIndexOf('；'), 前.lastIndexOf('!'),
    前.lastIndexOf('?'), 前.lastIndexOf('\n'), 前.lastIndexOf(';'));
  const 尾 = 文.slice(位置).search(/[。；\n!?]/);
  return 文.slice(界 + 1, 尾 < 0 ? 文.length : 位置 + 尾);
}

// 一个禁写区词在文中是否构成**真的写区声明**：只要有任一次出现是写语境，就算命中。
//
// **命中词本身必须先从子句里摘掉**再判语境——否则目录名自带的字会冒充语境词：
// `监制台/核查` 里的「查」正是只读表里的词，于是「本单要写 监制台/核查 下的文件」
// 被自己的靶子豁免掉了（本条落地时实测翻红，19 目录点名那条抓住的）。
// 中文子串匹配上，「词在文本里出现」和「词在说这件事」是两回事。
function 真写区声明(文, 词) {
  let p = -1;
  while ((p = 文.indexOf(词, p + 1)) >= 0) {
    const c = 子句(文, p).split(词).join(' ');   // 摘掉靶子本身，只看它周围的话
    if (写动作.test(c)) return true;             // 写动作压过一切（「读 X 并更新它」是写）
    if (!只读语境.test(c)) return true;           // 语境说不清就按写办（安全闸取保守边）
  }
  return false;
}

// 查落点({ 项目, 文本, cfg }) → { ok:true } | { ok:false, error, 疑似项目, 命中 }
//   项目 = 本单拟落的项目名（draftTicket 里的 opts.项目 或项目默认）
//   文本 = 需求原文 + 工单正文，拼一起看（错配特征两处都可能出现）
//   cfg  = studio.config.json 的内存形，只读 项目.注册
function 查落点({ 项目, 文本, cfg } = {}) {
  const t = 归一(文本);
  const 强命中 = 强特征.filter((w) => t.includes(w));
  const 反证命中 = TK反证.filter((w) => t.includes(w));
  const 弱命中 = 弱特征.filter((w) => t.includes(w));
  const 数据命中 = 数据根特征.filter((w) => t.includes(归一(w)));
  const { 前缀Of } = require('./brain');
  const 现名 = String(项目 || (cfg && cfg.项目 && cfg.项目.默认) || '（空）').trim();
  const 现前缀 = 前缀Of(cfg, 项目);

  // 规则⑦先判（议程第 27 条）：禁写区压过一切靶判。
  // 一张明写要动活存储的单，无论落到哪个项目都不该派——数据根注册与否都一样。
  // 摆在最前是因为它是**安全闸**，而下面几条是**路由闸**：路由错了返工一轮，
  // 活存储被并发写坏是 git 都还原不回的（回滚到哪一版都是错的）。
  // 语境判别见规则⑦b：字面出现 ≠ 写区声明。引作夹具/证据、或明写「禁碰」的，不算。
  const 禁命中 = 禁写区.filter((w) => 真写区声明(t, 归一(w)));
  if (禁命中.length) {
    return {
      ok: false,
      禁写区: true,
      // 疑似项目 补上（2026-08-28）：本分支原样不带这个字段，而 brain.js 的拦截留痕行
      // 打的是 `疑似 ${r.疑似项目}`——于是 journal 里躺着一行「疑似 undefined」。
      // 一条读不出信息的日志比没有日志更坏：它占着位置，让人以为这里已经有记录了。
      疑似项目: 数据根项目名,
      命中: 禁命中,
      error: [
        `写区触到监制台活存储，拒收：${禁命中.join('、')}`,
        '这些目录是状态机的活存储，runner 每拍都在读写；执行会话同期写入会产生 git 也还原不回的状态错乱。',
        `改法：这类活由总监手做，或把需求改写成「读它、把结论写进 ${数据根项目名} 的静态区（协议库/Docs/白夜馆）」再发。`,
      ].join(String.fromCharCode(10)),
    };
  }

  // 规则⑤·优先级固定：强特征 > TK 反证 > 弱特征/数据根特征。
  // 强特征是路径形、几乎不可能误判，命中即判 Ticketflow（反证不豁免）。
  // 两个名词形表都要 ≥2 词，且都受 TK 反证豁免。
  // 数据根排在弱特征之前判：两表重叠的词（排程台账/白夜馆/瞭望塔…）指的本就是数据根实体，
  // 08-26 装闸后 TK-193/TK-205 仍错配，正因为它们被送去了 Ticketflow。
  let 靶 = null; let 命中 = [];
  if (强命中.length) { 靶 = 本项目名; 命中 = 强命中; }
  else if (数据命中.length >= 2 && !反证命中.length) { 靶 = 数据根项目名; 命中 = 数据命中; }
  else if (弱命中.length >= 2 && !反证命中.length) { 靶 = 本项目名; 命中 = 弱命中; }
  if (!靶) return { ok: true };

  // 规则⑥·拒收条件：判为疑似某靶 **且** 落点没在那个靶。
  // 判疑似但项目填对了——那是正常的自维护单，照常放行。
  const 应前缀 = 前缀Of(cfg, 靶);
  if (现前缀 === 应前缀) return { ok: true };

  // 靶项目还没注册：**照拦不误**，只是改法换一句。
  // 曾经写成「未注册就放行」，被 draft-project-fit 的空配置用例当场抓住——那会让「配置缺一格」
  // 等于「整道闸哑掉」。而闸的本职是防止烧掉一轮够不着写区的执行会话：靶没注册，
  // 那张单落在原项目上照样跑不了，更该拦。拦得住 ≠ 说得出改法，两件事分开给。
  // （判注册要直接查注册表：前缀Of 对未注册项目回落成项目名本身，永远 truthy，拿它判会永远判成已注册。）
  const 已注册 = !!(cfg && cfg.项目 && cfg.项目.注册 && cfg.项目.注册[靶]);

  const 说明 = 靶 === 数据根项目名 ? '监制台运行数据根' : '监制台自身源码';
  // 报文三要素（供人一眼改正）：命中了什么 / 现在填的是什么 / 该怎么重发。
  const error = [
    `项目落点疑似错配：本单需求/正文命中 ${靶}（${说明}）的写区特征，落点却不在 ${靶}。`,
    `命中特征：${命中.join('、')}`,
    已注册
      ? `现填项目：${现名}（号段前缀 ${现前缀}）；应为 ${靶}（号段前缀 ${应前缀}）`
      : `现填项目：${现名}（号段前缀 ${现前缀}）；应为 ${靶}——**但 ${靶} 还没在 项目.注册 里立项**`,
    已注册
      ? `改法：派单时带「项目: ${靶}」重发；若本单确是 ${现名} 侧的活，把需求里的上述特征词改写成实际写区再发。`
      : `改法：先在 studio.config.json 的 项目.注册 里给 ${靶} 立项（路径+单号前缀），再带「项目: ${靶}」重发；`
        + `若本单确是 ${现名} 侧的活，把需求里的上述特征词改写成实际写区再发。`,
  ].join(String.fromCharCode(10));
  return { ok: false, error, 疑似项目: 靶, 命中, 靶未注册: !已注册 };
}

module.exports = { 查落点, 归一, 强特征, TK反证, 弱特征, 数据根特征, 禁写区, 本项目名, 数据根项目名 };
