// progress.js — 执行进度百分比（施工令-004 立结构；施工令-049 / H100 改口径）。
// 纯函数：无 IO、无全局态，输入一张单的现场快照，输出百分比 + 分段条 + 阶段如实命名。
// 服务端（/api/runner /api/agents）算好下发，前端只显示——口径唯一，可单测。
//
// 口径（施工令-049 定稿 · H108 改道，不许前端另立一套）：
//   阶段锚点  领单 5% ｜ 执行 5→60% ｜ 初检（QA）60→75% ｜ 核查（两检+深检）75→95% ｜ 落袋 100%
//   QA 关的单跳过初检段：执行 5→75%；「完成」定格 99%（出口驻留位，归档才 100%）
//   免检双钥匙单从执行直落完成（判官段显示为已过）；「保留」的例外在验收闸不在链条（H110）
//   阶段内插值 = **该阶段已耗时 ÷ 该阶段预期时长**（预算时间制），封顶该阶段上限——
//               超时不回退、不越级，停在上限并转警示态。
//   诚实纪律：永不显示 100% 直到真落袋；三级取数都拿不到时长的阶段停在锚点，编不出来的进度就不编。
//
// ---- H100（制作人 2026-08-12 21:13 裁决）：过程打点退役，进度按预算时间推算 ----
// 041 §四把百分比锁死在「会话打点」这唯一来源，代价是**判官阶段根本没有进度**：质检/初检/核查
// 从不打点，条子冻死在 60%，制作人直接点名「质检中看不到进度条闪烁」。本令反向收敛到时间单口径：
// 每个阶段各有预算时长，条子按已耗时推进，判官段从此有活的进度。
// 打点**不再参与进度计算**——解析器 解析打点() 保留，只剩一个消费者：pm/patrol 的「打点停滞」
// 看门狗拿它当活性信号（打过点又不动了 = 疑似卡死）。tail 原文照旧显示，纯诊断，不折算成任何百分比。
// 041 §四那道「同一张单两个百分比」的病也不会复发：现在全站只有时间这一把尺，
// 卡头百分比与计时行同源同分母，读出来必然一致。

// ---- H108 三大态状态机（2026-08-24）：阶段随目录改道 ----
// 审检链目录化：质检会话跑「初检」目录（原 质检 段更名 初检 60→75），两检初检+深检同驻「核查」
// 目录（原 待验收 里的 初检75-80/核查80-95 两小段并作 核查 75→95 一段），争议进「仲裁」（借位次显示）。
// 「完成」是在途大态出口驻留位（判官全过、等专项级验收）——**不算落袋**；「归档=落袋」才 100%。

// ---- 阶段预期时长：三级取数（施工令-049 要件②）----
//   ① 滚动均时：同职能×同阶段近 N 单实测中位（样本 ≥ 最少样本 才上台，见 滚动均时()）
//   ② 配置手配：studio.config.json · 阶段均时（缺省表见下）
//   ③ 执行段兜底：工单 fm.预计时间
// 缺省表**不给 执行 配值**：执行段该走它自己那张单的 预计时间（③ 比一刀切的职能均值贴单），
// 要一刀切的人自己往 阶段均时.执行 里填一个值即可（填了就按 ② 压过 ③，优先级不变）。
// 也**不给 定夺/完成 配值**：那两处是在等人落笔，给它们上预算时钟等于替人编一句
// 「你该多久签完」，属于编数据——它们如实停在锚点。
const 缺省阶段均时 = { 初检: 0.4, 核查: 0.5, 仲裁: 0.3 }; // 小时（H108：原 质检0.4 更名 初检；机判两检并入核查段）
const 最少样本 = 3;    // 一两张单的中位不叫均时，样本不足直接降级到 ②
const 样本上限h = 24;  // 超过一天的「阶段时长」多半是挂起/跨夜滞留，不是真干活时长，不进样本

// ---- 打点解析：已退出进度计算（H100），仅供 patrol 打点停滞看门狗做活性判据 ----
// 容错优先：任何解析异常都退化为「没有打点」，非法行一律忽略不炸。
function 解析打点(tail) {
  if (typeof tail !== 'string' || !tail) return null;
  const re = /\[\s*进度\s+(\d+)\s*\/\s*(\d+)(?:[^\]\n]*)\]/g;
  let m; let hit = null;
  while ((m = re.exec(tail)) !== null) {
    const k = Number(m[1]); const n = Number(m[2]);
    if (!Number.isFinite(k) || !Number.isFinite(n)) continue; // 非数字：忽略
    if (n <= 0 || k < 0 || k > n) continue;                   // n=0 / k>n：非法，忽略
    hit = { k, n };                                            // 取最后一个合法打点
  }
  return hit;
}

// ---- 阶段表：按 QA 开关裁段（段序 = 分段条的顺序，H108 目录化后的新裁法） ----
//   QA开：领单 5 ｜ 执行 5→60 ｜ 初检 60→75 ｜ 核查 75→95 ｜ 落袋 100
//   QA关：领单 5 ｜ 执行 5→75 ｜ 核查（简检）75→95 ｜ 落袋 100
// 原「你验收」段退役：H110 起「保留」的例外在验收闸（完成→归档 制作人亲验）而不在链条里——
// QA关的保留单同样走核查简检；免检双钥匙单从执行直落完成，判官段整段跳过（显示为已过）。
function 阶段表(opts) {
  const qaOn = !(opts && opts.qaOn === false);
  const segs = [{ 名: '领单', lo: 5, hi: 5 }];
  segs.push({ 名: '执行', lo: 5, hi: qaOn ? 60 : 75 });
  if (qaOn) segs.push({ 名: '初检', lo: 60, hi: 75 }); // H108：原 质检 段更名（质检会话驻初检目录）
  segs.push({ 名: '核查', lo: 75, hi: 95 }); // 两检初检+深检同驻核查目录，并作一段
  segs.push({ 名: '落袋', lo: 100, hi: 100 });
  return segs;
}

// 在跑会话 kind → 阶段名（判官阶段如实命名，绝不冒充「执行」）。
// H108：kind 质检（QA 复核）→ 初检段；kind 初检（两检机判格式）随深检并入核查段。
const KIND阶段 = { 执行: '执行', 质检: '初检', 初检: '核查', 代核: '核查', 核查: '核查', 代裁: '仲裁' };
const 判官阶段 = new Set(['初检', '核查', '仲裁', '定夺', '完成']);

// 显示名：一眼知道现在到底在干什么（超预期态自带盯守说明）
const 基名 = { 领单: '衔接中', 初检: '初检中 · QA复核', 核查: '核查中 · 深检',
  仲裁: '仲裁中', 定夺: '待处理 · 候分诊', 完成: '已完成 · 候验收', 落袋: '已落袋' };
function 显示名(阶段, 超时) {
  if (阶段 === '执行') return 超时 ? '执行超预期 · 软超时盯守中' : '执行中';
  const n = 基名[阶段] || 阶段 || '—';
  return 超时 ? n + ' · 超预期' : n;
}

// 无在跑会话时，按目录状态定位阶段（目录态是兜底，现场态优先）
function 状态阶段(state) {
  if (state === '在途') return '领单';       // 单已领、会话未起：衔接中，如实停在领单锚点
  if (state === '初检') return '初检';
  if (state === '核查') return '核查';
  if (state === '仲裁') return '仲裁';
  if (state === '待处理') return '定夺';     // H108：执行失败/待定夺并入待处理（总监分诊台，借判官段位次显示）
  if (state === '完成') return '完成';       // 出口驻留位：判官全过、等专项级验收——不是落袋
  if (state === '归档' || state === '废弃') return '落袋';
  return null;                               // 待审/待派/待重派/挂起：不在执行链条上，不编进度
}

/* ===================== 滚动均时（① 级取数）===================== */
// 表键：同职能×同阶段。职能缺失归「—」组——不跨职能借数，程序单的执行时长喂不了美术单。
const 均时键 = (职能, 阶段) => `${职能 || '—'}|${阶段}`;

// 阶段样本抽取（纯函数，入参是已解析的工单列表，零 IO）。
// 只从**有独立起止戳**的阶段取样，缺站不补造（同 pm/chain 的纪律）：
//   执行 = 领单时间 → 交付时间（这正是报表 实际h 那一列的分母，口径同源）
//   核查 = 初检.时间 → 核查/代核.时间（两检开的单才有；两检关时核查没有起点，不取）
// 质检 / 初检 没有独立完成戳（质检过关只改目录状态、覆盖 更新时间，历史查无实据），
// 所以它们**永远走 ② 配置表**——宁可用手配缺省值，也不拿「交付时间→初检时间」这种
// 含排队等待的跨段差冒充质检时长。
function 阶段样本(单表) {
  const out = [];
  for (const t of 单表 || []) {
    const fm = (t && t.fm) || {};
    const 职能 = fm.职能 || '—';
    const 加 = (阶段, a, b) => {
      const x = Date.parse(a || ''); const y = Date.parse(b || '');
      if (!Number.isFinite(x) || !Number.isFinite(y) || y <= x) return;
      out.push({ 职能, 阶段, 小时: (y - x) / 3600000, 时间: b });
    };
    加('执行', fm.领单时间, fm.交付时间);
    const 核 = fm.核查 || fm.代核;
    if (fm.初检 && 核) 加('核查', fm.初检.时间, 核.时间);
  }
  return out;
}

const 中位 = (arr) => {
  const a = [...arr].sort((x, y) => x - y);
  const m = a.length >> 1;
  return a.length % 2 ? a[m] : (a[m - 1] + a[m]) / 2;
};

/**
 * 近 N 单滚动中位表。
 * @param {Array<{职能:string,阶段:string,小时:number,时间:string}>} 样本
 * @param {{N?:number}} opts  N = 每组取最近几单（缺省 8）
 * @returns {Object<string,{小时:number,n:number}>}  键 = 均时键(职能,阶段)
 * 中位而非均值：一张跑飞的单（挂起过夜、卡在等实证）能把均值拉到天上去，中位不动摇。
 */
function 滚动均时(样本, opts) {
  const N = Math.max(1, Number((opts && opts.N) || 8));
  const g = new Map();
  for (const s of 样本 || []) {
    if (!s || !Number.isFinite(s.小时) || s.小时 <= 0 || s.小时 > 样本上限h) continue;
    const k = 均时键(s.职能, s.阶段);
    if (!g.has(k)) g.set(k, []);
    g.get(k).push(s);
  }
  const 表 = {};
  for (const [k, arr] of g) {
    arr.sort((a, b) => String(b.时间 || '').localeCompare(String(a.时间 || ''))); // 新单在前
    const 近 = arr.slice(0, N);
    if (近.length < 最少样本) continue; // 样本不足不上台：降级到 ② 配置表，不拿两张单当均时
    表[k] = { 小时: Math.round(中位(近.map((x) => x.小时)) * 1000) / 1000, n: 近.length };
  }
  return 表;
}

/**
 * 本阶段预期时长（三级取数）。返回 { ms, 来源, 样本数 }；ms=0 表示没有任何时长数据。
 * 来源取值：滚动均时 / 配置均时 / 工单预计 / 无
 */
function 阶段预期(阶段, i) {
  const 滚 = (i.均时 || {})[均时键(i.职能, 阶段)];
  const 命 = typeof 滚 === 'number' ? { 小时: 滚, n: 0 } : (滚 || null); // 表值容忍裸数字
  if (命 && Number.isFinite(命.小时) && 命.小时 > 0) {
    return { ms: 命.小时 * 3600000, 来源: '滚动均时', 样本数: Number(命.n) || 0 };
  }
  const 手配 = { ...缺省阶段均时, ...(i.阶段均时 || {}) };
  const h = parseFloat(手配[阶段]);
  if (Number.isFinite(h) && h > 0) return { ms: h * 3600000, 来源: '配置均时', 样本数: 0 };
  if (阶段 === '执行') {
    const est = parseFloat(i.预计时间);
    if (Number.isFinite(est) && est > 0) return { ms: est * 3600000, 来源: '工单预计', 样本数: 0 };
  }
  return { ms: 0, 来源: '无', 样本数: 0 };
}

/**
 * 计算一张单的执行进度。
 * @param {object} input
 *   state       工单目录状态（在途/初检/核查/仲裁/待处理/完成/归档…，H108 十二态）
 *   kind        在跑会话环节（执行/质检/初检/代核/代裁），无会话传 null
 *   QA          fm.QA（'关' 以外一律按开——与 lifecycle 的 fail-closed 同口径）
 *   验收方式     fm.验收方式（H108 起不再裁段——保留单的例外在验收闸；参数保留兼容旧调用方）
 *   职能         fm.职能（滚动均时按 职能×阶段 分组）
 *   预计时间     fm.预计时间（小时，字符串或数字）——执行段的第三级兜底
 *   阶段起时     本阶段起始 ISO（**只认在跑会话 startedAt**）；无则不插值，停锚点。
 *               没有会话就没有「这一阶段跑了多久」可言，拿领单时间顶上去等于给卡住的单编进度。
 *   均时         滚动均时表（见 滚动均时()），可缺
 *   阶段均时     配置手配表 cfg.阶段均时（小时），可缺
 *   初检         该单是否已过初检（fm.初检 存在即真）
 *   tail        活尾巴文本（仅诊断显示，H100 起不参与进度）
 *   now         当前时刻毫秒（测试可注入）
 * @returns {{百分比:number,阶段:string,阶段名:string,判官:boolean,超时:boolean,超期pct:number,
 *            段内:number,段:Array,预期分钟:?number,耗时分钟:?number,时长来源:string,样本数:number,
 *            来源:string,锚点:number}}
 */
function compute(input) {
  const i = input || {};
  const now = typeof i.now === 'number' ? i.now : Date.now();
  const qaOn = String(i.QA == null ? '开' : i.QA).trim() !== '关';
  const segs = 阶段表({ qaOn }); // H108：验收方式不再裁段（保留单照走核查，例外在验收闸）
  const 落袋了 = i.state === '归档' || i.state === '废弃'; // H108：归档=落袋；完成只是出口驻留位

  const 阶段 = 落袋了 ? '落袋'
    : (i.kind && KIND阶段[i.kind]) || 状态阶段(i.state);

  const 空 = { 超期pct: 0, 预期分钟: null, 耗时分钟: null, 时长来源: '无', 样本数: 0 };
  // 还没进链条（草稿/待投/池）：不编进度
  if (!阶段) {
    return { 百分比: 0, 阶段: '未领单', 阶段名: '未领单', 判官: false, 超时: false, 段内: 0, ...空,
      段: segs.map((s) => ({ 名: s.名, 态: 'todo' })), 来源: '锚点', 锚点: 0 };
  }
  if (阶段 === '落袋') {
    return { 百分比: 100, 阶段: '落袋', 阶段名: '已落袋', 判官: false, 超时: false, 段内: 1, ...空,
      段: segs.map((s) => ({ 名: s.名, 态: 'done' })), 来源: '锚点', 锚点: 100 };
  }
  if (阶段 === '完成') {
    // H108 出口驻留位：判官全过、停在验收闸前等专项级验收。诚实纪律：不落袋不 100%——
    // 定格 99，落袋段留 todo；不给它上预算时钟（等人签字的时长不该由机器编）。
    return { 百分比: 99, 阶段: '完成', 阶段名: 显示名('完成', false), 判官: true, 超时: false, 段内: 1, ...空,
      段: segs.map((s) => ({ 名: s.名, 态: s.名 === '落袋' ? 'todo' : 'done' })), 来源: '锚点', 锚点: 95 };
  }

  // 定夺（待处理）/仲裁在段序之外（分诊台/争议席）：借核查段位次显示
  const 位次名 = (阶段 === '定夺' || 阶段 === '仲裁') ? '核查' : 阶段;
  let idx = segs.findIndex((s) => s.名 === 位次名);
  if (idx < 0) idx = 1; // 兜底落在执行段（例如 QA 关的单意外报出质检会话）
  const seg = segs[idx];

  const 起 = i.阶段起时 ? Date.parse(i.阶段起时) : NaN;
  const 有起时 = Number.isFinite(起);
  const 耗时 = 有起时 ? Math.max(0, now - 起) : 0;
  const 预期 = 阶段预期(阶段, i);

  // 预算时间制（H100）：填充 = 已耗时 ÷ 预期时长。缺任一半（没会话起时 / 没时长数据）→ 停锚点。
  let 段内 = 0; let 来源 = '锚点';
  if (预期.ms > 0 && 有起时) { 段内 = 耗时 / 预期.ms; 来源 = '时间'; }
  const 超时 = 预期.ms > 0 && 有起时 && 耗时 > 预期.ms;
  const 超期pct = 超时 ? Math.round((耗时 / 预期.ms - 1) * 100) : 0;
  段内 = Math.max(0, Math.min(1, 段内));                   // 封顶该阶段上限：超时不回退、不越级

  let 百分比 = Math.round(seg.lo + (seg.hi - seg.lo) * 段内);
  if (!落袋了) 百分比 = Math.min(百分比, 99);              // 诚实纪律：不落袋永不 100%

  const 段 = segs.map((s, n) => ({
    名: s.名,
    态: n < idx ? 'done' : n === idx ? 'cur' : 'todo',
    ...(n === idx ? { 填充: 段内, ...(超时 ? { 超期pct } : {}) } : {}),
  }));

  return {
    百分比, 阶段, 阶段名: 显示名(阶段, 超时), 判官: 判官阶段.has(阶段), 超时, 超期pct, 段内, 段,
    预期分钟: 预期.ms ? Math.round(预期.ms / 60000) : null,
    耗时分钟: 有起时 ? Math.round(耗时 / 60000) : null,
    // 来源/锚点/时长来源随行：消费端要说得出这个数是怎么来的——「62% 是按 5 单滚动均时推的」
    // 和「62% 是按手配缺省表推的」，制作人的信任度天差地别（041 §四立的规矩，049 照旧）。
    时长来源: 预期.来源, 样本数: 预期.样本数, 来源, 锚点: seg.lo,
  };
}

