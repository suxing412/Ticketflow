// ── 规则⑦b·语境判别（2026-08-28，总监自撞）────────────────────────────
//
// 案源：给项管重开 draftguard 单，项管在正文里把三张截断标本的**路径**引作夹具
// （`…/监制台/待审/TF-3.md`），闸按字面命中当场拒收。那张单本身没问题——
// **引用一个目录当证据，和声明要写它，是两件事**。
// 与议程第 38 条（引擎门禁字面命中）同型：一处病修完要回头看同族，不然它换个地方再犯。
//
// 判别有意做成**不对称**的：本闸是安全闸（拦并发写活存储，那种错 git 还原不回），
// 所以只读/引用/否定语境豁免，但同句里只要还有明确写动作，豁免立刻作废。
t('语境判别：引作夹具/证据的路径不算写区声明', () => {
  const 该放行 = [
    '三张截断标本位于 D:/GitHub/AI-GameStudio/监制台/待审/TF-3.md，可直接拿来当判据夹具',
    '活标本：监制台/待审 里的 TK-213 验收方式字段写着「自检」',
    '写区仅 apps/studio/lib/pm，禁碰 监制台/待审 与 监制台/回执',
    '读取 监制台/排程台账 出一份只读统计，产物落 Docs',
  ];
  for (const 文 of 该放行) {
    const r = 查('AI-GameStudio', 文);
    assert.notEqual(r.禁写区, true, '引用/否定语境被误判成写区声明：' + 文.slice(0, 40));
  }
});

t('语境判别不许把闸放软：写语境照拦，写动作压过只读词', () => {
  const 该拦 = [
    ['明写写进', '把结论写进 监制台/待审 目录'],
    ['新建落盘', '新建工单落到 监制台/待派 下'],
    ['读+更新混合', '读取 监制台/待派 下的单并更新其 fm 字段'],   // 「读」在场，但写动作压过它
    ['裸提无语境', '监制台/journal 相关处理'],                    // 说不清就按写办：安全闸取保守边
  ];
  for (const [名, 文] of 该拦) {
    const r = 查('AI-GameStudio', 文);
    assert.equal(r.禁写区, true, `${名} 应被拦下：${文}`);
  }
});

// 下面两条是**为了把两处防护分开钉住**才写的。
// 语境判别里有两道各自独立的机制：①判语境前先摘掉命中词本身 ②写动作表收单字「写」。
// 上面那批用例里两者互为冗余——任拆一个另一个都兜得住，于是变异测试两次都不红，
// 判据看着全绿却**一处也没钉住**。冗余是好事，判据分不出冗余不是。
t('摘词机制单独钉住：目录名自带的只读字不许冒充语境（监制台/核查 的「查」）', () => {
  const r = 查('AI-GameStudio', '监制台/核查 目录的批量整理');
  assert.equal(r.禁写区, true,
    '不摘掉命中词本身，「核查」里的「查」会命中只读表，把靶子自己豁免掉');
});

t('单字写机制单独钉住：句中另有只读词时，「要写」仍要判成写', () => {
  const r = 查('AI-GameStudio', '参见附件，本单要写 监制台/待派 下的文件');
  assert.equal(r.禁写区, true,
    '「参见」是真的只读词且不在命中词内，此时只有写动作表里的单字「写」能把它压回去');
});

t('禁写区拦截要报得出疑似项目（journal 曾打「疑似 undefined」）', () => {
  const r = 查('TK', '把结论写进 监制台/待派');
  assert.equal(r.禁写区, true);
  assert.equal(r.疑似项目, 'AI-GameStudio',
    '本分支原样不带 疑似项目，而 brain.js 拦截留痕打的是 `疑似 ${r.疑似项目}`——'
    + '于是 journal 里躺着一行「疑似 undefined」，占着位置却读不出信息');
});

