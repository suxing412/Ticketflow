t('靶项目未注册：照拦不误，只是改法多一步「先立项」', () => {
  // 本格是回归闸。曾经把这里写成「未注册就放行」，被 draft-project-fit 的空配置用例当场抓住——
  // 那会让「配置缺一格」等于「整道闸哑掉」。靶没注册，单落在原项目上照样够不着写区，更该拦。
  const 无监制台 = { 项目: { 默认: 'TK', 注册: {
    TK: { 单号前缀: 'TK' }, Ticketflow: { 单号前缀: 'TF' },
  } } };
  const r = 落点.查落点({ 项目: 'TK', 文本: '对齐项管台账与排程台账的孤粒', cfg: 无监制台 });
  assert.equal(r.ok, false, '未注册照样拦——拦得住与说得出改法是两件事');
  assert.equal(r.疑似项目, 'AI-GameStudio');
  assert.equal(r.靶未注册, true, '要标明是「靶没立项」而不是「填错了项目」');
  assert.match(r.error, /还没在 项目\.注册 里立项/, '改法里得说清先立项这一步');

  // 空配置（连注册表都没有）同样拦得住——这正是旧用例传 cfg:{} 的那条路
  const r2 = 落点.查落点({ 项目: 'TK', 文本: '对齐项管台账与排程台账的孤粒', cfg: {} });
  assert.equal(r2.ok, false, '空配置不许让闸哑掉');
});

