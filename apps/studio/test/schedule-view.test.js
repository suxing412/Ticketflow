// ================= 消费④ 项目内队列页（施工令-042 §一）=================
// 被测四面：分组 / 依赖置灰判定 / 摘要统计 / 项目过滤。逐面单列，不合并成循环——
// 挂了的时候要看得出是「哪一面」错了，而不是「第几轮」错了（同本文件五态用例的理由）。
const 批 = (r, 名) => (r.批们 || []).find((b) => b.批 === 名);

t('队列页 · 分组：按 批→序 成块且不重排，全量五态都在场（终态是「还剩几件」的分母）', () => {
  const r = V.队列页([
    粒('完成', { 粒ID: 'a', 批: '批B', 序: 1, 题: 'B一' }),
    粒('计划', { 粒ID: 'b', 批: '批B', 序: 2, 题: 'B二' }),
    粒('计划', { 粒ID: 'c', 批: '批C', 序: 1, 题: 'C一' }),
    粒('撤销', { 粒ID: 'd', 批: '批C', 序: 2, 题: 'C二' }),
  ]);
  assert.deepEqual(r.批们.map((b) => b.批), ['批B', '批C'], '批的出场序＝入参序（排序口径唯一在 040，此处不重排）');
  assert.deepEqual(批(r, '批B').粒.map((c) => c.题), ['B一', 'B二']);
  assert.deepEqual(批(r, '批B').计数, { 总: 2, 未完: 1, 完: 1 }, '已完成的粒照样在场——不然「这批还剩几件」没有分母');
  assert.deepEqual(批(r, '批C').计数, { 总: 2, 未完: 1, 完: 1 }, '撤销＝已了结，计入「完」不计入「未完」');
  assert.equal(r.空, false);
});

