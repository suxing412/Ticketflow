// estimate.test.js — 估时自校准纯函数（H101 · 施工令-050）：
// 比样本抽取 / 滚动中位比 / 样本不足回退全局 / 系数夹逼 / 粒度取整 / 无 token 计量只校时间 /
// 无基准不代填 / 滚动窗只认近 N 单 / 提示词块的纪律文本。
//
// 病灶（H101 案源）：切单起草时 预计时间/预计token 是模型现拍的，跑完没人回头对，
// 报表 总览.预估偏差pct 早把这条缝晾着（>100=实际超预计）却只进报表不回流估值——
// 同一种偏差每张单重犯一次。本套件锁的是那条回路的算法端：给定历史，系数必须是这个数。
const assert = require('node:assert');
const est = require('../lib/pm/estimate');

let passed = 0; const t = (n, f) => { f(); passed++; console.log('  ✓ ' + n); };
console.log('estimate 估时自校准测试（施工令-050 · H101 章程「估时校准步」）');

const T0 = Date.parse('2026-08-10T00:00:00.000Z');
// 造一张完结单：h=实际耗时小时数，预计=预计时间，估tok/实tok=token 两端，序=新旧排序用
const 单 = (o = {}) => {
  const 起 = T0 + (o.序 || 0) * 86400000;
  return {
    id: o.id || 'TK-x',
    fm: {
      职能: o.职能 || '程序', 单型: o.单型 || '实现单',
      预计时间: String(o.预计 === undefined ? 0.5 : o.预计),
      预计token: String(o.估tok === undefined ? 50000 : o.估tok),
      领单时间: new Date(起).toISOString(),
      交付时间: new Date(起 + (o.h === undefined ? 1 : o.h) * 3600000).toISOString(),
    },
    实耗token: o.实tok === undefined ? 0 : o.实tok,
  };
};
const 表of = (单表, o) => est.校准表(est.比样本(单表, o), o);

t('比样本：实际耗时取 领单→交付（口径同报表 实际h），token 取回灌实耗', () => {
  const s = est.比样本([单({ h: 1, 预计: 0.5, 估tok: 50000, 实tok: 70000 })]);
  assert.equal(s.时间.length, 1);
  assert.equal(s.时间[0].比, 2, '1h 实际 ÷ 0.5h 预计 = 2');
  assert.equal(s.时间[0].职能 + '×' + s.时间[0].单型, '程序×实现单');
  assert.equal(s.token.length, 1);
  assert.equal(s.token[0].比, 1.4, '7 万实耗 ÷ 5 万预计 = 1.4');
});

t('比样本剔样：跨夜滞留（>24h）不进时间样本，缺预计/缺实耗不进对应维', () => {
  const s = est.比样本([
    单({ h: 30, 预计: 0.5 }),              // 挂起过夜：不是真干活时长
    单({ h: 1, 预计: 0 }),                 // 没预计：算不出比
    单({ h: 0, 预计: 0.5 }),               // 交付=领单：零耗时不成样本
    单({ h: 1, 预计: 0.5, 实tok: 0 }),      // 无 token 计量（codex 等不计量池）
  ]);
  assert.equal(s.时间.length, 1, '只有最后一张进时间样本');
  assert.equal(s.token.length, 0, '四张都进不了 token 维');
});

t('正常校准：同组近 N 单中位比 → 校后估值（时间与 token 各走各的系数）', () => {
  const 表 = 表of([
    单({ h: 1, 预计: 0.5, 实tok: 70000 }),   // 时间比 2 · token 比 1.4
    单({ h: 1, 预计: 0.5, 实tok: 70000, 序: 1 }),
    单({ h: 1, 预计: 0.5, 实tok: 70000, 序: 2 }),
  ]);
  assert.equal(表.时间.组[est.分组键('程序', '实现单')].系数, 2);
  assert.equal(表.时间.组[est.分组键('程序', '实现单')].样本数, 3);
  assert.equal(表.token.组[est.分组键('程序', '实现单')].系数, 1.4);
  const r = est.校准({ 表, 职能: '程序', 单型: '实现单', 预计时间: '0.5', 预计token: '50000' });
  assert.equal(r.预计时间, 1, '0.5 × 2 = 1.0h');
  assert.equal(r.预计token, 70000, '5 万 × 1.4 = 7 万');
  assert.equal(r.记录.时间.来源, '同组中位比');
  assert.deepEqual(r.记录.时间, { 校前: 0.5, 校后: 1, 系数: 2, 样本数: 3, 来源: '同组中位比' });
  assert.equal(r.记录.token.校前 + '→' + r.记录.token.校后, '50000→70000');
});

t('中位而非均值：一张跑飞的单拉不动系数', () => {
  const 表 = 表of([
    单({ h: 0.5, 预计: 0.5 }), 单({ h: 0.5, 预计: 0.5, 序: 1 }),
    单({ h: 0.5, 预计: 0.5, 序: 2 }), 单({ h: 20, 预计: 0.5, 序: 3 }), // 比 40 的离群单
  ]);
  assert.equal(表.时间.组[est.分组键('程序', '实现单')].系数, 1, '中位仍是 1（均值会被拉到 10 以上）');
});

t('样本不足回退全局：组内 <3 用全局中位比，全局也不足则不校准', () => {
  const 历史 = [
    单({ h: 1, 预计: 0.5 }), 单({ h: 1, 预计: 0.5, 序: 1 }), 单({ h: 1, 预计: 0.5, 序: 2 }), // 程序×实现单 ×2
    单({ h: 1, 预计: 0.5, 职能: '美术', 单型: '装配单', 序: 3 }),                            // 美术×装配单 只 1 张
  ];
  const 表 = 表of(历史);
  assert.ok(!表.时间.组[est.分组键('美术', '装配单')], '1 张不上台');
  const r = est.校准({ 表, 职能: '美术', 单型: '装配单', 预计时间: '0.5', 预计token: '50000' });
  assert.equal(r.记录.时间.来源, '全局中位比');
  assert.equal(r.记录.时间.样本数, 4, '全局吃全部四张');
  assert.equal(r.预计时间, 1);
  // 全局也不足（<3）：系数 1，估值原样不动——不拿一两张单当偏差
  const 瘦 = 表of([单({ h: 1, 预计: 0.5 }), 单({ h: 1, 预计: 0.5, 序: 1 })]);
  const r2 = est.校准({ 表: 瘦, 职能: '程序', 单型: '实现单', 预计时间: '0.5', 预计token: '50000' });
  assert.deepEqual(r2.记录.时间, { 校前: 0.5, 校后: 0.5, 系数: 1, 样本数: 2, 来源: '无样本' });
  assert.equal(r2.预计时间, 0.5);
  assert.equal(r2.预计token, 50000);
});

t('系数夹逼 [0.5, 3.0]：历史再离谱也不许把估值放飞或压穿', () => {
  const 高 = 表of([单({ h: 5, 预计: 0.5 }), 单({ h: 5, 预计: 0.5, 序: 1 }), 单({ h: 5, 预计: 0.5, 序: 2 })]); // 比 10
  assert.equal(高.时间.组[est.分组键('程序', '实现单')].系数, 3, '10 → 夹到上限 3');
  assert.equal(est.校准({ 表: 高, 职能: '程序', 单型: '实现单', 预计时间: '1' }).预计时间, 3);
  const 低 = 表of([单({ h: 0.1, 预计: 4 }), 单({ h: 0.1, 预计: 4, 序: 1 }), 单({ h: 0.1, 预计: 4, 序: 2 })]); // 比 0.025
  assert.equal(低.时间.组[est.分组键('程序', '实现单')].系数, 0.5, '0.025 → 夹到下限 0.5');
  assert.equal(est.校准({ 表: 低, 职能: '程序', 单型: '实现单', 预计时间: '2' }).预计时间, 1);
});

t('粒度取整：0.25h / 万 token 就近落格，且永不为 0（至少一格）', () => {
  assert.equal(est.取整(0.6, 0.25), 0.5, '0.6 → 0.5（就近落格）');
  assert.equal(est.取整(0.63, 0.25), 0.75);
  assert.equal(est.取整(0.01, 0.25), 0.25, '压到零头也保一格');
  assert.equal(est.取整(74000, 10000), 70000);
  assert.equal(est.取整(3, 10000), 10000);
  // 端到端：0.5h × 1.2 = 0.6 → 0.5h；5 万 × 0.6 = 3 万
  const 表 = 表of([
    单({ h: 0.6, 预计: 0.5, 实tok: 30000 }), 单({ h: 0.6, 预计: 0.5, 实tok: 30000, 序: 1 }),
    单({ h: 0.6, 预计: 0.5, 实tok: 30000, 序: 2 }),
  ]);
  const r = est.校准({ 表, 职能: '程序', 单型: '实现单', 预计时间: '0.5', 预计token: '50000' });
  assert.equal(r.预计时间, 0.5, '×1.2 后仍落回 0.5 格');
  assert.equal(r.预计token, 30000);
  assert.equal(r.记录.时间.系数, 1.2, '系数如实记 1.2——校后没动是取整所致，不是没校');
});

t('无 token 计量（codex 等不计量池）：只校时间，token 维如实记「无样本」', () => {
  const 表 = 表of([
    单({ h: 1, 预计: 0.5 }), 单({ h: 1, 预计: 0.5, 序: 1 }), 单({ h: 1, 预计: 0.5, 序: 2 }), // 实耗token 全 0
  ]);
  assert.equal(表.token.全局.不足, true);
  assert.deepEqual(Object.keys(表.token.组), [], 'token 维一个分组都上不了台');
  const r = est.校准({ 表, 职能: '程序', 单型: '实现单', 预计时间: '0.5', 预计token: '50000' });
  assert.equal(r.预计时间, 1, '时间照校');
  assert.equal(r.预计token, 50000, 'token 原样——不臆造数字');
  assert.equal(r.记录.token.来源, '无样本');
});

t('无基准：模型没填估值 → 该维原样返回，校准不替它编一个', () => {
  const 表 = 表of([单({ h: 1, 预计: 0.5, 实tok: 70000 }), 单({ h: 1, 预计: 0.5, 实tok: 70000, 序: 1 }),
    单({ h: 1, 预计: 0.5, 实tok: 70000, 序: 2 })]);
  const r = est.校准({ 表, 职能: '程序', 单型: '实现单', 预计时间: '', 预计token: undefined });
  assert.equal(r.预计时间, '', '空值原样退回（落 fm 前由白名单缺省值兜底）');
  assert.equal(r.预计token, undefined);
  assert.equal(r.记录.时间.来源, '无基准');
  assert.equal(r.记录.时间.校前, null);
});

t('滚动窗：只认近 N 单——陈年高偏差滚出窗外，系数跟着近况走', () => {
  const 历史 = [];
  for (let i = 0; i < 5; i++) 历史.push(单({ h: 1.5, 预计: 0.5, 序: i }));       // 陈年五单：比 3
  for (let i = 5; i < 9; i++) 历史.push(单({ h: 0.5, 预计: 0.5, 序: i }));       // 近况：比 1 ×4
  for (let i = 9; i < 13; i++) 历史.push(单({ h: 1, 预计: 0.5, 序: i }));        // 近况：比 2 ×4
  const g = 表of(历史).时间.组[est.分组键('程序', '实现单')];
  assert.equal(g.样本数, 8, '近 8 单封顶');
  assert.equal(g.系数, 1.5, '窗内 [1,1,1,1,2,2,2,2] 中位 1.5——陈年那批 3 已滚出窗');
  // 窗口可调：放宽到 13 就把陈年那批吃回来，中位抬到 2
  assert.equal(表of(历史, { 近N: 13 }).时间.组[est.分组键('程序', '实现单')].系数, 2);
});

t('分组不串味：不同职能×单型各算各的，绝不跨组借数', () => {
  const 表 = 表of([
    单({ h: 1, 预计: 0.5 }), 单({ h: 1, 预计: 0.5, 序: 1 }), 单({ h: 1, 预计: 0.5, 序: 2 }),                        // 程序×实现单 ×2
    单({ h: 0.25, 预计: 0.5, 职能: '美术', 单型: '装配单', 序: 3 }),
    单({ h: 0.25, 预计: 0.5, 职能: '美术', 单型: '装配单', 序: 4 }),
    单({ h: 0.25, 预计: 0.5, 职能: '美术', 单型: '装配单', 序: 5 }),                                                // 美术×装配单 ×0.5
  ]);
  assert.equal(表.时间.组[est.分组键('程序', '实现单')].系数, 2);
  assert.equal(表.时间.组[est.分组键('美术', '装配单')].系数, 0.5);
  assert.equal(est.系数查(表, '程序', '实现单', '时间').来源, '同组中位比');
  assert.equal(est.系数查(表, '策划', '调研单', '时间').来源, '全局中位比', '没这一组 → 全局');
});

t('落痕：记录一行说得出「校前→校后、系数、样本数、来源」（晨报按它对账）', () => {
  const 表 = 表of([单({ h: 1, 预计: 0.5, 实tok: 70000 }), 单({ h: 1, 预计: 0.5, 实tok: 70000, 序: 1 }),
    单({ h: 1, 预计: 0.5, 实tok: 70000, 序: 2 })]);
  const 行 = est.记录一行(est.校准({ 表, 职能: '程序', 单型: '实现单', 预计时间: '0.5', 预计token: '50000' }).记录);
  assert.match(行, /程序×实现单/);
  assert.match(行, /时间 0\.5→1（×2，同组中位比 3 样本）/);
  assert.match(行, /token 50000→70000/);
  assert.match(est.记录一行({ 职能: '程序', 单型: '实现单', 时间: { 校前: 1, 校后: 1, 系数: 1, 样本数: 1, 来源: '无样本' } }),
    /时间 1 不动（无样本）/);
});

t('提示词块：纪律文本 + 系数格；无表时退化为「无样本原样填」版', () => {
  const 表 = 表of([单({ h: 1, 预计: 0.5, 实tok: 70000 }), 单({ h: 1, 预计: 0.5, 实tok: 70000, 序: 1 }),
    单({ h: 1, 预计: 0.5, 实tok: 70000, 序: 2 })]);
  const s = est.提示词块(表);
  assert.match(s, /估时校准表/);
  assert.match(s, /不得自由拍值/);
  assert.match(s, /机器兜底/, '自律那一半必须点明机器会复核改写');
  assert.match(s, /程序×实现单：×2（3 样本）/);
  assert.match(s, /【token】全局系数 ×1\.4/);
  assert.match(s, /系数夹 \[0\.5, 3\]/);
  const 空 = est.提示词块(null);
  assert.match(空, /无历史可校/);
  assert.match(空, /无样本，未校准/);
});

t('容错：空输入/脏样本不炸（取数失败时整条链降级到不校准，不许抛）', () => {
  assert.deepEqual(est.比样本(null), { 时间: [], token: [] });
  assert.deepEqual(est.比样本([null, {}, { fm: null }]), { 时间: [], token: [] });
  const 表 = est.校准表(null);
  assert.equal(表.时间.全局.不足, true);
  const r = est.校准({ 表, 职能: '程序', 单型: '实现单', 预计时间: '0.5', 预计token: '50000' });
  assert.equal(r.预计时间, 0.5);
  assert.equal(est.校准({}).记录.时间.来源, '无基准');
  assert.equal(est.系数查(null, '程序', '实现单', '时间').系数, 1);
});

